  IF (LDATA_HC_ROOF) THEN
    PHC_ROOF=XPAR_HC_ROOF
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PHC_ROOF=PHC_ROOF)
  ELSE
    IF ( SIZE(PHC_ROOF,2) > SIZE(XDATA_HC_ROOF,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (1)')
    DO JLAYER=1,SIZE(PHC_ROOF,2)
      CALL AV_PGD (PHC_ROOF(:,JLAYER), PCOVER, XDATA_HC_ROOF (:,JLAYER),'BLD','INV')
    ENDDO
  ENDIF  
ENDIF
!
!      TC_ROOF
!      ----------
IF (PRESENT(PTC_ROOF)) THEN 
  IF (LDATA_TC_ROOF) THEN
    PTC_ROOF=XPAR_TC_ROOF
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PTC_ROOF=PTC_ROOF)
  ELSE
    IF ( SIZE(PTC_ROOF,2) > SIZE(XDATA_TC_ROOF,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (2)')
    DO JLAYER=1,SIZE(PTC_ROOF,2)
      CALL AV_PGD (PTC_ROOF(:,JLAYER)    ,PCOVER ,XDATA_TC_ROOF    (:,JLAYER),'BLD','ARI')
    END DO
  ENDIF  
ENDIF
