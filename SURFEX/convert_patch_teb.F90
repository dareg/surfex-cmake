!      D_ROOF
!      ----------
IF (PRESENT(PD_ROOF)) THEN 
  IF (LDATA_D_ROOF) THEN
    PD_ROOF=XPAR_D_ROOF
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PD_ROOF=PD_ROOF)
  ELSE
  IF ( SIZE(PD_ROOF,2) > SIZE(XDATA_D_ROOF,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (3)')
  DO JLAYER=1,SIZE(PD_ROOF,2)
    CALL AV_PGD (PD_ROOF (:,JLAYER)    ,PCOVER ,XDATA_D_ROOF     (:,JLAYER),'BLD','ARI')
  END DO    
  ENDIF  
ENDIF
!
!      ALB_ROAD
!      ----------
IF (PRESENT(PALB_ROAD)) THEN 
  IF (LDATA_ALB_ROAD) THEN
    PALB_ROAD=XPAR_ALB_ROAD
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PALB_ROAD=PALB_ROAD)
  ELSE
    CALL AV_PGD (PALB_ROAD ,PCOVER ,XDATA_ALB_ROAD (:),'STR','ARI')  
  ENDIF  
ENDIF
!
!      EMIS_ROAD
!      ----------
IF (PRESENT(PEMIS_ROAD)) THEN 
  IF (LDATA_EMIS_ROAD) THEN
    PEMIS_ROAD=XPAR_EMIS_ROAD
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PEMIS_ROAD=PEMIS_ROAD)
  ELSE
    CALL AV_PGD (PEMIS_ROAD ,PCOVER ,XDATA_EMIS_ROAD (:),'STR','ARI')  
  ENDIF  
ENDIF
!
!      HC_ROAD
!      ----------
IF (PRESENT(PHC_ROAD)) THEN 
  IF (LDATA_HC_ROAD) THEN
    PHC_ROAD=XPAR_HC_ROAD
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PHC_ROAD=PHC_ROAD)
  ELSE
    IF ( SIZE(PHC_ROAD,2) > SIZE(XDATA_HC_ROAD,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (4)')
    DO JLAYER=1,SIZE(PHC_ROAD,2)
      CALL AV_PGD (PHC_ROAD(:,JLAYER)    ,PCOVER ,XDATA_HC_ROAD    (:,JLAYER),'STR','INV')
    END DO    
  ENDIF  
ENDIF
!
!      TC_ROAD
!      ----------
IF (PRESENT(PTC_ROAD)) THEN
  IF (LDATA_TC_ROAD) THEN
    PTC_ROAD=XPAR_TC_ROAD
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PTC_ROAD=PTC_ROAD)
  ELSE
    IF ( SIZE(PTC_ROAD,2) > SIZE(XDATA_TC_ROAD,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (5)')
    DO JLAYER=1,SIZE(PTC_ROAD,2)
      CALL AV_PGD (PTC_ROAD(:,JLAYER)    ,PCOVER ,XDATA_TC_ROAD    (:,JLAYER),'STR','ARI')
    END DO
  ENDIF  
ENDIF
!
!      D_ROAD
!      ----------
IF (PRESENT(PD_ROAD)) THEN 
  IF (LDATA_D_ROAD) THEN
    PD_ROAD=XPAR_D_ROAD
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PD_ROAD=PD_ROAD)
  ELSE
    IF ( SIZE(PD_ROAD,2) > SIZE(XDATA_D_ROAD,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (6)')
    DO JLAYER=1,SIZE(PD_ROAD,2)
      CALL AV_PGD (PD_ROAD (:,JLAYER)    ,PCOVER ,XDATA_D_ROAD     (:,JLAYER),'STR','ARI')
    END DO
  ENDIF  
ENDIF
!
!      ALB_WALL
!      ----------
IF (PRESENT(PALB_WALL)) THEN
  IF (LDATA_ALB_WALL) THEN
    PALB_WALL=XPAR_ALB_WALL
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PALB_WALL=PALB_WALL)
  ELSE
    CALL AV_PGD (PALB_WALL ,PCOVER ,XDATA_ALB_WALL (:),'BLD','ARI')  
  ENDIF  
ENDIF
!
!      EMIS_WALL
!      ----------
IF (PRESENT(PEMIS_WALL)) THEN
  IF (LDATA_EMIS_WALL) THEN
    PEMIS_WALL=XPAR_EMIS_WALL
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PEMIS_WALL=PEMIS_WALL)
  ELSE
    CALL AV_PGD (PEMIS_WALL ,PCOVER ,XDATA_EMIS_WALL (:),'BLD','ARI')  
  ENDIF  
ENDIF
!
!      HC_WALL
!      ----------
IF (PRESENT(PHC_WALL)) THEN
  IF (LDATA_HC_WALL) THEN
    PHC_WALL=XPAR_HC_WALL
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PHC_WALL=PHC_WALL)
  ELSE
    IF ( SIZE(PHC_WALL,2) > SIZE(XDATA_HC_WALL,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (7)')
    DO JLAYER=1,SIZE(PHC_WALL,2)
      CALL AV_PGD (PHC_WALL(:,JLAYER)    ,PCOVER ,XDATA_HC_WALL    (:,JLAYER),'BLD','INV')
    END DO
  ENDIF  
ENDIF
!
!      TC_WALL
!      ----------
IF (PRESENT(PTC_WALL)) THEN
  IF (LDATA_TC_WALL) THEN
    PTC_WALL=XPAR_TC_WALL 
  ELSEIF (LDATA_URBTYPE) THEN
    CALL INI_DATA_PARAM(XPAR_URBTYPE,PTC_WALL=PTC_WALL)
  ELSE
    IF ( SIZE(PTC_WALL,2) > SIZE(XDATA_TC_WALL,2) ) CALL ABOR1_SFX('CONVERT_PATCH_TEB: (8)')
    DO JLAYER=1,SIZE(PTC_WALL,2)
      CALL AV_PGD (PTC_WALL(:,JLAYER)    ,PCOVER ,XDATA_TC_WALL    (:,JLAYER),'BLD','ARI')
    END DO
  ENDIF  
ENDIF
!
!      D_WALL
!      ----------
