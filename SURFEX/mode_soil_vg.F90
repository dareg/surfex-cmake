   FUNCTION WWILT_VG_2D(PWSAT,PALPHA,PN,PM,PWR,HPEDOTF)
   USE MODD_SURF_PAR,   ONLY : XUNDEF
   USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
   USE PARKIND1  ,ONLY : JPRB
   IMPLICIT NONE
   REAL, DIMENSION(:,:), INTENT(IN)     :: PWSAT,PALPHA,PN,PM,PWR
   CHARACTER(LEN=4),     INTENT(IN)     :: HPEDOTF
   REAL, DIMENSION(SIZE(PWSAT,1),SIZE(PWSAT,2)) :: WWILT_VG_2D
   REAL(KIND=JPRB) :: ZHOOK_HANDLE
   !
   ! Wilting point is calculated as the water content at a tension of 150m (15 bars)
   !
   IF (LHOOK) CALL DR_HOOK('MODE_SOIL_VG:WWILT_VG_2D',0,ZHOOK_HANDLE)
   SELECT CASE (HPEDOTF)
          CASE ('CP88')
               WHERE(PWSAT/=XUNDEF)
                    WWILT_VG_2D = PWR+(PWSAT-PWR)*(1.0/(1.0+(PALPHA*150.)**PN))**PM
               END WHERE
          CASE ('WO99')
               WHERE(PWSAT/=XUNDEF)
                    WWILT_VG_2D = PWSAT*(1.0/(1.0+(PALPHA*150.)**PN))**PM
               END WHERE
   END SELECT
   !                 
   WHERE(PWSAT==XUNDEF)
     WWILT_VG_2D = XUNDEF
   END WHERE
   IF (LHOOK) CALL DR_HOOK('MODE_SOIL_VG:WWILT_VG_2D',1,ZHOOK_HANDLE)
   !
   END FUNCTION WWILT_VG_2D
