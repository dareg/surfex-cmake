   FUNCTION WSAT_VG_2D(PCLAY,PSAND,PMO,PDENS,PTOPSOIL,HPEDOTF)
   USE MODD_SURF_PAR,   ONLY : XUNDEF
   USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
   USE PARKIND1  ,ONLY : JPRB
   IMPLICIT NONE
   REAL, DIMENSION(:,:), INTENT(IN)     :: PCLAY,PSAND,PMO,PDENS,PTOPSOIL
   CHARACTER(LEN=4),     INTENT(IN)     :: HPEDOTF
   REAL, DIMENSION(SIZE(PCLAY,1),SIZE(PCLAY,2)) :: ZSILT
   REAL, DIMENSION(SIZE(PCLAY,1),SIZE(PCLAY,2)) :: WSAT_VG_2D
   REAL(KIND=JPRB) :: ZHOOK_HANDLE
   !
   IF (LHOOK) CALL DR_HOOK('MODE_SOIL_VG:WSAT_VG_2D',0,ZHOOK_HANDLE)
   SELECT CASE (HPEDOTF)
          CASE ('CP88')
               WHERE(PCLAY/=XUNDEF)
                    WSAT_VG_2D = 0.4874391874-0.0673307510*PSAND-0.1974384849*PCLAY
               END WHERE
          CASE ('WO99')
               WHERE(PCLAY/=XUNDEF)
                    ZSILT=1.0-PCLAY-PSAND
                    WSAT_VG_2D = 0.7919+0.1691*PCLAY-0.29619*(PDENS/1000.)-0.01491*(ZSILT**2)+0.0000821*(PMO**2)   &
                                + 0.0002427/PCLAY+0.0001113/ZSILT+0.01472*LOG(ZSILT*100.)-0.00733*PMO*PCLAY         &
                                - 0.0619*(PDENS/1000.)*PCLAY-0.001183*(PDENS/1000.)*PMO-0.01664*PTOPSOIL*ZSILT 
               END WHERE
   END SELECT
   !                 
   WHERE(PCLAY==XUNDEF)
     WSAT_VG_2D = XUNDEF
   END WHERE
   IF (LHOOK) CALL DR_HOOK('MODE_SOIL_VG:WSAT_VG_2D',1,ZHOOK_HANDLE)
   !
   END FUNCTION WSAT_VG_2D
