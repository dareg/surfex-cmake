!     #########
SUBROUTINE READ_NAMELISTS_GARDEN(HPROGRAM)
!     #######################################################
!
USE MODD_ASSIM_GARDEN
USE MODD_AGRI_GARDEN,           ONLY : LAGRIP
USE MODD_DEEPSOIL_GARDEN,       ONLY : LPHYSDOMC, LDEEPSOIL
!
USE MODI_DEFAULT_ASSIM
USE MODI_DEFAULT_AGRI
USE MODI_DEFAULT_DEEPSOIL
USE MODI_READ_TEB_GARDEN_CONF
!
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE
!
CHARACTER(LEN=6),  INTENT(IN)  :: HPROGRAM ! program calling ISBA
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
!----------------------------------------------
!                 
IF (LHOOK) CALL DR_HOOK('READ_NAMELISTS_GARDEN',0,ZHOOK_HANDLE)
CALL DEFAULT_ASSIM(LASSIM,CASSIM)
!                
CALL DEFAULT_AGRI(LAGRIP)
!
CALL DEFAULT_DEEPSOIL(LDEEPSOIL,LPHYSDOMC)
!
!
CALL READ_TEB_GARDEN_CONF(HPROGRAM)
IF (LHOOK) CALL DR_HOOK('READ_NAMELISTS_GARDEN',1,ZHOOK_HANDLE)
!
!---------------------------------------
!
END SUBROUTINE READ_NAMELISTS_GARDEN
