#!/usr/bin/perl -w

use strict;
use FileHandle;

my $MM = '';
my $BB = '64';

my $fh = 'FileHandle'->new (">lfisuffix.h");

$fh->print (<< "EOF");
#ifndef _LFISUFFIX_H
#define _LFISUFFIX_H
#define _JPLIKB_   8
#define _JPLIKM_   4
EOF


while (<DATA>)
  {
    chomp;
    my $S = $_;

    $fh->print ("\n");

    for my $x (['_MM', $MM], ['_BB', $BB], ['_MT_MM', "_MT$MM"], ['_MT_BB', "_MT$BB"])
      {
        my ($s1, $s2) = @$x;
        $fh->printf ("#define %-15s %-20s\n", "$S$s1", "$S$s2");
      }

    $fh->print ("\n");

  }

$fh->print (<< "EOF");
#endif
EOF

