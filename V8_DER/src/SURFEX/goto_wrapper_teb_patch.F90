SUBROUTINE GOTO_WRAPPER_TEB_PATCH(KTO_PATCH)
!
USE MODD_DIAG_CUMUL_TEB_n
USE MODD_DIAG_MISC_TEB_n
USE MODD_TEB_n
USE MODD_BEM_n
USE MODD_TEB_GARDEN_n
USE MODD_TEB_GARDEN_PGD_EVOL_n
USE MODD_TEB_GREENROOF_n
USE MODD_TEB_GREENROOF_PGD_EVOL_n
!
USE MODE_MODELN_TEB_HANDLER, ONLY : GET_CURRENT_PATCH_INDEX_TEB, &
                                    PUT_CURRENT_PATCH_INDEX_TEB
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE 
INTEGER,INTENT(IN) :: KTO_PATCH
!
INTEGER            :: ICURRENT_PATCH
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('GOTO_WRAPPER_TEB_PATCH',0,ZHOOK_HANDLE)
ICURRENT_PATCH = GET_CURRENT_PATCH_INDEX_TEB()
!
 CALL DIAG_CUMUL_TEB_GOTO_PATCH(KTO_PATCH)
 CALL DIAG_MISC_TEB_GOTO_PATCH(KTO_PATCH)
 CALL TEB_GOTO_PATCH(KTO_PATCH)
 CALL BEM_GOTO_PATCH(KTO_PATCH)
 CALL TEB_GARDEN_PGD_EVOL_GOTO_PATCH(KTO_PATCH)
 CALL TEB_GREENROOF_PGD_EVOL_GOTO_PATCH(KTO_PATCH)
 CALL TEB_GARDEN_GOTO_PATCH(KTO_PATCH)
 CALL TEB_GREENROOF_GOTO_PATCH(KTO_PATCH)
!
 CALL PUT_CURRENT_PATCH_INDEX_TEB(KTO_PATCH)
!
IF (LHOOK) CALL DR_HOOK('GOTO_WRAPPER_TEB_PATCH',1,ZHOOK_HANDLE)
!
END SUBROUTINE GOTO_WRAPPER_TEB_PATCH
