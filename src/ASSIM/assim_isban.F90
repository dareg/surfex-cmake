!     ###############################################################################
SUBROUTINE ASSIM_ISBA_n(HPROGRAM,KI,                                   &
                        PCON_RAIN, PSTRAT_RAIN, PCON_SNOW, PSTRAT_SNOW,&
                        PCLOUDS,   PLSM,        PEVAPTR,   PEVAP,      &
                        PSWEC,     PTSC,                               &
                        PTS,       PT2M,        PHU2M,     PSWE,       &
                        HTEST )

!     ###############################################################################
!
!!****  *ASSIM_ISBA_n * - Chooses the surface assimilation schemes for ISBA
!!
!!    PURPOSE
!!    -------
!!
!!**  METHOD
!!    ------
!!
!!    REFERENCE
!!    ---------
!!      
!!
!!    AUTHOR
!!    ------
!!     T. Aspelien
!!
!!    MODIFICATIONS
!!    -------------
!!      Original    04/2012
!!      Trygve Aspelien, Separating IO  06/2013
!!--------------------------------------------------------------------
!
USE MODD_ASSIM,          ONLY : CASSIM_ISBA,LAESNM,LEXTRAP_NATURE,NPRINTLEV
USE MODD_SURF_ATM_n,     ONLY : NR_NATURE
USE MODD_SURF_ATM_GRID_n,ONLY : XLAT, XLON
USE MODN_IO_OFFLINE,     ONLY : CPGDFILE,CPREPFILE
USE MODD_SURF_PAR,       ONLY : XUNDEF
USE MODD_ISBA_n,         ONLY : TSNOW,XWG,XWGI,XTG,XZS
USE YOMHOOK,             ONLY : LHOOK,   DR_HOOK
USE PARKIND1,            ONLY : JPRB

USE MODI_ABOR1_SFX
USE MODI_OI_HOR_EXTRAPOL_SURF
USE MODI_ASSIM_ISBA_UPDATE_SNOW
USE MODI_ASSIM_NATURE_ISBA_EKF
USE MODI_ASSIM_NATURE_ISBA_OI
!
IMPLICIT NONE
!
!*      0.1    declarations of arguments
!
CHARACTER(LEN=6),    INTENT(IN) :: HPROGRAM  ! program calling surf. schemes
INTEGER,             INTENT(IN) :: KI
REAL, DIMENSION(KI), INTENT(IN) :: PCON_RAIN
REAL, DIMENSION(KI), INTENT(IN) :: PSTRAT_RAIN
REAL, DIMENSION(KI), INTENT(IN) :: PCON_SNOW
REAL, DIMENSION(KI), INTENT(IN) :: PSTRAT_SNOW
REAL, DIMENSION(KI), INTENT(IN) :: PCLOUDS
REAL, DIMENSION(KI), INTENT(IN) :: PLSM
REAL, DIMENSION(KI), INTENT(IN) :: PEVAPTR
REAL, DIMENSION(KI), INTENT(IN) :: PEVAP
REAL, DIMENSION(KI), INTENT(IN) :: PSWEC
REAL, DIMENSION(KI), INTENT(IN) :: PTSC
REAL, DIMENSION(KI), INTENT(IN) :: PTS
REAL, DIMENSION(KI), INTENT(IN) :: PT2M
REAL, DIMENSION(KI), INTENT(IN) :: PHU2M
REAL, DIMENSION(KI), INTENT(IN) :: PSWE
CHARACTER(LEN=2),    INTENT(IN) :: HTEST ! must be equal to 'OK'
!
!*      0.2    declarations of local variables
!
!-------------------------------------------------------------------------------------
!
REAL(KIND=JPRB)                    :: ZHOOK_HANDLE
LOGICAL, DIMENSION(:), ALLOCATABLE :: OINTERP_NATURE
LOGICAL, DIMENSION(:), ALLOCATABLE :: OINTERP_SN
REAL,    DIMENSION(:), ALLOCATABLE :: PLON
REAL,    DIMENSION(:), ALLOCATABLE :: PLAT
REAL,    DIMENSION(:), ALLOCATABLE :: PTS_EP,ZTS_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PTP_EP,ZTP_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PT3_EP,ZT3_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PWS_EP,ZWS_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PWP_EP,ZWP_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PTL_EP,ZTL_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PSWE_EP,ZSWE_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PSNR_EP,ZSNR_EP
REAL,    DIMENSION(:), ALLOCATABLE :: PSNA_EP,ZSNA_EP
REAL,    DIMENSION(:), ALLOCATABLE :: ZALT
REAL,    DIMENSION(KI)             :: ZSWE
REAL,    DIMENSION(KI)             :: ZSWE_ORIG
INTEGER                            :: I,NLAYER,NPATCH

IF (LHOOK) CALL DR_HOOK('ASSIM_ISBA_N',0,ZHOOK_HANDLE)

IF (HTEST/='OK') THEN
  CALL ABOR1_SFX('ASSIM_ISBA_n: FATAL ERROR DURING ARGUMENT TRANSFER')
END IF

! Set snow layers and patches
NPATCH=1
NLAYER=1

ZSWE=PSWE
! Soil assimilation
IF ( CASSIM_ISBA == 'EKF  ' ) THEN

  ! Snow analysis/update
  IF (LAESNM) THEN
    WRITE(*,*) 'UPDATE SNOW FROM ANALYSED CANARI VALUES'
    CALL ASSIM_ISBA_UPDATE_SNOW(HPROGRAM,KI,ZSWE,ZSWE_ORIG,.TRUE.,.TRUE.,HTEST)
  ELSE
    WRITE(*,*) 'SNOW IS NOT UPDATED FROM ANALYSED CANARI VALUES'
  ENDIF

  ! Run EKF for soil
  CALL ASSIM_NATURE_ISBA_EKF(HPROGRAM,KI,   &
                             PT2M,    PHU2M,&
                             HTEST )

ELSEIF ( CASSIM_ISBA == 'OI   ' ) THEN

  ! Snow analysis/update. Store the original field in the surfex file
  IF (LAESNM) THEN
    WRITE(*,*) 'UPDATE SNOW FROM ANALYSED CANARI VALUES'
    CALL ASSIM_ISBA_UPDATE_SNOW(HPROGRAM,KI,ZSWE,ZSWE_ORIG,.TRUE.,.FALSE.,HTEST)
  ELSE
    WRITE(*,*) 'SNOW IS NOT UPDATED FROM ANALYSED CANARI VALUES'
  ENDIF

  ! Run OI for soil
  CALL ASSIM_NATURE_ISBA_OI(HPROGRAM, KI,                                  &
                            PCON_RAIN, PSTRAT_RAIN, PCON_SNOW, PSTRAT_SNOW,&
                            PCLOUDS,   PLSM,        PEVAPTR,   PEVAP,      &
                            PSWEC,     PTSC,                               &
                            PTS,       PT2M,        PHU2M,     ZSWE,       &
                            HTEST )

  ! Snow analysis/update (changed in oi_cacsts). Get the full increment
  IF (LAESNM) THEN
    WRITE(*,*) 'UPDATE SNOW FROM ANALYSED OI_CACSTS VALUES'
    CALL ASSIM_ISBA_UPDATE_SNOW(HPROGRAM,KI,ZSWE,ZSWE_ORIG,.FALSE.,.TRUE.,HTEST)
  ELSE
    WRITE(*,*) 'SNOW IS NOT UPDATED FROM ANALYSED OI_CACSTS VALUES'
  ENDIF
ELSE
  CALL ABOR1_SFX(CASSIM_ISBA//' is not a defined scheme for ASSIM_ISBA_N')
ENDIF

! Extrapolation if requested
IF ( LEXTRAP_NATURE ) THEN
  ALLOCATE(OINTERP_NATURE(KI))
  ALLOCATE(OINTERP_SN(KI))
  ALLOCATE(PLON(KI))
  ALLOCATE(PLAT(KI))
  ALLOCATE(PTS_EP(KI),ZTS_EP(KI))
  ALLOCATE(PTP_EP(KI),ZTP_EP(KI))
  ALLOCATE(PT3_EP(KI),ZT3_EP(KI))
  ALLOCATE(PWS_EP(KI),ZWS_EP(KI))
  ALLOCATE(PWP_EP(KI),ZWP_EP(KI))
  ALLOCATE(PTL_EP(KI),ZTL_EP(KI))
  ALLOCATE(PSWE_EP(KI),ZSWE_EP(KI))
  ALLOCATE(PSNR_EP(KI),ZSNR_EP(KI))
  ALLOCATE(PSNA_EP(KI),ZSNA_EP(KI))
  ALLOCATE(ZALT(KI))

  ! Set longitudes/latitudes for nature points
  ZALT(:)=XZS(:)
  DO I=1,KI
    PLON(I)=XLON(NR_NATURE(I))
    PLAT(I)=XLAT(NR_NATURE(I))
  ENDDO

  PWS_EP=XWG(:,1,NPATCH)
  PWP_EP=XWG(:,2,NPATCH)
  PTS_EP=XTG(:,1,NPATCH)
  PTP_EP=XTG(:,2,NPATCH)
  PT3_EP=XTG(:,3,NPATCH)
  PTL_EP=XWGI(:,2,NPATCH)
  PSWE_EP=TSNOW%WSNOW(:,NLAYER,NPATCH)
  PSNR_EP=TSNOW%RHO(:,NLAYER,NPATCH)
  PSNA_EP=TSNOW%ALB(:,NPATCH)
  ! Search for the nearest grid point values for land surface fields
  ! at locations where the CANARI land fraction is less than 50%
  ! and therefore useless values MIGTH be given

  OINTERP_NATURE = .FALSE.
  OINTERP_SN     = .FALSE.

  ! Snow albedo and density are also extrapolated in points 
  ! which get initial snow in the snow analysis
  WHERE ( PSWE_EP(:) < 1.0E-10 .AND. PSWE(:)>= 1.0E-10 )
    OINTERP_SN(:) = .TRUE.
    PSNA_EP(:)    = XUNDEF
    PSNR_EP(:)    = XUNDEF
  END WHERE
  PSWE_EP(:)      = PSWE(:)

  WHERE ( PLSM(:) < 0.5 )
    OINTERP_NATURE(:) = .TRUE.
    OINTERP_SN(:) = .TRUE.
    PTS_EP(:)     = XUNDEF
    PTP_EP(:)     = XUNDEF
    PT3_EP(:)     = XUNDEF
    PWS_EP(:)     = XUNDEF
    PWP_EP(:)     = XUNDEF
    PTL_EP(:)     = XUNDEF
    PSWE_EP(:)    = XUNDEF
    PSNA_EP(:)    = XUNDEF
    PSNR_EP(:)    = XUNDEF
  END WHERE

  ZTS_EP(:) = PTS_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZTS_EP,PLAT,PLON,PTS_EP,OINTERP_NATURE,ZALT)
  ZTP_EP(:) = PTP_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZTP_EP,PLAT,PLON,PTP_EP,OINTERP_NATURE,ZALT)
  ZT3_EP(:) = PT3_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZT3_EP,PLAT,PLON,PT3_EP,OINTERP_NATURE,ZALT)
  ZWS_EP(:) = PWS_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZWS_EP,PLAT,PLON,PWS_EP,OINTERP_NATURE)
  ZWP_EP(:) = PWP_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZWP_EP,PLAT,PLON,PWP_EP,OINTERP_NATURE)
  ZTL_EP(:) = PTL_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZTL_EP,PLAT,PLON,PTL_EP,OINTERP_NATURE)
  ZSWE_EP(:) = PSWE_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZSWE_EP,PLAT,PLON,PSWE_EP,OINTERP_NATURE)
  ZSNA_EP(:) = PSNA_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZSNA_EP,PLAT,PLON,PSNA_EP,OINTERP_SN)
  ZSNR_EP(:) = PSNR_EP(:)
  CALL OI_HOR_EXTRAPOL_SURF(KI,PLAT,PLON,ZSNR_EP,PLAT,PLON,PSNR_EP,OINTERP_SN)

  !
  ! PRINT values produced by OI_HO_EXTRAPOL_SURF for TS
  !
  IF ( NPRINTLEV > 2 ) THEN
    DO I=1,KI
     IF (OINTERP_NATURE(I)) THEN
       PRINT *,'Surface temperature set to ',PTS_EP(I),'from nearest neighbour at I=',NR_NATURE(I)
     ENDIF
    ENDDO
  ENDIF

  ! Set extrpolated fields to global
  XWG(:,1,NPATCH)=PWS_EP
  XWG(:,2,NPATCH)=PWP_EP
  XTG(:,1,NPATCH)=PTS_EP
  XTG(:,2,NPATCH)=PTP_EP
  XTG(:,3,NPATCH)=PT3_EP
  XWGI(:,2,NPATCH)=PTL_EP
  TSNOW%WSNOW(:,NLAYER,NPATCH)=PSWE_EP
  TSNOW%RHO(:,NLAYER,NPATCH)=PSNR_EP
  TSNOW%ALB(:,NPATCH)=PSNA_EP

  DEALLOCATE(OINTERP_NATURE)
  DEALLOCATE(OINTERP_SN)
  DEALLOCATE(PLON)
  DEALLOCATE(PLAT)
  DEALLOCATE(PTS_EP,ZTS_EP)
  DEALLOCATE(PTP_EP,ZTP_EP)
  DEALLOCATE(PT3_EP,ZT3_EP)
  DEALLOCATE(PWS_EP,ZWS_EP)
  DEALLOCATE(PWP_EP,ZWP_EP)
  DEALLOCATE(PTL_EP,ZTL_EP)
  DEALLOCATE(PSWE_EP,ZSWE_EP)
  DEALLOCATE(PSNR_EP,ZSNR_EP)
  DEALLOCATE(PSNA_EP,ZSNA_EP)
  DEALLOCATE(ZALT)
ENDIF

! Snow analysis/update security
IF (LAESNM) THEN

  ! removes very small values due to computation precision
  WHERE(TSNOW%WSNOW(:,NLAYER,NPATCH) < 1.0E-10) TSNOW%WSNOW(:,NLAYER,NPATCH) = 0.0

  ! No SNOW
  WHERE ( TSNOW%WSNOW(:,NLAYER,NPATCH) == 0.0 )
    TSNOW%RHO(:,NLAYER,NPATCH) = XUNDEF
    TSNOW%ALB(:,NPATCH)        = XUNDEF
  END WHERE
ENDIF

IF (LHOOK) CALL DR_HOOK('ASSIM_ISBA_N',1,ZHOOK_HANDLE)
!
!-------------------------------------------------------------------------------------
!
END SUBROUTINE ASSIM_ISBA_n
