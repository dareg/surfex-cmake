                           DTT, DTZ, DGEI, DGF, DGI, DGMI, DGMTO, DGO, DGS, DGSI, DGU, &
                           DGT, DGUT, DGW, F, FSB, GB, ICP, I, O, SSB, UG, &
                           SV, TCP, TGD, TGDO, TGR, TGRO, T, TOP, TVG, W, WSB, &
                           IOB, S, U, &
                          KI,PITM,PSST,PSIC,HTEST)

!     ###############################################################################
!
!!****  *ASSIM_SET_SST * - Reads SST from file
!!
!!    PURPOSE
!!    -------
!!
!!**  METHOD
!!    ------
!!
!!    REFERENCE
!!    ---------
