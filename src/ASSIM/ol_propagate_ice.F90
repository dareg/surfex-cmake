SUBROUTINE OL_PROPAGATE_ICE(KSIZE, KNUM_LAYERS, PLON, PLAT, PSIC_OLD, PSIC_NEW, PTICE, PZICE, PSDF, OMISSING_OLD_ICE, PICE_EDGE_THK)

USE MODI_SEAICE_SICE_PROPAGATE_ICE
USE MODD_SURFEX_MPI, ONLY : NCOMM, NPROC, NRANK
USE YOMHOOK,       ONLY: LHOOK, DR_HOOK
USE PARKIND1,      ONLY: JPRB
IMPLICIT NONE

#ifdef SFX_MPI
INCLUDE 'mpif.h'
#endif
INTEGER, INTENT(IN) :: KSIZE
INTEGER, INTENT(IN) :: KNUM_LAYERS
REAL, DIMENSION (KSIZE), INTENT(IN) :: PLON
REAL, DIMENSION (KSIZE), INTENT(IN) :: PLAT
REAL, DIMENSION (KSIZE), INTENT(IN) :: PSIC_OLD
REAL, DIMENSION (KSIZE), INTENT(IN) :: PSIC_NEW
REAL, DIMENSION (KSIZE, KNUM_LAYERS), INTENT(IN OUT) :: PTICE
REAL, DIMENSION (KSIZE), INTENT(IN OUT) :: PZICE
REAL, DIMENSION (KSIZE), INTENT(OUT) :: PSDF
LOGICAL, INTENT(OUT) :: OMISSING_OLD_ICE
REAL, INTENT(OUT) :: PICE_EDGE_THK

INTEGER, ALLOCATABLE :: CHUNK_SIZES(:), RECV_CHUNKS(:)
INTEGER :: SIZE_TOT, JI, JMYPROC, JNPROC
INTEGER :: JERR

REAL, ALLOCATABLE :: ZLON_TOT(:), ZLAT_TOT(:)

REAL, ALLOCATABLE :: ZSIC_TOT_OLD(:), ZSIC_TOT_NEW(:)
REAL, ALLOCATABLE :: ZTICE_TOT(:,:), ZZICE_TOT(:)
REAL, ALLOCATABLE :: ZSDF(:)
LOGICAL :: GMISSING_OLD_ICE
INTEGER :: IMISSING_OLD_ICE
REAL :: ZICE_EDGE_THK

REAL(KIND=JPRB) :: ZHOOK_HANDLE

IF (LHOOK) CALL DR_HOOK('OL_PROPAGATE_ICE', 0, ZHOOK_HANDLE)

#ifdef SFX_MPI
  JMYPROC = NRANK
  JNPROC = NPROC
#else
  JMYPROC = 0
  JNPROC = 1
#endif

IF(JMYPROC == 0) THEN
  ALLOCATE(CHUNK_SIZES(JNPROC), RECV_CHUNKS(JNPROC))
ELSE
  ALLOCATE(CHUNK_SIZES(1), RECV_CHUNKS(1))
END IF
#ifdef SFX_MPI
  RECV_CHUNKS=1
  CALL MPI_GATHER(KSIZE, 1, MPI_INTEGER, CHUNK_SIZES, JNPROC, MPI_INTEGER, 0, NCOMM, JERR)
#else
  CHUNK_SIZES = KSIZE
#endif


IF(JMYPROC == 0) THEN
  SIZE_TOT = SUM(CHUNK_SIZES)
  print*, '==+==', CHUNK_SIZES(:)
  ALLOCATE(ZSDF(SIZE_TOT), ZSIC_TOT_OLD(SIZE_TOT), ZSIC_TOT_NEW(SIZE_TOT))
  ALLOCATE(ZLON_TOT(SIZE_TOT), ZLAT_TOT(SIZE_TOT), ZTICE_TOT(SIZE_TOT,KNUM_LAYERS))
  ALLOCATE(ZZICE_TOT(SIZE_TOT))
ELSE
  ALLOCATE(ZSDF(1), ZSIC_TOT_OLD(1), ZSIC_TOT_NEW(1))
  ALLOCATE(ZLON_TOT(1), ZLAT_TOT(1), ZTICE_TOT(1,1))
  ALLOCATE(ZZICE_TOT(1))
END IF
! Gather all required data
#ifdef SFX_MPI
  CALL MPI_GATHER(PLON, KSIZE, MPI_DOUBLE_PRECISION, ZLON_TOT, SIZE_TOT, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)
  CALL MPI_GATHER(PLAT, KSIZE, MPI_DOUBLE_PRECISION, ZLAT_TOT, SIZE_TOT, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)

  CALL MPI_GATHER(PSIC_OLD, KSIZE, MPI_DOUBLE_PRECISION, ZSIC_TOT_OLD, SIZE_TOT, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)
  CALL MPI_GATHER(PSIC_NEW, KSIZE, MPI_DOUBLE_PRECISION, ZSIC_TOT_NEW, SIZE_TOT, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)
  DO JI=1, KNUM_LAYERS
    CALL MPI_GATHER(         &
        PTICE(:,JI)          &
      , KSIZE                &
      , MPI_DOUBLE_PRECISION &
      , ZTICE_TOT(:,JI)      &
      , SIZE_TOT             &
      , MPI_DOUBLE_PRECISION &
      , 0                    &
      , NCOMM                &
      , JERR                 )
  END DO
  CALL MPI_GATHER(PZICE, KSIZE, MPI_DOUBLE_PRECISION, ZZICE_TOT, SIZE_TOT, MPI_DOUBLE_PRECISION, 1, NCOMM, JERR)
#else
  ZLON_TOT = PLON
  ZLAT_TOT = PLAT
  ZSIC_TOT_OLD = PSIC_OLD
  ZSIC_TOT_NEW = PSIC_NEW
  ZTICE_TOT = PTICE
  ZZICE_TOT = PZICE
#endif


IF(JMYPROC == 0) THEN
  CALL SEAICE_SICE_PROPAGATE_ICE( &
      SIZE_TOT                    &
    , KNUM_LAYERS                 &
    , ZLON_TOT                    &
    , ZLAT_TOT                    &
    , ZSIC_TOT_OLD                &
    , ZSIC_TOT_NEW                &
    , ZTICE_TOT                   &
    , ZZICE_TOT                   &
    , ZSDF                        &
    , GMISSING_OLD_ICE            &
    , ZICE_EDGE_THK               )

  IF(GMISSING_OLD_ICE) THEN
    IMISSING_OLD_ICE = 1
  ELSE
    IMISSING_OLD_ICE = 0
  END IF
END IF

! Send processed data back
#ifdef SFX_MPI
  DO JI=1, KNUM_LAYERS
    CALL MPI_SCATTER(        &
        ZTICE_TOT(:,JI)      &
      , SIZE_TOT             &
      , MPI_DOUBLE_PRECISION &
      , PTICE(:,JI)          &
      , KSIZE                &
      , MPI_DOUBLE_PRECISION &
      , 0                    &
      , NCOMM                &
      , JERR                 )
  END DO
  CALL MPI_SCATTER(ZZICE_TOT, SIZE_TOT, MPI_DOUBLE_PRECISION, PZICE, KSIZE, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)
  CALL MPI_SCATTER(ZSDF, SIZE_TOT, MPI_DOUBLE_PRECISION, PSDF, KSIZE, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)

  CALL MPI_BCAST(IMISSING_OLD_ICE, 1, MPI_INTEGER, 0, NCOMM, JERR)
  CALL MPI_BCAST(ZICE_EDGE_THK, 1, MPI_DOUBLE_PRECISION, 0, NCOMM, JERR)
#else
  PTICE = ZTICE_TOT
  PZICE = ZZICE_TOT
  PSDF  = ZSDF
#endif

IF(IMISSING_OLD_ICE == 1) THEN
  OMISSING_OLD_ICE = .TRUE.
ELSE
  OMISSING_OLD_ICE = .FALSE.
END IF
PICE_EDGE_THK = ZICE_EDGE_THK

DEALLOCATE(CHUNK_SIZES, ZSDF, ZSIC_TOT_OLD, ZSIC_TOT_NEW, ZLON_TOT, ZLAT_TOT)
DEALLOCATE(ZTICE_TOT, ZZICE_TOT)
DEALLOCATE(RECV_CHUNKS)

IF (LHOOK) CALL DR_HOOK('OL_PROPAGATE_ICE', 1, ZHOOK_HANDLE)
END SUBROUTINE OL_PROPAGATE_ICE
