SUBROUTINE SEAICE_SICE_PROPAGATE_ICE(KSIZE_TOT, PLON_TOT, PLAT_TOT, PSIC_OLD_TOT, &
  PSIC_NEW_TOT, PTICE_TOT, PICE_SHAPE_TOT, PZICE_TOT, PSDF_TOT, OMISSING_OLD_ICE, PICE_EDGE_THK)

USE NN_EXTRAPOLATE, ONLY: NEAREST_NEIGHBOUR_QUERY, DISTANCE_QUERY
USE YOMHOOK, ONLY: LHOOK, DR_HOOK
USE PARKIND1, ONLY: JPRB
IMPLICIT NONE
  INTEGER, INTENT(IN) :: KSIZE_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN) :: PLON_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN) :: PLAT_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN) :: PSIC_OLD_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN) :: PSIC_NEW_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN OUT) :: PTICE_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN OUT) :: PICE_SHAPE_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(IN OUT) :: PZICE_TOT
  REAL, DIMENSION (KSIZE_TOT), INTENT(OUT) :: PSDF_TOT
  LOGICAL, INTENT(OUT) :: OMISSING_OLD_ICE
  REAL, INTENT(OUT) :: PICE_EDGE_THK

  REAL, PARAMETER :: SMOOTHE_RADIUS = 3.E+4
  REAL, PARAMETER :: EXTRAPOL_TOLERANCE = -2.E+5
  INTEGER, PARAMETER :: QNUM = 50

  INTEGER :: SIZE_SEA

  REAL, ALLOCATABLE :: ZSIC_TOT_OLD(:), ZSIC_TOT_NEW(:)
  REAL, ALLOCATABLE :: ZTICE_TOT(:), ZICE_SHAPE_TOT(:), ZZICE_TOT(:)
  REAL, ALLOCATABLE :: ZSDF(:), ZSDF_NEW_ICE(:)

  REAL, ALLOCATABLE :: NN_DIST(:), NN_DIST_INSIDE_ICE(:), NN_NEW_ICE(:), NN_INSIDE_NEW_ICE(:)

  REAL, ALLOCATABLE :: ZOPEN_SEA_LON(:), ZOPEN_SEA_LAT(:)
  REAL, ALLOCATABLE :: ZSEA_ICE_LON(:), ZSEA_ICE_LAT(:)
  REAL, ALLOCATABLE :: ZNOT_NEW_ICE_LON(:), ZNOT_NEW_ICE_LAT(:)
  REAL, ALLOCATABLE :: ZNEW_ICE_LON(:), ZNEW_ICE_LAT(:)
  REAL, ALLOCATABLE :: ZLON_REG(:), ZLAT_REG(:)
  REAL, ALLOCATABLE :: ZTICE_REG(:), ZICE_SHAPE_REG(:), ZSDF_REG(:), ZSDF_NEW_ICE_REG(:)

  REAL :: ZWEIGHTS(QNUM)
  INTEGER :: INDICES(QNUM)

  INTEGER :: JI, JIOPEN_SEA, JISEA_ICE, JINOT_NEW_ICE, JINEW_ICE, JISMOOTH, JICURR_POS
  INTEGER :: IOUTSIDE_NEW_ICE_SIZE, INEW_ICE_SIZE, IOPEN_SEA_SIZE, ISEA_ICE_SIZE, ISMOOTH_SIZE
  INTEGER, ALLOCATABLE :: IOPEN_SEA_MASK(:), ISEA_ICE_MASK(:), INOT_NEW_ICE_MASK(:), INEW_ICE_MASK(:)
  INTEGER, ALLOCATABLE :: NN_INDEX(:), ISMOOTH_MASK(:), INVERSE_SMOOTH_MASK(:)

  INTEGER :: INUM_BORDER_CELLS
  LOGICAL :: GMISSING_ICE

  REAL :: ZTOTAL_WEIGHT
  REAL :: ZICE_EDGE_THK

  REAL(KIND=JPRB) :: ZHOOK_HANDLE

  IF (LHOOK) CALL DR_HOOK('SEAICE_SICE_PROPAGATE_ICE', 0, ZHOOK_HANDLE)

  ALLOCATE(ZSDF(KSIZE_TOT), ZSIC_TOT_OLD(KSIZE_TOT), ZSIC_TOT_NEW(KSIZE_TOT))
  ALLOCATE(ZTICE_TOT(KSIZE_TOT), ZZICE_TOT(KSIZE_TOT))
  ALLOCATE(ZICE_SHAPE_TOT(KSIZE_TOT))

  ZSIC_TOT_OLD   = PSIC_OLD_TOT
  ZSIC_TOT_NEW   = PSIC_NEW_TOT
  ZTICE_TOT      = PTICE_TOT
  ZICE_SHAPE_TOT = PICE_SHAPE_TOT
  ZZICE_TOT      = PZICE_TOT

  IF(COUNT(ZSIC_TOT_OLD > 0) == 0) THEN
    GMISSING_ICE = .TRUE.
  ELSE
    GMISSING_ICE = .FALSE.
  END IF

  IF(.NOT. GMISSING_ICE) THEN
  print*, minval(ZSIC_TOT_OLD), maxval(ZSIC_TOT_OLD)
  print*, minval(ZSIC_TOT_NEW), maxval(ZSIC_TOT_NEW)

    IOPEN_SEA_SIZE = COUNT(.NOT. ZSIC_TOT_OLD > 0.)
    ISEA_ICE_SIZE = COUNT(ZSIC_TOT_OLD > 0.)

    print*, 'No of grid points with ice in previous ice field:', ISEA_ICE_SIZE
    print*, 'No of grid points with ice in new      ice field:', COUNT(ZSIC_TOT_NEW > 0.)

    ALLOCATE(ZOPEN_SEA_LON(IOPEN_SEA_SIZE), &
             ZOPEN_SEA_LAT(IOPEN_SEA_SIZE), &
             NN_INDEX     (IOPEN_SEA_SIZE), &
             NN_DIST      (IOPEN_SEA_SIZE), &
             IOPEN_SEA_MASK(IOPEN_SEA_SIZE)  )

    ALLOCATE(ZSEA_ICE_LON(ISEA_ICE_SIZE), &
             ZSEA_ICE_LAT(ISEA_ICE_SIZE), &
             NN_DIST_INSIDE_ICE(ISEA_ICE_SIZE), &
             ISEA_ICE_MASK(ISEA_ICE_SIZE)  )

    JIOPEN_SEA = 1
    JISEA_ICE = 1

    DO JI = 1, KSIZE_TOT
      IF(.NOT. ZSIC_TOT_OLD(JI) > 0.) THEN
        IOPEN_SEA_MASK(JIOPEN_SEA) = JI
        ZOPEN_SEA_LON(JIOPEN_SEA) = PLON_TOT(JI)
        ZOPEN_SEA_LAT(JIOPEN_SEA) = PLAT_TOT(JI)

        JIOPEN_SEA = JIOPEN_SEA + 1
      ELSE
        ISEA_ICE_MASK(JISEA_ICE) = JI
        ZSEA_ICE_LON(JISEA_ICE) = PLON_TOT(JI)
        ZSEA_ICE_LAT(JISEA_ICE) = PLAT_TOT(JI)

        JISEA_ICE = JISEA_ICE + 1
      END IF
    END DO

    ! Construct signed distance field
    CALL NEAREST_NEIGHBOUR_QUERY(PLON_TOT, PLAT_TOT, ZOPEN_SEA_LON, ZOPEN_SEA_LAT, &
      O_INPUT_MASK = ZSIC_TOT_OLD > 0., K_INDEX = NN_INDEX, P_DIST = NN_DIST)

    ZSDF = 0.
    ZSDF(IOPEN_SEA_MASK) = NN_DIST

    CALL NEAREST_NEIGHBOUR_QUERY(PLON_TOT, PLAT_TOT, ZSEA_ICE_LON, ZSEA_ICE_LAT, &
      O_INPUT_MASK = .NOT. ZSIC_TOT_OLD > 0. .AND. ZSDF < 1.E+5, P_DIST = NN_DIST_INSIDE_ICE )

    ZSDF(ISEA_ICE_MASK) = - NN_DIST_INSIDE_ICE

    ! Get mean ice thickness along the ice edge
    ZICE_EDGE_THK = 0.
    INUM_BORDER_CELLS = 0
    DO JI = 1, KSIZE_TOT
      IF(ZSDF(JI) < -1.E+3 .AND. ZSDF(JI) > -5.E+3) THEN
        ZICE_EDGE_THK = ZICE_EDGE_THK + ZZICE_TOT(JI)
        INUM_BORDER_CELLS = INUM_BORDER_CELLS + 1
      END IF
    END DO
    IF(INUM_BORDER_CELLS > 0) THEN
      ZICE_EDGE_THK = ZICE_EDGE_THK/REAL(INUM_BORDER_CELLS)
      print*, 'Mean ice thickness along the edge: ', ZICE_EDGE_THK
    ELSE
      ZICE_EDGE_THK = MINVAL(ZZICE_TOT(ISEA_ICE_MASK))
      print*, 'All sea grid cells are covered by ice'
    END IF

    ! Extrapolate ice to the new border
    ZTICE_TOT(IOPEN_SEA_MASK) = 271.3
    ZICE_SHAPE_TOT(IOPEN_SEA_MASK) = 271.3
    ZZICE_TOT(IOPEN_SEA_MASK) = ZICE_EDGE_THK
    WHERE(ZSIC_TOT_NEW(IOPEN_SEA_MASK) > 0.)
      ZTICE_TOT(IOPEN_SEA_MASK) = ZTICE_TOT(NN_INDEX)
      ZICE_SHAPE_TOT(IOPEN_SEA_MASK) = ZICE_SHAPE_TOT(NN_INDEX)
      ZZICE_TOT(IOPEN_SEA_MASK) = ZZICE_TOT(NN_INDEX)
    END WHERE


    DEALLOCATE(ZOPEN_SEA_LON, ZOPEN_SEA_LAT)
    DEALLOCATE(ZSEA_ICE_LON, ZSEA_ICE_LAT)
    DEALLOCATE(NN_DIST, NN_DIST_INSIDE_ICE)
    DEALLOCATE(ISEA_ICE_MASK)

    ! Smoothe result fields
    INEW_ICE_SIZE = COUNT(ZSIC_TOT_NEW(IOPEN_SEA_MASK) > 0.)

    DEALLOCATE(IOPEN_SEA_MASK)

    HAS_NEW_ICE: IF(INEW_ICE_SIZE > 0) THEN
      IOUTSIDE_NEW_ICE_SIZE = COUNT(ZSIC_TOT_OLD > 0. .OR. .NOT. ZSIC_TOT_NEW > 0. )

      ALLOCATE(INOT_NEW_ICE_MASK(IOUTSIDE_NEW_ICE_SIZE), &
               ZNOT_NEW_ICE_LON(IOUTSIDE_NEW_ICE_SIZE), &
               ZNOT_NEW_ICE_LAT(IOUTSIDE_NEW_ICE_SIZE), &
               NN_NEW_ICE(IOUTSIDE_NEW_ICE_SIZE))

      ALLOCATE(INEW_ICE_MASK(INEW_ICE_SIZE), &
               ZNEW_ICE_LON(INEW_ICE_SIZE), &
               ZNEW_ICE_LAT(INEW_ICE_SIZE), &
               NN_INSIDE_NEW_ICE(INEW_ICE_SIZE))

      JINOT_NEW_ICE = 1
      JINEW_ICE = 1

      DO JI = 1, KSIZE_TOT
        IF( ZSIC_TOT_OLD(JI) > 0. .OR. .NOT. ZSIC_TOT_NEW(JI) > 0.) THEN
          INOT_NEW_ICE_MASK(JINOT_NEW_ICE) = JI
          ZNOT_NEW_ICE_LON(JINOT_NEW_ICE) = PLON_TOT(JI)
          ZNOT_NEW_ICE_LAT(JINOT_NEW_ICE) = PLAT_TOT(JI)

          JINOT_NEW_ICE = JINOT_NEW_ICE + 1
        ELSE
          INEW_ICE_MASK(JINEW_ICE) = JI
          ZNEW_ICE_LON(JINEW_ICE) = PLON_TOT(JI)
          ZNEW_ICE_LAT(JINEW_ICE) = PLAT_TOT(JI)

          JINEW_ICE = JINEW_ICE + 1
        END IF
      END DO

      CALL NEAREST_NEIGHBOUR_QUERY(PLON_TOT, PLAT_TOT, ZNOT_NEW_ICE_LON, ZNOT_NEW_ICE_LAT, &
        O_INPUT_MASK = .NOT. ZSIC_TOT_OLD > 0. .AND. ZSIC_TOT_NEW > 0., P_DIST = NN_NEW_ICE)

      ALLOCATE(ZSDF_NEW_ICE(KSIZE_TOT))
      ZSDF_NEW_ICE = 0.
      ZSDF_NEW_ICE(INOT_NEW_ICE_MASK) = NN_NEW_ICE

      CALL NEAREST_NEIGHBOUR_QUERY(PLON_TOT, PLAT_TOT, ZNEW_ICE_LON, ZNEW_ICE_LAT, &
        O_INPUT_MASK = (ZSIC_TOT_OLD > 0. .OR. .NOT. ZSIC_TOT_NEW > 0. ) .AND. ZSDF_NEW_ICE < 1.E+5, P_DIST = NN_INSIDE_NEW_ICE)

      ZSDF_NEW_ICE(INEW_ICE_MASK) = - NN_INSIDE_NEW_ICE

      ISMOOTH_SIZE = COUNT(ZSDF_NEW_ICE < SMOOTHE_RADIUS .AND. ZSDF_NEW_ICE > EXTRAPOL_TOLERANCE)

      ALLOCATE(ISMOOTH_MASK(ISMOOTH_SIZE), INVERSE_SMOOTH_MASK(KSIZE_TOT))
      INVERSE_SMOOTH_MASK = 0

      JISMOOTH = 1
      DO JI = 1, KSIZE_TOT
        IF(ZSDF_NEW_ICE(JI) < SMOOTHE_RADIUS .AND. ZSDF_NEW_ICE(JI) > EXTRAPOL_TOLERANCE) THEN
          ISMOOTH_MASK(JISMOOTH) = JI
          INVERSE_SMOOTH_MASK(JI) = JISMOOTH

          JISMOOTH = JISMOOTH + 1
        END IF
      END DO

      ALLOCATE(ZTICE_REG(ISMOOTH_SIZE), &
               ZICE_SHAPE_REG(ISMOOTH_SIZE), &
               ZSDF_REG(ISMOOTH_SIZE), &
               ZSDF_NEW_ICE_REG(ISMOOTH_SIZE), &
               ZLON_REG(ISMOOTH_SIZE), &
               ZLAT_REG(ISMOOTH_SIZE) )

      ZTICE_REG(:) = ZTICE_TOT(ISMOOTH_MASK)
      ZICE_SHAPE_REG(:) = ZICE_SHAPE_TOT(ISMOOTH_MASK)
      ZSDF_REG(:) = ZSDF(ISMOOTH_MASK)
      ZSDF_NEW_ICE_REG(:) = ZSDF_NEW_ICE(ISMOOTH_MASK)

      ZLON_REG(:) = PLON_TOT(ISMOOTH_MASK)
      ZLAT_REG(:) = PLAT_TOT(ISMOOTH_MASK)

      DO JI = 1, INEW_ICE_SIZE
        JICURR_POS = INVERSE_SMOOTH_MASK(INEW_ICE_MASK(JI))
        IF(JICURR_POS == 0) CYCLE
        CALL SMOOTHE(JICURR_POS, ZLON_REG, ZLAT_REG, ZSDF_NEW_ICE_REG, INDICES, ZWEIGHTS)
        ZTOTAL_WEIGHT = SUM(ZWEIGHTS)

        ZTICE_TOT(INEW_ICE_MASK(JI)) = SUM(ZWEIGHTS(:)*ZTICE_REG(INDICES))/ZTOTAL_WEIGHT
        ZICE_SHAPE_TOT(INEW_ICE_MASK(JI)) = SUM(ZWEIGHTS(:)*ZICE_SHAPE_REG(INDICES))/ZTOTAL_WEIGHT
        ZSDF(INEW_ICE_MASK(JI)) = SUM(ZWEIGHTS(:)*ZSDF_REG(INDICES))/ZTOTAL_WEIGHT
      END DO
      CALL NEAREST_NEIGHBOUR_QUERY(ZLON_REG, ZLAT_REG, 0., 0., K_NUMN=0, O_CLEANUP=.TRUE.)

      DEALLOCATE(ZSDF_NEW_ICE, ISMOOTH_MASK, INVERSE_SMOOTH_MASK)

      DEALLOCATE(ZTICE_REG, ZICE_SHAPE_REG, ZSDF_REG, ZSDF_NEW_ICE_REG, ZLON_REG, ZLAT_REG)

      DEALLOCATE(NN_INDEX)
      DEALLOCATE(ZNOT_NEW_ICE_LON, ZNOT_NEW_ICE_LAT, NN_NEW_ICE)
      DEALLOCATE(ZNEW_ICE_LON, ZNEW_ICE_LAT, NN_INSIDE_NEW_ICE)
      DEALLOCATE(INOT_NEW_ICE_MASK)
    END IF HAS_NEW_ICE
  END IF

  ! Send processed data back
  PTICE_TOT = ZTICE_TOT
  PICE_SHAPE_TOT = ZICE_SHAPE_TOT
  PZICE_TOT = ZZICE_TOT
  PSDF_TOT = ZSDF

  IF(.NOT. GMISSING_ICE) THEN
    OMISSING_OLD_ICE = .FALSE.
    PICE_EDGE_THK = ZICE_EDGE_THK
  ELSE
    OMISSING_OLD_ICE = .TRUE.
    PICE_EDGE_THK = 0.
  END IF

  DEALLOCATE(ZSDF, ZSIC_TOT_OLD, ZSIC_TOT_NEW)
  DEALLOCATE(ZTICE_TOT, ZICE_SHAPE_TOT)

  IF (LHOOK) CALL DR_HOOK('SEAICE_SICE_PROPAGATE_ICE', 1, ZHOOK_HANDLE)
CONTAINS
SUBROUTINE SMOOTHE(KCURR, PLON_TOT, PLAT_TOT, PSDF, KINDICES, PWEIGHTS)
USE NN_EXTRAPOLATE, ONLY: NEAREST_NEIGHBOUR_QUERY
IMPLICIT NONE
  INTEGER, INTENT(IN) :: KCURR
  REAL, INTENT(IN) :: PLON_TOT(:)
  REAL, INTENT(IN), DIMENSION(SIZE(PLON_TOT)) :: &
    PLAT_TOT, PSDF
  REAL, INTENT(OUT) :: PWEIGHTS(:)
  INTEGER, INTENT(OUT), DIMENSION(SIZE(PWEIGHTS)) :: &
    KINDICES

  REAL, PARAMETER :: SMOOTHING_PAR = 8.E-5

  REAL :: ZDIST(SIZE(KINDICES))

  INTEGER :: JI, INN_COUNT
  REAL :: ZLON, ZLAT, ZWEIGHT

  INN_COUNT = SIZE(KINDICES)

  ZLON = PLON_TOT(KCURR)
  ZLAT = PLAT_TOT(KCURR)

  CALL NEAREST_NEIGHBOUR_QUERY(PLON_TOT, PLAT_TOT, ZLON, ZLAT, K_NUMN=INN_COUNT, K_INDEX=KINDICES, P_DIST=ZDIST)

  PWEIGHTS(:) = EXP(- ZDIST(:)*SMOOTHING_PAR)
  WHERE(KINDICES == 0)
    KINDICES = 1
    PWEIGHTS = 0.
  ENDWHERE
END SUBROUTINE SMOOTHE
END SUBROUTINE SEAICE_SICE_PROPAGATE_ICE
