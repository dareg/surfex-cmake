!     #########
      SUBROUTINE TRIP_DIAG_WRITE(KLISTING,KLON,KLAT,KDIAG,PTSTEP_DIAG)  
!     ############################################################
!
!!****  *TRIP_DIAG_WRITE*  
!!
!!    PURPOSE
!!    -------
!
!     TRIP river routing outputs.
!     
!!      
!!    AUTHOR
!!    ------
!!	B. Decharme     
!!
!!    MODIFICATIONS
!!    -------------
!!      Original    28/05/05 
!-------------------------------------------------------------------------------
!
!*       0.     DECLARATIONS
!               ------------
!
USE MODN_TRIP,       ONLY : CGROUNDW, CVIT, LFLOOD
USE MODN_TRIP_RUN,   ONLY : LDIAG_MISC
USE MODD_TRIP_OASIS, ONLY : LCPL_LAND
!
USE MODD_TRIP_PAR,   ONLY : XTIME_DIAG
!
USE MODD_TRIP_GRID,  ONLY : TGRID
!
USE MODD_TRIP_DIAG
!
USE MODE_RW_TRIP
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE
!
!*      0.1    declarations of arguments
!
INTEGER, INTENT(IN)             :: KLISTING
INTEGER, INTENT(IN)             :: KLON
INTEGER, INTENT(IN)             :: KLAT
INTEGER, INTENT(IN)             :: KDIAG
REAL,    INTENT(IN)             :: PTSTEP_DIAG
!
!*      0.2    declarations of local variables
!
CHARACTER(LEN=19), PARAMETER         :: YDIAG  = 'TRIP_DIAG.nc'
CHARACTER(LEN=50)                    :: YFILE
CHARACTER(LEN=10)                    :: YVNAME
!
REAL,   DIMENSION(KLON,KLAT)         :: ZWRITE
LOGICAL,DIMENSION(KLON,KLAT)         :: LMASK
LOGICAL,DIMENSION(KLON,KLAT)         :: LMASK_GW
!
INTEGER :: ITNUM, ITVAL
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
!-------------------------------------------------------------------------------
!
IF (LHOOK) CALL DR_HOOK('TRIP_DIAG_WRITE',0,ZHOOK_HANDLE)
!
! * Trip mask
!
LMASK(:,:) = TGRID%GMASK(:,:)
!
! * Groundwater specific mask
!
IF(CGROUNDW/='DEF')THEN
  LMASK_GW(:,:) = TGRID%GMASK_GW(:,:)        
ENDIF
!
!-------------------------------------------------------------------------------
!outputs
!-------------------------------------------------------------------------------
!
! * Recup diag file
!
YFILE =YDIAG
!
! * Time attribut
!
ITNUM = KDIAG
ITVAL = (KDIAG-1)*INT(PTSTEP_DIAG/XTIME_DIAG)
!
!
! * Store output in diag file
!
YVNAME = 'SURF_STO'
ZWRITE = TDIAG%XSURF_STO / PTSTEP_DIAG
CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)   
CALL CUM_DIAG(TDIAG%XSURF_STO,TDIAG_RUN%XSURF_STO)
!                
YVNAME = 'QDIS'
ZWRITE = TDIAG%XQDIS / PTSTEP_DIAG
CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
CALL CUM_DIAG(TDIAG%XQDIS,TDIAG_RUN%XQDIS)
!
IF(LDIAG_MISC)THEN                
  YVNAME = 'QSIN'
  ZWRITE = TDIAG%XQIN / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XQIN,TDIAG_RUN%XQIN)
ENDIF
!
IF(LCPL_LAND.AND.LDIAG_MISC)THEN                
! kg/m2         
  YVNAME = 'RUNOFF'
  ZWRITE = TDIAG%XRUNOFF
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XRUNOFF,TDIAG_RUN%XRUNOFF)
! kg/m2         
  YVNAME = 'DRAIN'
  ZWRITE = TDIAG%XDRAIN
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XDRAIN,TDIAG_RUN%XDRAIN)
!          
ENDIF
!
IF(CGROUNDW/='DEF')THEN          
  YVNAME = 'QGF'
  ZWRITE = TDIAG%XQGF / PTSTEP_DIAG 
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XQGF,TDIAG_RUN%XQGF)
ENDIF
!
IF(CGROUNDW=='CST')THEN
!          
  YVNAME = 'GROUND_STO'
  ZWRITE = TDIAG%XGROUND_STO / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
  CALL CUM_DIAG(TDIAG%XGROUND_STO,TDIAG_RUN%XGROUND_STO)
!    
ELSEIF(CGROUNDW=='DIF')THEN
!
  YVNAME = 'HGROUND'
  ZWRITE = TDIAG%XHGROUND / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XHGROUND,TDIAG_RUN%XHGROUND)
!       
  YVNAME = 'FWTD'
  ZWRITE = TDIAG%XFWTD / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)  
  CALL CUM_DIAG(TDIAG%XFWTD,TDIAG_RUN%XFWTD)
!       
  YVNAME = 'WTD'
  ZWRITE = TDIAG%XWTD / PTSTEP_DIAG 
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XWTD,TDIAG_RUN%XWTD)
!   
  IF(LDIAG_MISC)THEN      
!       
      YVNAME = 'WTDRIV'
      ZWRITE = TDIAG%XWTDRIV / PTSTEP_DIAG
      CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)    
      CALL CUM_DIAG(TDIAG%XWTDRIV,TDIAG_RUN%XWTDRIV)
!       
      YVNAME = 'WTDELEV'
      ZWRITE = TDIAG%XWTDELEV / PTSTEP_DIAG
      CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)    
      CALL CUM_DIAG(TDIAG%XWTDELEV,TDIAG_RUN%XWTDELEV)
!      
      YVNAME = 'QGCELL'
      ZWRITE = TDIAG%XQGCELL / PTSTEP_DIAG 
      CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)
      CALL CUM_DIAG(TDIAG%XQGCELL,TDIAG_RUN%XQGCELL)
!       
      YVNAME = 'HGHRIV'
      ZWRITE = TDIAG%XHGHS / PTSTEP_DIAG
      CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK_GW,ZWRITE,ITNUM,ITVAL)
      CALL CUM_DIAG(TDIAG%XHGHS,TDIAG_RUN%XHGHS)
!
  ENDIF
! 
ENDIF
!
IF(CVIT=='VAR')THEN
!
  YVNAME = 'VEL'
  ZWRITE = TDIAG%XVEL / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)
  CALL CUM_DIAG(TDIAG%XVEL,TDIAG_RUN%XVEL)
!
  YVNAME = 'HSTREAM'
  ZWRITE = TDIAG%XHS / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
  CALL CUM_DIAG(TDIAG%XHS,TDIAG_RUN%XHS)
!
ENDIF
!
IF(LFLOOD)THEN
!
  YVNAME = 'FFLOOD'
  ZWRITE = TDIAG%XFF / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)   
  CALL CUM_DIAG(TDIAG%XFF,TDIAG_RUN%XFF)
!
  YVNAME = 'FLOOD_STO'
  ZWRITE = TDIAG%XFLOOD_STO / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)   
  CALL CUM_DIAG(TDIAG%XFLOOD_STO,TDIAG_RUN%XFLOOD_STO)
!
  YVNAME = 'HFLOOD'
  ZWRITE = TDIAG%XHF / PTSTEP_DIAG
  CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)  
  CALL CUM_DIAG(TDIAG%XHF,TDIAG_RUN%XHF)
!
  IF(LDIAG_MISC)THEN
!
    YVNAME = 'QFR'
    ZWRITE = TDIAG%XQFR / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)  
    CALL CUM_DIAG(TDIAG%XQFR,TDIAG_RUN%XQFR)
!                
    YVNAME = 'QRF'
    ZWRITE = TDIAG%XQRF / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
    CALL CUM_DIAG(TDIAG%XQRF,TDIAG_RUN%XQRF)
!
    YVNAME = 'FSOURCE'
    ZWRITE = TDIAG%XSOURCE / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
    CALL CUM_DIAG(TDIAG%XSOURCE,TDIAG_RUN%XSOURCE)
!
    YVNAME = 'VFIN'
    ZWRITE = TDIAG%XVFIN / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
    CALL CUM_DIAG(TDIAG%XVFIN,TDIAG_RUN%XVFIN) 
!
    YVNAME = 'VFOUT'
    ZWRITE = TDIAG%XVFOUT / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL) 
    CALL CUM_DIAG(TDIAG%XVFOUT,TDIAG_RUN%XVFOUT)
!
    YVNAME = 'HSF'
    ZWRITE = TDIAG%XHSF / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)
    CALL CUM_DIAG(TDIAG%XHSF,TDIAG_RUN%XHSF)
!
    YVNAME = 'WF'
    ZWRITE = TDIAG%XWF / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)  
    CALL CUM_DIAG(TDIAG%XWF,TDIAG_RUN%XWF)
!
    YVNAME = 'LF'
    ZWRITE = TDIAG%XLF / PTSTEP_DIAG
    CALL WRITE_TRIP(KLISTING,YFILE,YVNAME,LMASK,ZWRITE,ITNUM,ITVAL)
    CALL CUM_DIAG(TDIAG%XLF,TDIAG_RUN%XLF)
!      
  ENDIF
!
ENDIF
!
IF (LHOOK) CALL DR_HOOK('TRIP_DIAG_WRITE',1,ZHOOK_HANDLE)
!
!-------------------------------------------------------------------------------
CONTAINS
!-------------------------------------------------------------------------------
!
SUBROUTINE CUM_DIAG(PDIAG,PRUN)
!
IMPLICIT NONE
!
REAL, DIMENSION(:,:),INTENT(INOUT) :: PDIAG
REAL, DIMENSION(:,:),INTENT(OUT  ) :: PRUN
!
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('TRIP_DIAG_WRITE:CUM_DIAG',0,ZHOOK_HANDLE)
!
PRUN(:,:) = PRUN(:,:) + PDIAG(:,:)
!
PDIAG(:,:) = 0.0
!
IF (LHOOK) CALL DR_HOOK('TRIP_DIAG_WRITE:CUM_DIAG',1,ZHOOK_HANDLE)
!
END SUBROUTINE CUM_DIAG
!
!-------------------------------------------------------------------------------
END SUBROUTINE TRIP_DIAG_WRITE
