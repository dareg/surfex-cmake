      SUBROUTINE FACAGE(CDNOMC, LDGARD )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      LOGICAL LDGARD
      CHARACTER CDNOMC*(*)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FACAGE_MT (FA_COM_DEFAULT, CDNOMC, LDGARD )
      END SUBROUTINE

