C Jan-2011 P. Marguinaud Interface to thread-safe FA
      SUBROUTINE FACIES(CDNOMC, KTYPTR, PSLAPO, PCLOPO, PSLOPO,
     S                    PCODIL, KTRONC, KNLATI, KNXLON, KNLOPA,
     S                    KNOZPA, PSINLA, KNIVER, PREFER, PAHYBR,
     S                    PBHYBR, LDGARD )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
#include "precision.h"
      INTEGER KTYPTR, KTRONC, KNLATI, KNXLON, KNIVER
      INTEGER KNLOPA (FA_COM_DEFAULT%JPXPAH), 
     S        KNOZPA (FA_COM_DEFAULT%JPXIND)
      REAL (KIND=JPDBLR) PSLAPO, PCLOPO, PSLOPO, PCODIL, PREFER
      REAL (KIND=JPDBLR) PSINLA (FA_COM_DEFAULT%JPXGEO), 
     S                   PAHYBR (0:FA_COM_DEFAULT%JPXNIV)
      REAL (KIND=JPDBLR) PBHYBR (0:FA_COM_DEFAULT%JPXNIV)
      CHARACTER CDNOMC*(*)
      LOGICAL LDGARD
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FACIES_MT (FA_COM_DEFAULT, CDNOMC, KTYPTR, PSLAPO, PCLOPO, 
     S                PSLOPO, PCODIL, KTRONC, KNLATI, KNXLON, KNLOPA,
     S                KNOZPA, PSINLA, KNIVER, PREFER, PAHYBR,
     S                PBHYBR, LDGARD )
      END SUBROUTINE

