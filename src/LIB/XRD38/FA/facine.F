C Jan-2011 P. Marguinaud Interface to thread-safe FA
      SUBROUTINE FACINE(KREP,   KRANG,  CDNOMA, KCHAMP, LDCOSP,
     S                      KVALCO, KLONGD, KB1PAR )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
#include "precision.h"
      INTEGER KREP, KRANG, KLONGD
      INTEGER (KIND=JPDBLE) KCHAMP(*), KVALCO(*)
      INTEGER KB1PAR (FA_COM_DEFAULT%JPLB1P)
      LOGICAL LDCOSP
      CHARACTER CDNOMA*(*)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FACINE_MT (FA_COM_DEFAULT, KREP,   KRANG,  CDNOMA, KCHAMP, 
     S                LDCOSP, KVALCO, KLONGD, KB1PAR )
      END SUBROUTINE

