C Jan-2011 P. Marguinaud Interface to thread-safe FA
      SUBROUTINE FACODX(KREP,   KRANG,  CDPREF, KNIVAU, CDSUFF,
     S                  PSEC4, LDCOSP, KVALCO, KLONGD )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
#include "precision.h"
      INTEGER KREP, KRANG, KNIVAU, KLONGD
      INTEGER (KIND=JPDBLE) KVALCO(*)
      REAL (KIND=JPDBLR) PSEC4(*)
      LOGICAL LDCOSP
      CHARACTER CDPREF*(*), CDSUFF*(*)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FACODX_MT (FA_COM_DEFAULT, KREP,   KRANG,  CDPREF, KNIVAU, 
     S                CDSUFF, PSEC4, LDCOSP, KVALCO, KLONGD )
      END SUBROUTINE

