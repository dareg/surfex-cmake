      SUBROUTINE FAGOTE(KREP, KNUMER, KNGRIB, KNBPDG, KNBCSP, 
     S                      KSTRON, KPUILA, KDMOPL )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KNUMER, KNGRIB, KNBPDG, KNBCSP, KSTRON, KPUILA
      INTEGER KDMOPL
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FAGOTE_MT (FA_COM_DEFAULT, KREP, KNUMER, KNGRIB, KNBPDG, 
     S                KNBCSP, KSTRON, KPUILA, KDMOPL )
      END SUBROUTINE

