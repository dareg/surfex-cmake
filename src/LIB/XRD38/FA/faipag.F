      SUBROUTINE FAIPAG(KREP, KRANG,  CDPREF, KNIVAU, CDSUFF,
     S                  KNIPAR )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KRANG, KNIVAU, KNIPAR(6)
      CHARACTER (LEN=*) CDPREF, CDSUFF
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FAIPAG_MT (FA_COM_DEFAULT, KREP, KRANG, CDPREF, KNIVAU, 
     S                CDSUFF, KNIPAR )
      END SUBROUTINE

