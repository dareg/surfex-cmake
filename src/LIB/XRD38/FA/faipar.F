      SUBROUTINE FAIPAR(KNUMER, KNIMES, KCODE, LDFATA, CDMESS, 
     S                      CDNSPR, CDACTI, LDRLFI )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KNUMER, KNIMES, KCODE
      LOGICAL LDFATA, LDRLFI
      CHARACTER  CDNSPR*(*), CLJOLI*6, CDMESS*(*), CLMESA*80, CDACTI*(*)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FAIPAR_MT (FA_COM_DEFAULT, KNUMER, KNIMES, KCODE, LDFATA, 
     S                CDMESS, CDNSPR, CDACTI, LDRLFI )
      END SUBROUTINE

