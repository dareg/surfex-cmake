      SUBROUTINE FAIRNO(KREP, KNUMER, CDSTTU )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KNUMER
      CHARACTER CDSTTU*(*), CLSTTU*7
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FAIRNO_MT (FA_COM_DEFAULT, KREP, KNUMER, CDSTTU )
      END SUBROUTINE

