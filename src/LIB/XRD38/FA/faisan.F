      SUBROUTINE FAISAN(KREP, KNUMER, CDNOMA, PDONNE, KLONGD )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
#include "precision.h"
      INTEGER KREP, KNUMER, KLONGD
      REAL (KIND=JPDBLR) PDONNE (KLONGD)
      CHARACTER CDNOMA*(*)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FAISAN_MT (FA_COM_DEFAULT, KREP, KNUMER, CDNOMA, 
     S                PDONNE, KLONGD )
      END SUBROUTINE

