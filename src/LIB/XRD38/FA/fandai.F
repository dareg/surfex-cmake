      SUBROUTINE FANDAI(KREP, KRANG, KDATEF, LDMODA )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KRANG
      INTEGER KDATEF (FA_COM_DEFAULT%JPLDAT)
      LOGICAL LDMODA
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FANDAI_MT (FA_COM_DEFAULT, KREP, KRANG, KDATEF, LDMODA )
      END SUBROUTINE

