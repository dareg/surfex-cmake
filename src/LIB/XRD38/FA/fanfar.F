      SUBROUTINE FANFAR(KREP, KRANG, CDPREF, KNIVAU, CDSUFF, 
     S                  CDNOMA, KB1PAR, KLPRFU, KLSUFU, KLNOMU )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KRANG, KNIVAU, KLPRFU, KLSUFU, KLNOMU
      INTEGER KB1PAR (3)
      CHARACTER CDPREF*(*), CDSUFF*(*), CDNOMA*(*)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FANFAR_MT (FA_COM_DEFAULT, KREP, KRANG, CDPREF, KNIVAU, 
     S                CDSUFF, CDNOMA, KB1PAR, KLPRFU, KLSUFU, KLNOMU )
      END SUBROUTINE

