      SUBROUTINE FANUCA(CDNOMC, KRANGC, LDVERR )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KRANGC
      CHARACTER CDNOMC*(*)
      LOGICAL LDVERR
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FANUCA_MT (FA_COM_DEFAULT, CDNOMC, KRANGC, LDVERR )
      END SUBROUTINE

