      SUBROUTINE FARCIS(KREP, KRANG, PCHAMP, KSTRON, KPUILA )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
#include "precision.h"
      INTEGER KREP, KRANG, KSTRON, KPUILA
      REAL (KIND=JPDBLR) PCHAMP (FA_COM_DEFAULT%JPXCSP)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FARCIS_MT (FA_COM_DEFAULT, KREP, KRANG, PCHAMP, 
     S                KSTRON, KPUILA )
      END SUBROUTINE

