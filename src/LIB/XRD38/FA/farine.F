      SUBROUTINE FARINE(KOPTIO )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KOPTIO
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FARINE_MT (FA_COM_DEFAULT, KOPTIO )
      END SUBROUTINE

