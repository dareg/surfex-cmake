      SUBROUTINE FARPAR(KREP, CDPREF, CDSUFF, KCODPA, KNUM )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KNUM
      INTEGER KCODPA(KNUM,6)
      CHARACTER (LEN=*) CDPREF(KNUM), CDSUFF(KNUM)
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FARPAR_MT (FA_COM_DEFAULT, KREP, CDPREF, CDSUFF, 
     S                KCODPA, KNUM )
      END SUBROUTINE

