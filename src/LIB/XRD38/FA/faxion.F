C Jan-2011 P. Marguinaud Interface to thread-safe FA
      SUBROUTINE FAXION(PCHAME, KPUISS, KDIMNC, KLCHAM, PMIN, 
     S                  PMAX,
     S                  KNBITS, LDARPE, PECART, LDMLAM, KNOZPA,
     S                  KSTROF, KTRONC, KXLOPA )
      USE FA_MOD, ONLY : FA_COM_DEFAULT,
     S                   FA_COM_DEFAULT_INIT,
     S                   NEW_FA_DEFAULT
      IMPLICIT NONE
#include "precision.h"
      INTEGER KPUISS, KDIMNC, KLCHAM, KNBITS, KSTROF
      INTEGER KTRONC, KXLOPA
      INTEGER KNOZPA (FA_COM_DEFAULT%JPXIND)
      REAL (KIND=JPDBLR) PMIN, PMAX, PECART
      REAL (KIND=JPDBLR) PCHAME(KLCHAM)
      LOGICAL LDARPE, LDMLAM
      IF (.NOT. FA_COM_DEFAULT_INIT) CALL NEW_FA_DEFAULT ()
      CALL FAXION_MT (FA_COM_DEFAULT, PCHAME, KPUISS, KDIMNC, KLCHAM, 
     S                PMIN, PMAX,
     S                KNBITS, LDARPE, PECART, LDMLAM, KNOZPA,
     S                KSTROF, KTRONC, KXLOPA )
      END SUBROUTINE

