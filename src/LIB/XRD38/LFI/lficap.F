     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      CHARACTER CDNOMA*(*), CLNOMA*(LFICOM_DEFAULT%JPNCPN)
      INTEGER KREP, KNUMER, KLONG, KPOSEX
      LOGICAL LDRECU
