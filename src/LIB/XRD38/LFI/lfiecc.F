      SUBROUTINE LFIECC ( KREP, KNUMER, KREC, CDTAB, KNBECR, 
     S                      KFACTM, KRETIN )
      USE LFIMOD, ONLY : LFICOM_DEFAULT,
     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KNUMER, KREC, KNBECR, KFACTM, KRETIN
      CHARACTER CDTAB (LFICOM_DEFAULT%JPNXNA*KFACTM)
     S             *(LFICOM_DEFAULT%JPNCPN)
      IF (.NOT. LFICOM_DEFAULT_INIT) CALL NEW_LFI_DEFAULT ()
      CALL LFIECC_MT (LFICOM_DEFAULT, KREP, KNUMER, KREC, CDTAB, KNBECR, 
     S                      KFACTM, KRETIN )
      END SUBROUTINE

