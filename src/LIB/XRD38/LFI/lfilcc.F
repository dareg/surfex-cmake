      SUBROUTINE LFILCC ( KREP, KNUMER, KREC, CDTAB, 
     S                      KNBLEC, KFACTM, KRETIN )
      USE LFIMOD, ONLY : LFICOM_DEFAULT,
     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KNUMER, KREC, KNBLEC, KFACTM, KRETIN
      CHARACTER CDTAB (LFICOM_DEFAULT%JPNXNA*KFACTM)
     S                     *(LFICOM_DEFAULT%JPNCPN)
      IF (.NOT. LFICOM_DEFAULT_INIT) CALL NEW_LFI_DEFAULT ()
      CALL LFILCC_MT (LFICOM_DEFAULT, KREP, KNUMER, KREC, CDTAB, 
     S                      KNBLEC, KFACTM, KRETIN )
      END SUBROUTINE

