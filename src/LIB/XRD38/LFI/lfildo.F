C Jan-2011 P. Marguinaud Interface to thread-safe LFI
      SUBROUTINE LFILDO ( KREP, KNUMER, KREC, KTAB, KNBLEC, 
     S                      KFACTM, KRETIN )
      USE LFIMOD, ONLY : LFICOM_DEFAULT,
     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      INTEGER KREP, KNUMER, KREC, KNBLEC, KFACTM, KRETIN
#ifndef f77
#include "precision.h"
      INTEGER (KIND=JPDBLE)  KTAB (LFICOM_DEFAULT%JPLARD*KFACTM)
#else
      INTEGER KTAB (LFICOM_DEFAULT%JPLARD*KFACTM)
#endif
      IF (.NOT. LFICOM_DEFAULT_INIT) CALL NEW_LFI_DEFAULT ()
      CALL LFILDO_MT (LFICOM_DEFAULT, KREP, KNUMER, KREC, KTAB, KNBLEC, 
     S                      KFACTM, KRETIN )
      END SUBROUTINE

