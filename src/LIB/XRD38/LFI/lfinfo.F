      SUBROUTINE LFINFO ( KREP, KNUMER, CDNOMA, KLONG, KPOSEX )
      USE LFIMOD, ONLY : LFICOM_DEFAULT,
     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      CHARACTER CDNOMA*(*)
      INTEGER KREP, KNUMER, KLONG, KPOSEX
      IF (.NOT. LFICOM_DEFAULT_INIT) CALL NEW_LFI_DEFAULT ()
      CALL LFINFO_MT (LFICOM_DEFAULT, KREP, 
     S                KNUMER, CDNOMA, KLONG, KPOSEX )
      END SUBROUTINE

