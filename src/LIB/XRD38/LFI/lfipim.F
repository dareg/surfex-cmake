      SUBROUTINE LFIPIM ( KREP ,KRANG, KRANGM, KRGPIM, 
     S                      KRGPIF, KRGFOR, KNPILE, KRETIN )
      USE LFIMOD, ONLY : LFICOM_DEFAULT,
     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      INTEGER KREP ,KRANG, KRANGM, KRGPIM, KRGPIF, KRGFOR, KNPILE
      INTEGER KRETIN
