     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
      CHARACTER CDNOMA*(*), CDSUIV*(*), CDSTRU*(*)
      INTEGER KREP, KNUMER, KLSUIV
