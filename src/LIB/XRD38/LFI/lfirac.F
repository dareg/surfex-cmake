C Jan-2011 P. Marguinaud Interface to thread-safe LFI
      SUBROUTINE LFIRAC ( KNOMAR, KNALPI, KCLE, KINDIC, KNBVAL )
      USE LFIMOD, ONLY : LFICOM_DEFAULT,
     S                   LFICOM_DEFAULT_INIT,
     S                   NEW_LFI_DEFAULT
      IMPLICIT NONE
#ifndef f77
#include "precision.h"
      INTEGER (KIND=JPDBLE) KNOMAR (LFICOM_DEFAULT%JPNMPN,
     S                              LFICOM_DEFAULT%JPNAPX),
     S                      KCLE (LFICOM_DEFAULT%JPNMPN)
#else
      INTEGER KNOMAR (LFICOM_DEFAULT%JPNMPN,LFICOM_DEFAULT%JPNAPX), 
     S        KCLE (LFICOM_DEFAULT%JPNMPN)
#endif
      INTEGER KNALPI, KNBVAL, KINDIC (LFICOM_DEFAULT%JPNAPX)
      IF (.NOT. LFICOM_DEFAULT_INIT) CALL NEW_LFI_DEFAULT ()
      CALL LFIRAC_MT (LFICOM_DEFAULT, KNOMAR, KNALPI, 
     S                KCLE, KINDIC, KNBVAL )
      END SUBROUTINE

