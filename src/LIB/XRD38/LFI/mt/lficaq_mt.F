C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFICAQ_MT (LFI, KREP, KRANG, KRGPIM, KARTEX, KRETIN )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        SOUS-PROGRAMME *INTERNE* DU LOGICIEL DE FICHIERS INDEXES LFI;
C     RECHERCHE DE L'ARTICLE LOGIQUE *DE DONNEES* PRECEDENT, DANS UNE
C     UNITE LOGIQUE DONNEE.
C**
C    ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                KRANG  (ENTREE) ==> RANG ( DANS LA TABLE *LFI%NUMERO* )
C                                    DE L'UNITE LOGIQUE CONCERNEE;
C                KRGPIM (SORTIE) ==> RANG DANS LES TABLES LFI%CNOMAR,LFI%MLGPOS,
C                                    ETC. DE LA P.P.I OU FIGURE
C                                    L'ARTICLE ( 0 SI PAS TROUVE );
C                KARTEX (SORTIE) ==> RANG ( DANS LA PAGE D'INDEX ) DE L'
C                                    ARTICLE S'IL EXISTE ( 0 SINON );
C                KRETIN (SORTIE) ==> CODE-RETOUR INTERNE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KREP, KRANG, KRGPIM, KARTEX, IRANG, INBALO, INALPP, INTPPI
      INTEGER INPPIM, IDERGF, IRANGF, IRGPIF, IRGPIM, IRANGM, ILFORC, J
      INTEGER INPILE, IARTIK, IARTIC, IRETOU, INIMES, INUMER, KRETIN
      INTEGER IRETIN
C
#include "lficom2.h"
#include "lficom_mt.h"
C**
C     1.  -  CONTROLES DES PARAMETRES D'APPEL, PUIS INITIALISATIONS.
C-----------------------------------------------------------------------
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFICAQ_MT',0,ZHOOK_HANDLE)
      IRETOU=0
C
      IF (KRANG.LE.0.OR.KRANG.GT.LFI%JPNXFI) THEN
        KREP=-16
        GOTO 1001
      ENDIF
C
      IRANG=KRANG
      KREP=0
      KRGPIM=0
      KARTEX=0
      INBALO=LFI%MDES1D(IXM(LFI%JPNALO,IRANG))
      INALPP=LFI%JPNAPP*LFI%MFACTM(IRANG)
      INTPPI=(INBALO-1+INALPP)/INALPP
      INPPIM=LFI%NPPIMM(IRANG)
C
      IF (LFI%NPRECF(IRANG).EQ.LFI%JPNIL) THEN
C
C           ON N'A DONC PAS ENCORE APPELE CE SOUS-PROGRAMME POUR
C        RECHERCHER CET ARTICLE ( A PRIORI, VIA *LFICAP* ) .
C
        IF (LFI%NDERGF(IRANG).EQ.LFI%JPNIL) THEN
          IDERGF=INBALO+1
        ELSE
          IDERGF=LFI%NDERGF(IRANG)
        ENDIF
C
        IF (IDERGF.LE.1) THEN
          LFI%NPRECF(IRANG)=0
          GOTO 1001
        ENDIF
C
        IRANGF=IDERGF-1
C
      ELSEIF (LFI%NPRECF(IRANG).EQ.0) THEN
C
C        PLUS D'ARTICLE LOGIQUE "PRECEDENT" A LIRE .
C
        GOTO 1001
      ELSEIF (LFI%NDERGF(IRANG).EQ.LFI%JPNIL.OR.
     S        LFI%NPRECF(IRANG).LT.LFI%NDERGF(IRANG)) THEN
        IRANGF=LFI%NPRECF(IRANG)
      ELSE
        KREP=-16
        GOTO 1001
      ENDIF
C**
C     2.  -  EXPLORATION DES (PAIRES DE) PAGES ET ARTICLES D'INDEX,
C            A LA RECHERCHE DE L'ARTICLE LOGIQUE DEMANDE,
C            DEFINI PAR SON RANG "A PRIORI" DANS LE FICHIER.
C            ( MAIS IL FAUT "SAUTER" LES TROUS )
C-----------------------------------------------------------------------
C*
C     2.1 -  RECHERCHE DANS LES PAGES D'INDEX .
C-----------------------------------------------------------------------
C
      IRGPIF=1+(IRANGF-1)/INALPP
C
  211 CONTINUE
C
      IF (IRANGF.LE.INALPP) THEN
        IRGPIM=LFI%MRGPIM(1,IRANG)
        GOTO 215
      ELSEIF (IRANGF.GT.INALPP*(INTPPI-1)) THEN
        IRGPIM=LFI%MRGPIM(LFI%NPODPI(IRANG),IRANG)
        GOTO 215
      ENDIF
C
      DO 213 J=2,INPPIM
      IRGPIM=LFI%MRGPIM(J,IRANG)
      IF (LFI%MRGPIF(IRGPIM).EQ.IRGPIF) GOTO 215
  213 CONTINUE
C
C        MISE EN MEMOIRE DE L'ARTICLE D'INDEX "NOMS" CHERCHE.
C
      ILFORC=1
      INPILE=1
      CALL LFIPIM_MT (LFI, KREP,IRANG,IRANGM,IRGPIM,IRGPIF,
     S                ILFORC,INPILE,IRETIN)
C
      IF (IRETIN.EQ.1) THEN
        GOTO 903
      ELSEIF (IRETIN.EQ.2) THEN
        GOTO 904
      ELSEIF (IRETIN.NE.0) THEN
        GOTO 1001
      ENDIF
C
      INPPIM=MAX0 (INPPIM,IRANGM)
C
  215 CONTINUE
      IARTIK=IRANGF-INALPP*(IRGPIF-1)
C
C         ON CHERCHE LE PREMIER ARTICLE LOGIQUE *DE DONNEES* DE LA PAGE
C       D'INDEX, A PARTIR DU RANG *IARTIK* DANS CETTE PAGE.
C
      DO 216 J=IARTIK,1,-1
C
      IF (LFI%CNOMAR(IXC(J,IRGPIM)).NE.' ') THEN
        IARTIC=J
        GOTO 220
      ENDIF
C
  216 CONTINUE
C
C        CHOU BLANC POUR CETTE PAGE... A PRIORI, ON VA CHERCHER DANS
C     LA P.A.I. PRECEDENTE, EN RANG DANS LE FICHIER.
C
      IF (IRGPIF.GT.1) THEN
        IRGPIF=IRGPIF-1
        IRANGF=INALPP*IRGPIF
        GOTO 211
      ENDIF
C
C    SI ON ARRIVE ICI, C'EST QUE LE PREMIER ARTICLE LOGIQUE EST UN TROU
C
      LFI%NPRECF(IRANG)=0
      GOTO 1001
C*
C     2.2 -  ARTICLE DE DONNEES REPERE, ON RENVOIE SES CARACTERISTIQUES.
C-----------------------------------------------------------------------
C
  220 CONTINUE
      KRGPIM=IRGPIM
      KARTEX=IARTIC
      LFI%NPRECF(IRANG)=(IRGPIF-1)*INALPP+IARTIC
      GOTO 1001
C**
C     9.  - CI-DESSOUS, ETIQUETTES DE BRANCHEMENT EN CAS D'ERREUR E/S.
C      AU CAS OU, ON FORCE LE CODE-REPONSE ENTREE/SORTIE A ETRE POSITIF.
C-----------------------------------------------------------------------
C
  903 CONTINUE
      IRETOU=1
      CLACTI='WRITE'
      GOTO 909
C
  904 CONTINUE
      IRETOU=2
      CLACTI='READ'
C
  909 CONTINUE
      KREP=IABS (KREP)
C**
C    10.  -  PHASE TERMINALE : MESSAGERIE INTERNE EVENTUELLE,
C            VIA LE SOUS-PROGRAMME "LFIEMS", PUIS RETOUR.
C-----------------------------------------------------------------------
C
 1001 CONTINUE
      LLFATA=LLMOER (KREP,KRANG)
C
      IF (KREP.EQ.0) THEN
        KRETIN=0
      ELSEIF (KREP.GT.0) THEN
        KRETIN=IRETOU
      ELSE
        KRETIN=3
      ENDIF
C
      IF (LFI%LMISOP.OR.LLFATA) THEN
        INUMER=LFI%NUMERO(KRANG)
        INIMES=2
        CLNSPR='LFICAQ'
        WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KRANG='',I3,
     S         '', KRGPIM='',I3,'', KARTEX='',I5,'', KRETIN='',I2)')
     S    KREP,KRANG,KRGPIM,KARTEX,KRETIN
        CALL LFIEMS_MT (LFI, INUMER,INIMES,KREP,.FALSE.,
     S                  CLMESS,CLNSPR,CLACTI)
      ENDIF
C
      IF (LHOOK) CALL DR_HOOK('LFICAQ_MT',1,ZHOOK_HANDLE)
      END

