      SUBROUTINE LFIDEB_MT (LFI, LDEBUG )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME D'ACTIVER OU DE DESACTIVER LE MODE
C     "MISE AU POINT DU LOGICIEL". ( PAR DEFAUT, INACTIF )
C**
C        ARGUMENT : LDEBUG (ENTREE) ==> VRAI SI ON DOIT ACTIVER CE MODE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER INUMER, IREP, INIMES
C
      LOGICAL LDEBUG
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIDEB_MT',0,ZHOOK_HANDLE)
      IF (LFI%LFIDEB_LLPREA) THEN
        CALL LFIINI_MT (LFI, 2)
        LFI%LFIDEB_LLPREA=.FALSE.
      ENDIF
C
      LFI%LMISOP=LDEBUG
C
C        MESSAGERIE EVENTUELLE .
C
      IF (LFI%NIMESG.NE.2)  THEN 
        IF (LHOOK) CALL DR_HOOK('LFIDEB_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
      INUMER=LFI%JPNIL
      INIMES=2
      IREP=0
      CLNSPR='LFIDEB'
      WRITE (UNIT=CLMESS,FMT='(''LDEBUG= '',L1)') LDEBUG
      CALL LFIEMS_MT (LFI, INUMER,INIMES,IREP,.FALSE.,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFIDEB_MT',1,ZHOOK_HANDLE)
      END

