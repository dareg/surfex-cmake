C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIECR_MT (LFI, KREP, KNUMER, CDNOMA, KTAB, KLONG )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        SOUS-PROGRAMME D'ECRITURE D'UN ARTICLE (DE DONNEES) SUR UNE
C     UNITE LOGIQUE OUVERTE POUR LE LOGICIEL DE FICHIERS INDEXES LFI;
C     L'ARTICLE DOIT ETRE UN "BLOC" DE DONNEES ADJACENTES.
C**
C    ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                KNUMER (ENTREE) ==> LFI%NUMERO DE L'UNITE LOGIQUE;
C                CDNOMA (ENTREE) ==> NOM DE L'ARTICLE A ECRIRE;
C                KTAB   (ENTREE) ==> PREMIER MOT A ECRIRE
C                KLONG  (ENTREE) ==> LONGUEUR DE L'ARTICLE A ECRIRE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      CHARACTER CDNOMA*(*), CLNOMA*(LFI%JPNCPN)
C
      INTEGER KREP, KNUMER, KLONG
#ifndef f77
      INTEGER (KIND=JPDBLE)  KTAB (KLONG)
#else
      INTEGER KTAB (KLONG)
#endif
      INTEGER IRANG, IREP, ILCLNO, IDECBL, IPOSBL, INBALO, INBPIR
      INTEGER IFACTM, ILARPH, INALPP, IRPIEX, IARTEX, ILONEX, IRPIEC
      INTEGER IARTEC, IPOSEC, IDTROU, ILONUT, INPPIM, IRETIN, IRGPI, J
      INTEGER IRGPIM, ILFORC, INPILE, INAPHY, IRANGM, INAPXX, INDMAX
      INTEGER IMDESC, INIMES, ILCDNO
C
      LOGICAL LLLECT, LLECR, LLVERF
C
#include "lficom2.h"
#include "lficom_mt.h"
C**
C     1.  -  CONTROLES DES PARAMETRES D'APPEL, PUIS INITIALISATIONS.
C-----------------------------------------------------------------------
C
C        Appel legerement anticipe a LFINUM, garantissant l'initialisa-
C     tion des variables globales du logiciel a la 1ere utilisation.
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIECR_MT',0,ZHOOK_HANDLE)
      CALL LFINUM_MT (LFI, KNUMER,IRANG)
      LLVERF=.FALSE.
      ILCDNO=LEN (CDNOMA)
C
      IF (ILCDNO.LE.0) THEN
        IREP=-15
        CLNOMA=LFI%CHINCO(:LFI%JPNCPN)
        ILCLNO=LFI%JPNCPN
        GOTO 1001
      ELSEIF (CDNOMA.EQ.' ') THEN
        IREP=-18
        CLNOMA=' '
        ILCLNO=1
        GOTO 1001
      ENDIF
C
C        Recherche de la longueur "utile" du nom d'article specifie.
C        (c'est-a-dire sans tenir compte des blancs terminaux eventuels)
C
      IDECBL=0
C
  101 CONTINUE
      IPOSBL=IDECBL+INDEX (CDNOMA(IDECBL+1:),' ')
C
      IF (IPOSBL.LE.IDECBL) THEN
        ILCLNO=ILCDNO
      ELSEIF (CDNOMA(IPOSBL:).EQ.' ') THEN
        ILCLNO=IPOSBL-1
      ELSE
        IDECBL=IPOSBL
        GOTO 101
      ENDIF
C
      IF (ILCLNO.LE.LFI%JPNCPN) THEN
        CLNOMA=CDNOMA(:ILCLNO)
      ELSE
        CLNOMA=CDNOMA(:LFI%JPNCPN)
        ILCLNO=LFI%JPNCPN
        IREP=-15
        GOTO 1001
      ENDIF
C
      IF (KLONG.LE.0) THEN
        IREP=-14
        GOTO 1001
      ELSEIF (IRANG.EQ.0) THEN
        IREP=-1
        GOTO 1001
      ENDIF
C
       IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'ON')
      LLVERF=LFI%LMULTI
C
      IF (LFI%NEXPOR(IRANG).GT.0) THEN
C
C         Fichier en cours d'export... ne devant donc pas etre modifie.
C
        IREP=-37
        GOTO 1001
      ENDIF
C
      LLLECT=.TRUE.
      LLECR =.FALSE.
      INBALO=LFI%MDES1D(IXM(LFI%JPNALO,IRANG))
      INBPIR=LFI%MDES1D(IXM(LFI%JPNPIR,IRANG))
      IFACTM=LFI%MFACTM(IRANG)
      ILARPH=LFI%JPLARD*IFACTM
      INALPP=LFI%JPNAPP*IFACTM
C**
C     2.  -  EXPLORATION DES (PAIRES DE) PAGES ET ARTICLES D'INDEX,
C            A LA RECHERCHE DE L'ARTICLE LOGIQUE ET/OU D'UN "TROU"
C            DANS L'INDEX, SUFFISANT POUR Y "CASER" LEDIT ARTICLE.
C-----------------------------------------------------------------------
C
      INAPHY=0
      CALL LFIREE_MT (LFI, IREP,IRANG,CLNOMA(:ILCLNO),KLONG,IRPIEX,
     S                IARTEX, ILONEX,IRPIEC,IARTEC,IPOSEC,
     S                IDTROU,ILONUT,IRETIN)
C
      IF (IRETIN.EQ.1) THEN
        GOTO 903
      ELSEIF (IRETIN.EQ.2) THEN
        GOTO 904
      ELSEIF (IRETIN.NE.0) THEN
        GOTO 1001
      ENDIF
C
      INPPIM=LFI%NPPIMM(IRANG)
C
      IF (IARTEX.NE.0.AND.LFI%NEXPOR(IRANG).GT.0) THEN
C
C         Fichier en cours d'export... la seule modification acceptee
C         est l'ajout de nouveaux articles.
C
        IREP=-37
        GOTO 1001
      ENDIF
C**
C     3.  -   PARTIE ECRITURE DES DONNEES .
C-----------------------------------------------------------------------
C
      CALL LFIECD_MT (LFI, IREP,IRANG,KTAB,KLONG,IPOSEC,IRETIN)
C
      IF (IRETIN.EQ.1) THEN
        GOTO 903
      ELSEIF (IRETIN.EQ.2) THEN
        GOTO 904
      ELSEIF (IRETIN.NE.0) THEN
        GOTO 1001
      ENDIF
C**
C     4.  -   MODIFICATION(S) EVENTUELLE(S) DE L'INDEX.
C-----------------------------------------------------------------------
C
      IF (IARTEX.NE.0.AND.IARTEC.NE.IARTEX) THEN
C*
C     4.1 - CAS OU L'ON CREE UN TROU DANS L'INDEX.
C-----------------------------------------------------------------------
C
C           RECHERCHE OU MISE EN MEMOIRE DE L'ARTICLE D'INDEX "NOMS"
C        CONTENANT LES CARACTERISTIQUES DE L'ARTICLE LOGIQUE
C        QUE L'ON "TROUE".
C
        DO 411 J=1,INPPIM
        IRGPI=LFI%MRGPIM(J,IRANG)
C
        IF (LFI%MRGPIF(IRGPI).EQ.IRPIEX) THEN
          IRGPIM=IRGPI
          GOTO 413
        ENDIF
C
  411   CONTINUE
C
        ILFORC=1
        INPILE=1
        INAPHY=0
        CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPIM,IRPIEX,
     S                  ILFORC,INPILE, IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
        INPPIM=MAX0 (INPPIM,IRANGM)
C
  413   CONTINUE
        LFI%CNOMAR(IXC(IARTEX,IRGPIM))=' '
        LFI%LECRPI(IRGPIM,1)=.TRUE.
C
        IF (ILONEX.NE.ILONUT) THEN
C
C           STOCKAGE DE LA LONGUEUR TOTALE UTILISABLE DU TROU .
C         DANS CE CAS, ON EST SUR QUE LA PAGE D'INDEX "LONG./POS."
C         EST TOUJOURS PHASEE.
C
          LFI%MLGPOS(IXM(2*IARTEX-1,IRGPIM))=ILONUT
          LFI%LECRPI(IRGPIM,2)=.TRUE.
        ENDIF
C
      ENDIF
C
      IF (INALPP*(IRPIEC-1)+IARTEC.GT.INBALO) THEN
C*
C     4.2 - CAS OU L'ON A CREE UN ARTICLE LOGIQUE SUPPLEMENTAIRE.
C-----------------------------------------------------------------------
C
        LFI%MDES1D(IXM(LFI%JPNALO,IRANG))=INBALO+1
C
        IF (INBALO.NE.0.AND.IARTEC.EQ.1) THEN
C
C             ON DOIT CREER UNE P.A.I. SUPPLEMENTAIRE.
C
          IF (IRPIEC.GT.INBPIR) THEN
C
C             CETTE NOUVELLE P.A.I. EST "EXCEDENTAIRE".
C             RECHERCHE DU PREMIER ARTICLE PHYSIQUE DISPONIBLE
C             POUR Y ECRIRE (ULTERIEUREMENT) CETTE P.A.I. EXCEDENTAIRE.
C             LE CONTROLE DE DEPASSEMENT DE CAPACITE DE L'INDEX
C             DU FICHIER A ETE FAIT DANS LE SOUS-PROGRAMME *LFIREE*.
C
            INAPXX=LFI%MDES1D(IXM(LFI%JPAXPD,IRANG))
            INDMAX=LFI%JPNIL
C
            DO 421 J=0,LFI%JPNPDF-1
C
            IF (LFI%NUMAPD(J,IRANG).GT.INAPXX) THEN
              INAPXX=LFI%NUMAPD(J,IRANG)
              INDMAX=J
            ENDIF
C
  421       CONTINUE
C
            IF (IRPIEC.GT.(INBPIR+1)) THEN
              IMDESC=LFI%MDES1D(IXM(ILARPH+2-IRPIEC+INBPIR,IRANG))
              INAPXX=MAX0 (INAPXX,IMDESC+1)
            ENDIF
C
            LFI%MDES1D(IXM(ILARPH+1-IRPIEC+INBPIR,IRANG))=INAPXX+1
C
C      L'ON A AUSSI CREE, EN GENERAL, UNE ZONE "PERDUE" (MAIS NEANMOINS
C     REUTILISABLE DANS UNE CERTAINE MESURE) A LA FIN DU DERNIER
C     ARTICLE PHYSIQUE DES DONNEES QUE L'ON VIENT D'ECRIRE.
C           IL EST ALORS NECESSAIRE DE "COMPLETER" LA ZONE PERDUE,
C     POUR NE PAS AVOIR DE PROBLEME ULTERIEUR DANS *LFIECX*.
C
            IF (INDMAX.NE.LFI%JPNIL) THEN
C
              DO 423 J=LFI%NLONPD(INDMAX,IRANG)+1,ILARPH
              LFI%MTAMPD(IXT(J,INDMAX,IRANG))=0
  423         CONTINUE
C
              LFI%NLONPD(INDMAX,IRANG)=ILARPH
            ENDIF
C
          ENDIF
C
          ILFORC=1
          INPILE=0
          INAPHY=0
          CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPIM,IRPIEC,
     S                    ILFORC,INPILE, IRETIN)
C
          IF (IRETIN.EQ.1) THEN
            GOTO 903
          ELSEIF (IRETIN.EQ.2) THEN
            GOTO 904
          ELSEIF (IRETIN.NE.0) THEN
            GOTO 1001
          ENDIF
C
          LFI%NPODPI(IRANG)=IRANGM
C
C           REMARQUE: LA DERNIERE P.P.I. EST TOUJOURS "PHASEE".
C
          LFI%LPHASP(IRGPIM)=.TRUE.
        ELSE
          IRGPIM=LFI%MRGPIM(LFI%NPODPI(IRANG),IRANG)
        ENDIF
C
        LFI%NALDPI(IRANG)=IARTEC
        LFI%CNOMAR(IXC(IARTEC,IRGPIM))=CLNOMA(:ILCLNO)
        LFI%MLGPOS(IXM(2*IARTEC-1,IRGPIM))=KLONG
        LFI%MLGPOS(IXM(2*IARTEC  ,IRGPIM))=IPOSEC
        LFI%LECRPI(IRGPIM,1)=.TRUE.
        LFI%LECRPI(IRGPIM,2)=.TRUE.
C
      ELSEIF (IARTEX.EQ.0.OR.KLONG.NE.ILONEX) THEN
C*
C     4.3 - CAS OU L'ON REUTILISE UN ARTICLE OU TROU QUI EXISTAIT
C           AU PREALABLE, EN MODIFIANT SES CARACTERISTIQUES DE NOM ET/OU
C           DE LONGUEUR.
C-----------------------------------------------------------------------
C
        DO 431 J=1,INPPIM
        IRGPI=LFI%MRGPIM(J,IRANG)
C
        IF (LFI%MRGPIF(IRGPI).EQ.IRPIEC) THEN
          IRANGM=J
          IRGPIM=IRGPI
C
C           L'ARTICLE D'INDEX "NOMS" CORRESPONDANT EST EN MEMOIRE...
C       PHASAGE EVENTUEL DE LA PAGE D'INDEX "LONG/POS" .
C
          INAPHY=0
C
          IF (.NOT.LFI%LPHASP(IRGPIM)) THEN
C
            CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPIM,IRETIN)
C
            IF (IRETIN.EQ.1) THEN
              GOTO 903
            ELSEIF (IRETIN.EQ.2) THEN
              GOTO 904
            ELSEIF (IRETIN.NE.0) THEN
              GOTO 1001
            ENDIF
C
          ENDIF
C
          GOTO 434
        ENDIF
C
  431   CONTINUE
C
C            ARTICLE D'INDEX CORRESPONDANT NON PRESENT EN MEMOIRE...
C         ON L'Y AMENE.
C
        ILFORC=1
        INPILE=2
        INAPHY=0
        CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPIM,IRPIEC,
     S                  ILFORC,INPILE, IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
  434   CONTINUE
C
        IF (IARTEC.NE.IARTEX.OR.IRPIEC.NE.IRPIEX) THEN
          LFI%CNOMAR(IXC(IARTEC,IRGPIM))=CLNOMA(:ILCLNO)
          LFI%LECRPI(IRGPIM,1)=.TRUE.
        ENDIF
C
        LFI%MLGPOS(IXM(2*IARTEC-1,IRGPIM))=KLONG
        LFI%LECRPI(IRGPIM,2)=.TRUE.
C
      ENDIF
C**
C     5.  -   MISE A JOUR: STATISTIQUES, TABLES, PAGE DOCUMENTAIRE.
C-----------------------------------------------------------------------
C
      IF (IARTEX.EQ.0) THEN
        LFI%NBNECR(IRANG)=LFI%NBNECR(IRANG)+1
      ELSEIF (KLONG.EQ.ILONEX) THEN
        LFI%NREESP(IRANG)=LFI%NREESP(IRANG)+1
      ELSEIF (KLONG.LT.ILONEX) THEN
        LFI%NREECO(IRANG)=LFI%NREECO(IRANG)+1
        LFI%LMIMAL(IRANG)=LFI%LMIMAL(IRANG).OR.
     S                ILONEX.EQ.LFI%MDES1D(IXM(LFI%JPLXAL,IRANG))
      ELSE
        LFI%NREELO(IRANG)=LFI%NREELO(IRANG)+1
        LFI%LMIMAL(IRANG)=LFI%LMIMAL(IRANG).OR.
     S                ILONEX.EQ.LFI%MDES1D(IXM(LFI%JPLNAL,IRANG))
      ENDIF
C
      LFI%NBTROU(IRANG)=LFI%NBTROU(IRANG)+IDTROU
      IF (LFI%LMISOP) WRITE (UNIT=LFI%NULOUT,FMT=*)
     S        'IDTROU = ',IDTROU,', ILONEX = ',ILONEX,', KLONG = ',KLONG
C
C        On met a jour ce qui a trait aux acces pseudo-sequentiels...
C
      LFI%NDERGF(IRANG)=INALPP*(IRPIEC-1)+IARTEC
      LFI%CNDERA(IRANG)=CLNOMA(:ILCLNO)
      LFI%NSUIVF(IRANG)=LFI%JPNIL
      LFI%NPRECF(IRANG)=LFI%JPNIL
C
      IMDESC=LFI%MDES1D(IXM(LFI%JPLNAL,IRANG))
      LFI%MDES1D(IXM(LFI%JPLNAL,IRANG))=MIN0 (IMDESC,KLONG)
      IMDESC=LFI%MDES1D(IXM(LFI%JPLXAL,IRANG))
      LFI%MDES1D(IXM(LFI%JPLXAL,IRANG))=MAX0 (IMDESC,KLONG)
      LFI%MDES1D(IXM(LFI%JPLTAL,IRANG))=
     S             LFI%MDES1D(IXM(LFI%JPLTAL,IRANG))+KLONG-ILONEX
      IF (INBALO.EQ.0) LFI%MDES1D(IXM(LFI%JPLNAL,IRANG))=KLONG
C
      IF (.NOT.LFI%LMODIF(IRANG)) THEN
C
C         CAS DE LA PREMIERE ECRITURE DEPUIS L'OUVERTURE DU FICHIER.
C
        LFI%LMODIF(IRANG)=.TRUE.
        INAPHY=0
        CALL LFIMOE_MT (LFI, IREP,IRANG,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
      ENDIF
C
      IREP=0
      LFI%NBMOEC(IRANG)=LFI%NBMOEC(IRANG)+KLONG
      GOTO 1001
C**
C     9.  - CI-DESSOUS, ETIQUETTES DE BRANCHEMENT EN CAS D'ERREUR E/S.
C-----------------------------------------------------------------------
C
  903 CONTINUE
      CLACTI='WRITE'
      GOTO 909
C
  904 CONTINUE
      CLACTI='READ'
C
  909 CONTINUE
C
C      AU CAS OU, ON FORCE LE CODE-REPONSE ENTREE/SORTIE A ETRE POSITIF.
C
      IREP=IABS (IREP)
      IF (INAPHY.NE.0) LFI%NUMAPH(IRANG)=INAPHY
C**
C    10.  -  PHASE TERMINALE : MESSAGERIE, AVEC "ABORT" EVENTUEL,
C            VIA LE SOUS-PROGRAMME "LFIEMS" .
C-----------------------------------------------------------------------
C
 1001 CONTINUE
      KREP=IREP
      LLFATA=LLMOER (IREP,IRANG)
C
      IF (IRANG.NE.0) THEN
        LFI%NDEROP(IRANG)=1
        LFI%NDERCO(IRANG)=IREP
         IF (LLVERF) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'OFF')
      ENDIF
C
      IF (LLFATA.OR.IXNIMS (IRANG).EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFIECR_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      CLNSPR='LFIECR'
      WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KNUMER='',I3,
     S       '', CDNOMA='''''',A,'''''', KLONG='',I7)')
     S     KREP,KNUMER,CLNOMA(:ILCLNO),KLONG
      CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFIECR_MT',1,ZHOOK_HANDLE)
      END

