C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIERF_MT (LFI, KREP, KNUMER, LDERFA )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME PERMET D'ACTIVER OU DE DESACTIVER L'OPTION
C     RENDANT FATALE TOUTE ERREUR DETECTEE SUR UN FICHIER PARTICULIER,
C     OUVERT POUR LE LOGICIEL LFI.
C        CEPENDANT, TANT QUE LE NIVEAU GLOBAL D'ERREUR FATALE *LFI%NERFAG*
C     VAUT 0 OU 2, L'OPTION PROPRE AU FICHIER EST INOPERANTE.
C     *LFI%NERFAG* VAUT PAR DEFAUT 1, ET EST REGLABLE VIA LE S/P "LFINEG".
C**
C     ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                 KNUMER (ENTREE) ==> LFI%NUMERO D'UNITE LOGIQUE CONCERNEE;
C                 LDERFA (ENTREE) ==> OPTION D'ERREUR FATALE (VRAI=OUI).
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KREP, KNUMER, IRANG, IREP, INIMES
C
      LOGICAL LDERFA
C
#include "lficom2.h"
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIERF_MT',0,ZHOOK_HANDLE)
      CALL LFINUM_MT (LFI, KNUMER,IRANG)
C
      IF (IRANG.NE.0) THEN
        LFI%LERFAT(IRANG)=LDERFA
        LFI%NDEROP(IRANG)=4
        IREP=0
      ELSE
        IREP=-1
      ENDIF
C
      LLFATA=LLMOER (IREP,IRANG)
      KREP=IREP
C
      IF (LLFATA.OR.IXNIMS (IRANG).EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFIERF_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      CLNSPR='LFIERF'
      WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KNUMER='',I3,
     S       '', LDERFA= '',L1)') KREP,KNUMER,LDERFA
      CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFIERF_MT',1,ZHOOK_HANDLE)
      END

