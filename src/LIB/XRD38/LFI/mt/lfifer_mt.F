C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIFER_MT (LFI, KREP, KNUMER, CDSTTC )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        SOUS-PROGRAMME DE FERMETURE D'UN FICHIER INDEXE AU SENS DU
C     LOGICIEL DE FICHIERS INDEXES LFI.
C        CETTE FERMETURE EST VITALE SI LE FICHIER A ETE MODIFIE DEPUIS
C     LA DERNIERE OUVERTURE, ET EST DE TOUTE MANIERE CHAUDEMENT
C     RECOMMANDEE AVANT DE SORTIR DU PROGRAMME UTILISATEUR.
C
C        De maniere generale, il vaut mieux fermer une unite logique
C     des que l'on n'en a plus besoin, de maniere a ne pas bloquer un
C     espace dans les tables qui pourrait faire defaut lors d'une
C     ouverture ulterieure, particulierement pour un fichier "multiple"
C     qui a besoin d'espace CONTIGU dans les tables des unites logiques.
C     Par ailleurs, tout fichier ouvert (au sens FORTRAN du terme cette
C     fois) "occupe" generalement un morceau de la memoire du programme.
C**
C    ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                KNUMER (ENTREE) ==> LFI%NUMERO DE L'UNITE LOGIQUE;
C                CDSTTC (ENTREE) ==> "STATUS" EVENTUEL POUR "CLOSE".
C
C    Modifications:
C
C    02/06/97, Jean Clochard.
C
C              -Modification des impressions pour que l'annee puisse
C               etre imprimee avec 4 chiffres.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      CHARACTER CDSTTC*(*), CLSTTC*(LFI%JPLSTX), CLAUXI*3
C
#ifndef f77
      INTEGER (KIND=JPDBLE) ITAMPO (LFI%JPLARX)
#else
      INTEGER ITAMPO (LFI%JPLARX)
#endif
      INTEGER KREP, KNUMER, IEXPLO (LFI%JPNPIA+LFI%JPNPIS)
      INTEGER ILSTTU, IREPX, INAPHY, IRANG, IREP, ILSTTC, IREC, INPPIM
      INTEGER IFACTM, ILARPH, INALPP, INBALO, INTPPI, INTRLZ, IDECAL, J
      INTEGER IPOTZC, IRGPFC, IRGPMC, ILFORC, INPILE, INIMES, IPOTZS, JJ
      INTEGER IRGPFS, IPOTZE, IRGPMS, INTCON, IPOSFE, JNPAGE, IRGPFE, JR
      INTEGER IRGPME, IRANGM, IDECDB, INBARE, IRGPC2, IRGPS2, IDECDC
      INTEGER INBARC, IDECDS, INBARS, INBART, INTPPN, ILOMIN, ILOMAX
      INTEGER IRPIFN, INPIME, IDEBEX, IRGPIM, IRGPIF, INLNOM, IDEBUT
      INTEGER ILONGA, INALDO, IPOSNU, IRANIE, IRETIN, IAUXIL
C
      LOGICAL LLSTTU, LLVERF, LLVERG, LLECRD, LLIMST
C
#include "lficom2.h"
#include "lficom_mt.h"
C**
C     1.  -  CONTROLES DES PARAMETRES D'APPEL, PUIS INITIALISATIONS.
C-----------------------------------------------------------------------
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIFER_MT',0,ZHOOK_HANDLE)
      IF (LFI%LMISOP) WRITE (UNIT=LFI%NULOUT,FMT=*)'DEBUT LFIFER'
      CLNSPR='LFIFER'
      ILSTTU=MIN0 (LEN (CLSTTC), LEN (CDSTTC))
      CLSTTC=CDSTTC(:ILSTTU)
      IREPX=0
      INAPHY=0
      LLVERF=.FALSE.
      LLVERG=.FALSE.
      CALL LFINUM_MT (LFI, KNUMER,IRANG)
C
      IF (IRANG.EQ.0) THEN
        IREP=-1
        GOTO 1001
      ENDIF
C
       IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'ON')
      LLVERF=LFI%LMULTI
C
      IF (CDSTTC.EQ.'KEEP'.AND.LFI%CSTAOP(IRANG).EQ.'SCRATCH') THEN
        IREP=-19
        LLFATA=LLMOER (IREP,IRANG)
C
        IF (LLFATA) THEN
          GOTO 1001
        ELSE
C
C        SI L'ERREUR (-19) N'EST PAS FATALE, ON FERME L'UNITE LOGIQUE,
C       MAIS SANS PRECISER DE DIRECTIVE "STATUS" DANS LE "CLOSE".
C
          LLSTTU=.FALSE.
          GOTO 105
        ENDIF
C
      ELSE
        LLSTTU=CDSTTC.EQ.'KEEP'.OR.CDSTTC.EQ.'DELETE'
C
        IF (LLSTTU) THEN
          ILSTTC=INDEX (CDSTTC,' ')-1
          IF (ILSTTC.GT.0) ILSTTU=ILSTTC
          CLSTTC=CDSTTC(:ILSTTU)
        ELSE
          CLSTTC=LFI%CHINCO(:ILSTTU)
        ENDIF
C
      ENDIF
C
      IREP=0
C
  105 CONTINUE
      IREPX=IREP
      INPPIM=LFI%NPPIMM(IRANG)
      IFACTM=LFI%MFACTM(IRANG)
      ILARPH=LFI%JPLARD*IFACTM
      INALPP=LFI%JPNAPP*IFACTM
      INBALO=LFI%MDES1D(IXM(LFI%JPNALO,IRANG))
      INTPPI=(INBALO-1+INALPP)/INALPP
C**
C     2.  -  TRAITEMENT D'EVENTUELS "TROUS" D'INDEX DE LONGUEUR ZERO.
C            CES "PARASITES" PEUVENT AVOIR ETE CREES PAR LE RECYCLAGE
C            DE TROUS DANS LE FICHIER; ON VA LES SUPPRIMER.
C
C         L'ALGORITHME CHOISI N'EST PEUT-ETRE PAS LE PLUS EFFICACE;
C     MAIS A PARTIR DU MOMENT OU LA PROBABILITE DE GENERER DES TROUS
C     DE LONGUEUR NULLE EST FAIBLE, ET OU ON NE LES RETASSE
C     QU'A LA FERMETURE, IL N'Y A PAS LIEU DE RAFFINER A OUTRANCE !
C-----------------------------------------------------------------------
C
      INTRLZ=LFI%NTRULZ(IRANG)
      IF (INTRLZ.EQ.0) GOTO 300
C
      IDECAL=0
      IPOTZC=LFI%NRFPTZ(IRANG)
      IRGPFC=1+(IPOTZC-1)/INALPP
C*
C     2.1 - MISE EN MEMOIRE DE LA PREMIERE P.A.I. AYANT UN TEL TROU.
C-----------------------------------------------------------------------
C
      DO 211 J=1,INPPIM
      IRGPMC=LFI%MRGPIM(J,IRANG)
C
      IF (LFI%MRGPIF(IRGPMC).EQ.IRGPFC) THEN
C
      IF (.NOT.LFI%LPHASP(IRGPMC)) THEN
C
        CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPMC,IRETIN)
C
          IF (IRETIN.EQ.1) THEN
            GOTO 903
          ELSEIF (IRETIN.EQ.2) THEN
            GOTO 904
          ELSEIF (IRETIN.NE.0) THEN
            GOTO 1001
          ENDIF
C
        ENDIF
C
        GOTO 220
C
      ENDIF
C
  211 CONTINUE
C
      ILFORC=IRGPFC+1
      INPILE=2
      CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPMC,IRGPFC,
     S                ILFORC,INPILE,IRETIN)
C
      IF (IRETIN.EQ.1) THEN
        GOTO 903
      ELSEIF (IRETIN.EQ.2) THEN
        GOTO 904
      ELSEIF (IRETIN.NE.0) THEN
        GOTO 1001
      ENDIF
C
      INPPIM=MAX0 (INPPIM,IRANGM)
C
  220 CONTINUE
C*
C     2.2 - AMORCAGE DE LA RECHERCHE DU NOMBRE DE TROUS NULS CONSECUTIFS
C           ET DE L'EVENTUEL TROU NUL "SUIVANT" CE PAQUET.
C-----------------------------------------------------------------------
C
      IPOTZS=IPOTZC+IDECAL
      IRGPFS=1+(IPOTZS-1)/INALPP
      IPOTZE=IPOTZS
      IRGPMS=0
C
C       ON ELIMINE LES CAS "TRIVIAUX"
C
      IF (INTRLZ.EQ.1.OR.IPOTZE+INTRLZ.GT.INBALO) THEN
        INTCON=INTRLZ
        IPOSFE=INBALO
        GOTO 250
      ENDIF
C*
C     2.3 - DECOMPTE DU NOMBRE DE TROUS NULS CONSECUTIFS.
C-----------------------------------------------------------------------
C
      DO 235 JNPAGE=IRGPFS,INTPPI
      IRGPFE=JNPAGE
C
      DO 231 J=1,INPPIM
      IRGPME=LFI%MRGPIM(J,IRANG)
C
      IF (LFI%MRGPIF(IRGPME).EQ.IRGPFE) THEN
C
        IF (.NOT.LFI%LPHASP(IRGPME)) THEN
C
          CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPME,IRETIN)
C
          IF (IRETIN.EQ.1) THEN
            GOTO 903
          ELSEIF (IRETIN.EQ.2) THEN
            GOTO 904
          ELSEIF (IRETIN.NE.0) THEN
            GOTO 1001
          ENDIF
C
        ENDIF
C
        GOTO 233
C
      ENDIF
C
  231 CONTINUE
C
      INPILE=2
      CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPME,
     S                IRGPFE,IRGPFC,INPILE,IRETIN)
C
      IF (IRETIN.EQ.1) THEN
        GOTO 903
      ELSEIF (IRETIN.EQ.2) THEN
        GOTO 904
      ELSEIF (IRETIN.NE.0) THEN
        GOTO 1001
      ENDIF
C
      INPPIM=MAX0 (INPPIM,IRANGM)
C
  233 CONTINUE
      IF (IRGPMS.EQ.0) IRGPMS=IRGPME
      IDECDB=IPOTZE-1-(IRGPFE-1)*INALPP
      INBARE=MIN0 (INBALO,IRGPFE*INALPP)-IPOTZE+1
      INTCON=0
C
      DO 234 J=1,INBARE
C
      IF (LFI%MLGPOS(IXM(2*(J+IDECDB)-1,IRGPME)).NE.0) THEN
        INTCON=INTCON+J-1
        GOTO 240
      ENDIF
C
  234 CONTINUE
C
      INTCON=INTCON+INBARE
      IPOTZE=IPOTZE+INBARE
  235 CONTINUE
C*
C     2.4 - RECHERCHE DU PROCHAIN TROU NUL, APRES LE PAQUET TROUVE.
C-----------------------------------------------------------------------
C
  240 CONTINUE
      IPOTZE=IPOTZE+INTCON
C
C             D'ABORD, ELIMINATION DES CAS "TRIVIAUX"
C
      IF (INTCON.EQ.INTRLZ) THEN
C
C        ON A TROUVE TOUS LES TROUS NULS RESTANT.
C
        IPOSFE=INBALO
      ELSEIF (INTCON.EQ.(INTRLZ-1)) THEN
C
C        PLUS QU'UN SEUL TROU NUL... CE SERA DONC CELUI DE RANG MAXIMUM.
C
        IPOSFE=LFI%NRFDTZ(IRANG)-1
      ELSE
C
C          CAS GENERAL.
C
        DO 245 JNPAGE=IRGPFE,INTPPI
C
        IF (JNPAGE.NE.IRGPFE) THEN
C
          DO 241 J=1,INPPIM
          IRGPME=LFI%MRGPIM(J,IRANG)
C
          IF (LFI%MRGPIF(IRGPME).EQ.JNPAGE) THEN
C
            IF (.NOT.LFI%LPHASP(IRGPME)) THEN
C
              CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPME,IRETIN)
C
              IF (IRETIN.EQ.1) THEN
                GOTO 903
              ELSEIF (IRETIN.EQ.2) THEN
                GOTO 904
              ELSEIF (IRETIN.NE.0) THEN
                GOTO 1001
              ENDIF
C
            ENDIF
C
            GOTO 243
C
          ENDIF
C
  241     CONTINUE
C
          INPILE=2
          CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPME,JNPAGE,
     S                    IRGPFC,INPILE,IRETIN)
C
          IF (IRETIN.EQ.1) THEN
            GOTO 903
          ELSEIF (IRETIN.EQ.2) THEN
            GOTO 904
          ELSEIF (IRETIN.NE.0) THEN
            GOTO 1001
          ENDIF
C
          INPPIM=MAX0 (INPPIM,IRANGM)
        ENDIF
C
  243   CONTINUE
        IDECDB=IPOTZE-1-(JNPAGE-1)*INALPP
        INBARE=MIN0 (INBALO,JNPAGE*INALPP)-IPOTZE+1
C
        DO 244 J=1,INBARE
C
        IF (LFI%MLGPOS(IXM(2*(J+IDECDB)-1,IRGPME)).EQ.0) THEN
          IPOSFE=(JNPAGE-1)*INALPP+J-1
          GOTO 250
        ENDIF
C
  244   CONTINUE
C
  245   CONTINUE
C
      ENDIF
C
  250 CONTINUE
C*
C     2.5 - RETASSAGE "A GAUCHE" D'UNE PARTIE DE L'INDEX.
C-----------------------------------------------------------------------
C
      IDECAL=IDECAL+INTCON
C
  251 CONTINUE
      IPOTZS=IPOTZC+IDECAL
      IRGPC2=1+(IPOTZC-1)/INALPP
      IRGPS2=1+(IPOTZS-1)/INALPP
C
      IF (IRGPC2.NE.IRGPFC) THEN
        IRGPFC=IRGPC2
C
        DO 252 J=2,INPPIM
        IRGPMC=LFI%MRGPIM(J,IRANG)
C
        IF (LFI%MRGPIF(IRGPMC).EQ.IRGPFC) THEN
C
          IF (.NOT.LFI%LPHASP(IRGPMC)) THEN
C
            CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPMC,IRETIN)
C
            IF (IRETIN.EQ.1) THEN
              GOTO 903
            ELSEIF (IRETIN.EQ.2) THEN
              GOTO 904
            ELSEIF (IRETIN.NE.0) THEN
              GOTO 1001
            ENDIF
C
          ENDIF
C
          GOTO 254
C
        ENDIF
C
  252   CONTINUE
C
        INPILE=2
        CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPMC,IRGPFC,
     S                  IRGPS2,INPILE,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
        INPPIM=MAX0 (INPPIM,IRANGM)
      ENDIF
C
  254 CONTINUE
C
      IF (IRGPS2.NE.IRGPFS) THEN
        IRGPFS=IRGPS2
C
        DO 255 J=2,INPPIM
        IRGPMS=LFI%MRGPIM(J,IRANG)
C
        IF (LFI%MRGPIF(IRGPMS).EQ.IRGPFS) THEN
C
          IF (.NOT.LFI%LPHASP(IRGPMS)) THEN
C
            CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPMS,IRETIN)
C
            IF (IRETIN.EQ.1) THEN
              GOTO 903
            ELSEIF (IRETIN.EQ.2) THEN
              GOTO 904
            ELSEIF (IRETIN.NE.0) THEN
              GOTO 1001
            ENDIF
C
          ENDIF
C
          GOTO 257
C
        ENDIF
C
  255   CONTINUE
C
        INPILE=2
        CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPMS,IRGPFS,
     S                  IRGPFC,INPILE,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
        INPPIM=MAX0 (INPPIM,IRANGM)
      ENDIF
C
  257 CONTINUE
      IDECDC=IPOTZC-1+(IRGPFC-1)/INALPP
      INBARC=MIN0 (INBALO-IDECAL,IRGPFC*INALPP)-IPOTZC+1
      IDECDS=IPOTZS-1+(IRGPFS-1)/INALPP
      INBARS=MIN0 (INBALO,IRGPFS*INALPP)-IPOTZS+1
      INBART=MIN0 (INBARC,INBARS)
C
      DO 258 J=1,INBART
      LFI%CNOMAR(IXC(IDECDC+J,IRGPMC))=LFI%CNOMAR(IXC(IDECDS+J,IRGPMS))
  258 CONTINUE
C
      DO 259 J=1,2*INBART
      LFI%MLGPOS(IXM(2*IDECDC+J,IRGPMC))=
     S                   LFI%MLGPOS(IXM(2*IDECDS+J,IRGPMS))
  259 CONTINUE
C
      IPOTZC=IPOTZC+INBART
C
      IF (IPOTZS+INBART.LT.IPOSFE) THEN
        GOTO 251
      ELSEIF (IPOSFE.LT.INBALO) THEN
        GOTO 220
      ENDIF
C*
C     2.6 - MISE A JOUR DE CERTAINES TABLES.
C-----------------------------------------------------------------------
C
      LFI%NBTROU(IRANG)=LFI%NBTROU(IRANG)-IDECAL
      INBALO=INBALO-IDECAL
      LFI%MDES1D(IXM(LFI%JPNALO,IRANG))=INBALO
      INTPPN=(INBALO-1+INALPP)/INALPP
      LFI%NALDPI(IRANG)=INBALO-(INTPPN-1)*INALPP
C
      IF (INTPPN.NE.INTPPI) THEN
C
C           ON A DONC LAISSE DES P.P.I. "PARASITES" EN MEMOIRE.
C        A PRIORI CE N'EST PAS GENANT, CAR ON VA BIENTOT RELACHER
C        TOUTES CELLES RELATIVES AU FICHIER QUE L'ON TRAITE.
C        NEANMOINS IL EST PREFERABLE DE REDEFINIR LE RANG EN MEMOIRE
C        DE LA DERNIERE P.P.I. DU FICHIER.
C
        LFI%NPODPI(IRANG)=IRGPMC
        INTPPI=INTPPN
      ENDIF
C
  300 CONTINUE
C**
C     3.  -  CAS OU IL FAUT RECALCULER LES LONGUEURS EXTREMES DES
C            ARTICLES DE DONNEES.
C-----------------------------------------------------------------------
C
      IF (.NOT.LFI%LMIMAL(IRANG)) GOTO 400
C*
C     3.1 - EXPLORATION DES P.P.I., PUIS EVENTUELLEMENT DES P.A.I. .
C-----------------------------------------------------------------------
C
      ILOMIN=0
      ILOMAX=0
      IRPIFN=1
      INPIME=0
C
      IF (LFI%NPODPI(IRANG).EQ.2) THEN
        IDEBEX=3
      ELSE
        IDEBEX=2
      ENDIF
C
      DO 317 JNPAGE=1,INTPPI
C
      IF (JNPAGE.LE.INPPIM) THEN
C
C           IL S'AGIT D'UNE EXPLORATION EN MEMOIRE ( PAGES D'INDEX ).
C
        IRGPIM=LFI%MRGPIM(JNPAGE,IRANG)
        IRGPIF=LFI%MRGPIF(IRGPIM)
        INPIME=INPIME+1
        IEXPLO(INPIME)=IRGPIF
        IF (IRGPIF.EQ.(IRPIFN+1)) IRPIFN=IRGPIF
C
        IF (.NOT.LFI%LPHASP(IRGPIM)) THEN
C
          CALL LFIPHA_MT (LFI, IREP,IRANG,IRGPIM,IRETIN)
C
          IF (IRETIN.EQ.1) THEN
            GOTO 903
          ELSEIF (IRETIN.EQ.2) THEN
            GOTO 904
          ELSEIF (IRETIN.NE.0) THEN
            GOTO 1001
          ENDIF
C
        ENDIF
C
      ELSE
C
C           IL S'AGIT D'UNE EXPLORATION "HORS MEMOIRE";
C         ON CHERCHE LA PROCHAINE P.A.I. NON EXPLOREE .
C
        IF (JNPAGE.EQ.INPPIM+1) IRGPIF=IRPIFN
C
  311   CONTINUE
        IRGPIF=IRGPIF+1
C
        DO 312 J=IDEBEX,INPIME
        IF (IEXPLO(J).EQ.IRGPIF) GOTO 311
  312   CONTINUE
C
        ILFORC=1
        INPILE=2
        CALL LFIPIM_MT (LFI, IREP,IRANG,IRANGM,IRGPIM,IRGPIF,
     S                  ILFORC,INPILE,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
      ENDIF
C
      INBART=MIN0 (INALPP,INBALO-(IRGPIF-1)*INALPP)
C
      IF (ILOMIN.EQ.0) THEN
C
        DO 314 J=1,INBART
C
        IF (LFI%CNOMAR(IXC(J,IRGPIM)).NE.' ') THEN
          ILOMIN=LFI%MLGPOS(IXM(2*J-1,IRGPIM))
          ILOMAX=ILOMIN
          IDEBUT=J+1
          GOTO 315
        ENDIF
C
  314   CONTINUE
C
        GOTO 317
      ELSE
        IDEBUT=1
      ENDIF
C
  315 CONTINUE
C
      DO 316 J=IDEBUT,INBART
C
      IF (LFI%CNOMAR(IXC(J,IRGPIM)).NE.' ') THEN
        ILONGA=LFI%MLGPOS(IXM(2*J-1,IRGPIM))
        ILOMIN=MIN0 (ILONGA,ILOMIN)
        ILOMAX=MAX0 (ILONGA,ILOMAX)
      ENDIF
C
  316 CONTINUE
C
  317 CONTINUE
C*
C     3.2 - MISE A JOUR DES TABLES CONCERNEES.
C-----------------------------------------------------------------------
C
      LFI%MDES1D(IXM(LFI%JPLNAL,IRANG))=ILOMIN
      LFI%MDES1D(IXM(LFI%JPLXAL,IRANG))=ILOMAX
C
  400 CONTINUE
C**
C     4.  -  "VIDAGE" SUR FICHIER DES PAGES RESTANT A ECRIRE.
C-----------------------------------------------------------------------
C*
C     4.1 -  PAGES DE *DONNEES* RESTANT A ECRIRE.
C-----------------------------------------------------------------------
C
      DO 411 J=0,LFI%JPNPDF-1
C
      IF (LFI%LECRPD(J,IRANG)) THEN
C
        CALL LFIVID_MT (LFI, IREP,IRANG,J,ITAMPO(1),IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.EQ.2) THEN
          GOTO 904
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
      ENDIF
C
  411 CONTINUE
C*
C     4.2 -  (PAIRES DE) PAGES D'*INDEX* RESTANT A ECRIRE.
C-----------------------------------------------------------------------
C
      INPPIM=LFI%NPPIMM(IRANG)
C
      DO 423 J=1,INPPIM
      IRGPIM=LFI%MRGPIM(J,IRANG)
      IRGPIF=LFI%MRGPIF(IRGPIM)
      CALL LFIREC_MT (LFI, IRGPIF,IRANG,IREC)
C
      IF (LFI%LECRPI(IRGPIM,1)) THEN
C
        IF (J.EQ.LFI%NPODPI(IRANG).AND.LFI%NALDPI(IRANG).NE.INALPP) THEN
C
C          COMPLEMENT DE LA DERNIERE PAGE D'INDEX NOMS AVEC UN NOM
C        CONVENTIONNEL.
C
          DO 421 JJ=LFI%NALDPI(IRANG)+1,LFI%JPNXNA*IFACTM
          LFI%CNOMAR(IXC(JJ,IRGPIM))='**FIN D''INDEX**'
  421     CONTINUE
C
        ENDIF
C
        INAPHY=IREC
        CALL LFIECC_MT (LFI, IREP,KNUMER,IREC,LFI%CNOMAR(IXC(1,IRGPIM)),
     S               LFI%NBWRIT(IRANG),IFACTM,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
        LFI%LECRPI(IRGPIM,1)=.FALSE.
      ENDIF
C
      IF (LFI%LECRPI(IRGPIM,2).AND.LFI%LPHASP(IRGPIM)) THEN
C
        IF (J.EQ.LFI%NPODPI(IRANG).AND.LFI%NALDPI(IRANG).NE.INALPP) THEN
C
C          COMPLEMENT DE LA DERNIERE PAGE D'INDEX LONGUEUR/POSITION
C        AVEC DES ZEROS.
C
          DO 422 JJ=2*LFI%NALDPI(IRANG)+1,ILARPH
          LFI%MLGPOS(IXM(JJ,IRGPIM))=0
  422     CONTINUE
C
        ENDIF
C
        INAPHY=IREC+1
        CALL LFIEDO_MT (LFI, IREP,KNUMER,IREC+1,
     S                  LFI%MLGPOS(IXM(1,IRGPIM)),
     S                  LFI%NBWRIT(IRANG),IFACTM,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
        LFI%LECRPI(IRGPIM,2)=.FALSE.
      ENDIF
C
  423 CONTINUE
C*
C     4.3 -  CAS DE L'ARTICLE DOCUMENTAIRE, SI NECESSAIRE.
C-----------------------------------------------------------------------
C
      LLECRD=LFI%LMODIF(IRANG).OR.LFI%NBWRIT(IRANG).NE.0
C
      IF (LLECRD) THEN
C
C        AU PREALABLE, MISE A JOUR DE CET ARTICLE DOCUMENTAIRE.
C
        IAUXIL=IXM(LFI%JPNRES,IRANG)
        LFI%MDES1D(IAUXIL)=LFI%MDES1D(IAUXIL)+LFI%NREESP(IRANG)
        IAUXIL=IXM(LFI%JPNREC,IRANG)
        LFI%MDES1D(IAUXIL)=LFI%MDES1D(IAUXIL)+LFI%NREECO(IRANG)
        IAUXIL=IXM(LFI%JPNREL,IRANG)
        LFI%MDES1D(IAUXIL)=LFI%MDES1D(IAUXIL)+LFI%NREELO(IRANG)
        IAUXIL=IXM(LFI%JPNTRU,IRANG)
        LFI%MDES1D(IAUXIL)=LFI%MDES1D(IAUXIL)+LFI%NBTROU(IRANG)
        CALL LFIDAH_MT (LFI, LFI%MDES1D(IXM(LFI%JPDDMG,IRANG)),
     S               LFI%MDES1D(IXM(LFI%JPHDMG,IRANG)))
        IREC=1
        INAPHY=IREC
        CALL LFIEDO_MT (LFI, IREP,KNUMER,IREC,LFI%MDES1D(IXM(1,IRANG)),
     S               LFI%NBWRIT(IRANG),IFACTM,IRETIN)
C
        IF (IRETIN.EQ.1) THEN
          GOTO 903
        ELSEIF (IRETIN.NE.0) THEN
          GOTO 1001
        ENDIF
C
      ENDIF
C**
C     5.  -  FERMETURE EFFECTIVE (*CLOSE*) DU FICHIER.
C-----------------------------------------------------------------------
C
      INALDO=INBALO-LFI%MDES1D(IXM(LFI%JPNTRU,IRANG))
      INAPHY=0
C
      IF (LLSTTU) THEN
        CLOSE (UNIT=KNUMER,STATUS=CLSTTC,ERR=905,IOSTAT=IREP)
      ELSE
C
        IF (INALDO.EQ.0) THEN
C
C       SI ON SE RETROUVE AVEC UN FICHIER "VIDE" ET QUE L'ON N'A PAS DE
C       PARAMETRE "STATUS" POUR LE "CLOSE", ON VA ESSAYER DE RELACHER LE
C       FICHIER, AFIN DE NE PAS LAISSER TRAINER UN TEL FICHIER "ZOMBIE".
C             ( "VIDE" = SANS ARTICLE LOGIQUE DE DONNEES )
C       ON N'A PAS DE GARANTIE D'Y ARRIVER, DANS LA MESURE OU ON N'EST
C       PAS SUR D'AVOIR DES DROITS D'ACCES SUFFISANTS.
C
          CLOSE (UNIT=KNUMER,STATUS='DELETE',ERR=511)
          CLSTTC='DELETE'
          LLSTTU=.TRUE.
          GOTO 600
        ENDIF
C
  511   CONTINUE
C
        CLOSE (UNIT=KNUMER,ERR=905,IOSTAT=IREP)
C
      ENDIF
C
  600 CONTINUE
C**
C     6.  -  IMPRESSION EVENTUELLE DE STATISTIQUES D'UTILISATION.
C-----------------------------------------------------------------------
C
      LFI%NDEROP(IRANG)=9
      LFI%NDERCO(IRANG)=IREP
      LLIMST=LFI%NISTAG.EQ.2.OR.(LFI%NISTAG.EQ.1.AND.LFI%LISTAT(IRANG))
      IF (LLIMST) CALL LFIIST_MT (LFI, IRANG,.TRUE.)
C**
C     7.  -  "NETTOYAGE" DES TABLES AYANT PERMIS DE GERER LE FICHIER.
C            ( AU MOINS CELLES AYANT UN CARACTERE "GLOBAL"; A NOTER
C              TOUTEFOIS QU'ON NE TOUCHE PAS AUX CARACTERISTIQUES DES
C              PAGES D'INDEX PREAFFECTEES )
C-----------------------------------------------------------------------
C
       IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERGLA,'ON')
      LLVERG=LFI%LMULTI
C
      DO 702 J=2,MIN0 (INPPIM,LFI%JPNPIA)
      IRGPIM=LFI%MRGPIM(J,IRANG)
C
      DO 701 JR=IRGPIM,IRGPIM+IFACTM-1
      LFI%MRGPIF(JR)=LFI%JPNIL
  701 CONTINUE
C
  702 CONTINUE
C
      DO 704 J=LFI%JPNPIA+1,INPPIM
      IRGPIM=LFI%MRGPIM(J,IRANG)
C
      DO 703 JR=IRGPIM,IRGPIM+IFACTM-1
      LFI%MCOPIF(JR)=LFI%JPNIL
      LFI%MRGPIF(JR)=LFI%JPNIL
  703 CONTINUE
C
  704 CONTINUE
C
      LFI%NPISAF=LFI%NPISAF-MAX0 (0,(INPPIM-LFI%JPNPIA)*IFACTM)
C
      DO 705 JR=IRANG,IRANG+IFACTM-1
      LFI%NUMERO(JR)=LFI%JPNIL
  705 CONTINUE
C
      DO 706 J=1,LFI%NBFIOU
C
      IF (LFI%NUMIND(J).EQ.IRANG) THEN
        IPOSNU=J
        GOTO 707
      ENDIF
C
  706 CONTINUE
C
      IREP=-16
      GOTO 1001
C
  707 CONTINUE
C
      LFI%NBFIOU=LFI%NBFIOU-1
      LFI%NFACTM=LFI%NFACTM-IFACTM
C
      DO 708 J=IPOSNU,LFI%NBFIOU
      LFI%NUMIND(J)=LFI%NUMIND(J+1)
  708 CONTINUE
C*
C     7.1 -  ASPECTS SPECIFIQUES AUX TABLES D'IMPORT/EXPORT.
C-----------------------------------------------------------------------
C
      IF (LFI%NEXPOR(IRANG).GT.0.OR.LFI%NIMPOR(IRANG).GT.0) THEN
        IRANIE=MAX0 (LFI%NEXPOR(IRANG),LFI%NIMPOR(IRANG))
        INIMES=IXNIMS (IRANG)
C
        IF (INIMES.GE.1) THEN
          WRITE (UNIT=CLMESS,FMT='(''KNUMER='',I3,
     S           '', ATTENTION: IMPORT/EXPORT NON TERMINE'')') KNUMER
          CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,.FALSE.,
     S                    CLMESS,CLNSPR,CLACTI)
        ENDIF
C
        DO 711 J=1,LFI%NUIMEX
C
        IF (LFI%NINIEX(J).EQ.IRANIE) THEN
          IPOSNU=J
          GOTO 712
        ENDIF
C
  711   CONTINUE
C
        IREP=-16
        GOTO 1001
C
  712   CONTINUE
C
        LFI%MNUIEX(IRANG)=LFI%JPNIL
        LFI%NUIMEX=LFI%NUIMEX-1
C
        DO 713 J=IPOSNU,LFI%NUIMEX
        LFI%NINIEX(J)=LFI%NINIEX(J+1)
  713   CONTINUE
C
      ENDIF
C
       IF (LFI%LMULTI) THEN
         CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'OFF')
         CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'REL')
       ENDIF
C
      LLVERF=.FALSE.
      IREP=IREPX
      GOTO 1001
C**
C     9.  - CI-DESSOUS, ETIQUETTES DE BRANCHEMENT EN CAS D'ERREUR E/S.
C-----------------------------------------------------------------------
C
  903 CONTINUE
      CLACTI='WRITE'
      GOTO 909
C
  904 CONTINUE
      CLACTI='READ'
      GOTO 909
C
  905 CONTINUE
      CLACTI='CLOSE'
C
  909 CONTINUE
      IF (INAPHY.NE.0) LFI%NUMAPH(IRANG)=INAPHY
C
C      AU CAS OU, ON FORCE LE CODE-REPONSE ENTREE/SORTIE A ETRE POSITIF.
C
      IREP=IABS (IREP)
C**
C    10.  -  PHASE TERMINALE : MESSAGERIE, AVEC "ABORT" EVENTUEL,
C            VIA LE SOUS-PROGRAMME "LFIEMS" .
C-----------------------------------------------------------------------
C
 1001 CONTINUE
      KREP=IREP
      LLFATA=LLMOER (IREP,IRANG)
C
      IF (LLFATA) THEN
        INIMES=2
      ELSE
        INIMES=IXNIMS (IRANG)
      ENDIF
C
       IF (LLVERF) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'OFF')
       IF (LLVERG) CALL LFIVER_MT (LFI, LFI%VERGLA,'OFF')
C
      IF (.NOT.LLFATA.AND.INIMES.EQ.0)  THEN 
        IF (LHOOK) CALL DR_HOOK('LFIFER_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      IF (INIMES.EQ.2) THEN
        WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KNUMER='',I3,
     S         '', CDSTTC='''''',A,'''''''')')
     S      KREP,KNUMER,CLSTTC(:ILSTTU)
        CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,LLFATA,
     S                  CLMESS,CLNSPR,CLACTI)
      ENDIF
C
C       LA MESSAGERIE QUI SUIT N'EST PAS EMISE EN CAS D'ERREUR FATALE.
C
      IF (INIMES.GE.1.AND.(IREP.EQ.0.OR.IREP.EQ.-19)) THEN
        CLAUXI='   '
C
        IF (LFI%LFRANC) THEN
          WRITE (UNIT=CLMESS,FMT='(''Unite'',I3,
     S           '' traitee, Fichier'',A)')
     S            KNUMER,CLAUXI
        ELSE
          WRITE (UNIT=CLMESS,FMT='(''Unit'',I3,
     S           '' processed, File'',A)')
     S            KNUMER,CLAUXI
        ENDIF
C
        IDECAL=INDEX (CLMESS,CLAUXI)
C
        IF (INBALO.EQ.0) THEN
C
          IF (LFI%LFRANC) THEN
            CLMESS(IDECAL+1:)='*VIDE*'//CLAUXI
          ELSE
            CLMESS(IDECAL+1:)='*EMPTY*'//CLAUXI
          ENDIF
C
          IDECAL=IDECAL+INDEX (CLMESS(IDECAL+1:),CLAUXI)
        ENDIF
C
        IF (LFI%LFRANC) THEN
C
          IF (LFI%LNOUFI(IRANG)) THEN
            CLMESS(IDECAL+1:)='$CREE$ &'//CLAUXI
          ELSEIF (LLECRD) THEN
            CLMESS(IDECAL+1:)='$MODIFIE$ &'//CLAUXI
          ELSE
            CLMESS(IDECAL+1:)='non modifie &'//CLAUXI
          ENDIF
C
          IDECAL=IDECAL+INDEX (CLMESS(IDECAL+1:),CLAUXI)
C
          IF (.NOT.LLSTTU) THEN
            CLMESS(IDECAL+1:)='FERME'//CLAUXI
          ELSEIF (CLSTTC.EQ.'KEEP') THEN
            CLMESS(IDECAL+1:)='GARDE'//CLAUXI
          ELSE
            CLMESS(IDECAL+1:)='*RELACHE*'//CLAUXI
          ENDIF
C
          IF (LFI%LNOUFI(IRANG).OR.LLECRD) THEN
            IDECAL=IDECAL+INDEX (CLMESS(IDECAL+1:),CLAUXI)
            WRITE (UNIT=CLMESS(IDECAL+1:),
     S             FMT='(''a'',I9.6,''_'',I6.6,
     S       '','',I7,'' Articles de donnees,'',I9,'' mots en tout'')')
     S       LFI%MDES1D(IXM(LFI%JPDDMG,IRANG)),
     S       LFI%MDES1D(IXM(LFI%JPHDMG,IRANG)),
     S       INALDO,ILARPH*LFI%MDES1D(IXM(LFI%JPNAPH,IRANG))
          ENDIF
C
        ELSE
C
          IF (LFI%LNOUFI(IRANG)) THEN
            CLMESS(IDECAL+1:)='$CREATED$ &'//CLAUXI
          ELSEIF (LLECRD) THEN
            CLMESS(IDECAL+1:)='$MODIFIED$ &'//CLAUXI
          ELSE
            CLMESS(IDECAL+1:)='not modified &'//CLAUXI
          ENDIF
C
          IDECAL=IDECAL+INDEX (CLMESS(IDECAL+1:),CLAUXI)
C
          IF (.NOT.LLSTTU) THEN
            CLMESS(IDECAL+1:)='CLOSED'//CLAUXI
          ELSEIF (CLSTTC.EQ.'KEEP') THEN
            CLMESS(IDECAL+1:)='KEPT'//CLAUXI
          ELSE
            CLMESS(IDECAL+1:)='*RELEASED*'//CLAUXI
          ENDIF
C
          IF (LFI%LNOUFI(IRANG).OR.LLECRD) THEN
            IDECAL=IDECAL+INDEX (CLMESS(IDECAL+1:),CLAUXI)
            WRITE (UNIT=CLMESS(IDECAL+1:),FMT='(''at'',I9.6,''_'',
     S I6.6,'','',I7,'' data Records,'',I9,'' words for a whole'')')
     S       LFI%MDES1D(IXM(LFI%JPDDMG,IRANG)),
     S       LFI%MDES1D(IXM(LFI%JPHDMG,IRANG)),
     S       INALDO,ILARPH*LFI%MDES1D(IXM(LFI%JPNAPH,IRANG))
          ENDIF
C
        ENDIF
C
        CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,.FALSE.,
     S                  CLMESS,CLNSPR,CLACTI)
C
        IF (LFI%LFRANC) THEN
          INLNOM=MIN0 (LFI%NLNOMF(IRANG),LFI%JPLFIX,LEN (CLMESS)-6)
          CLMESS='Nom='''//LFI%CNOMFI(IRANG)(1:INLNOM)//''''
        ELSE
          INLNOM=MIN0 (LFI%NLNOMF(IRANG),LFI%JPLFIX,LEN (CLMESS)-7)
          CLMESS='Name='''//LFI%CNOMFI(IRANG)(1:INLNOM)//''''
        ENDIF
C
        CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,.FALSE.,
     S                  CLMESS,CLNSPR,CLACTI)
C
        IF (LFI%CNOMSY(IRANG)(1:LFI%NLNOMS(IRANG)).NE.
     S      LFI%CNOMFI(IRANG)(1:LFI%NLNOMF(IRANG))) THEN
C
          IF (LFI%LFRANC) THEN
            INLNOM=MIN0 (LFI%NLNOMS(IRANG),LFI%JPLFIX,
     S                   LEN (CLMESS)-14)
            CLMESS='Nom SYSTEME='''//
     S                 LFI%CNOMSY(IRANG)(1:INLNOM)//''''
          ELSE
            INLNOM=MIN0 (LFI%NLNOMS(IRANG),LFI%JPLFIX,
     S                   LEN (CLMESS)-14)
            CLMESS='SYSTEM Name='''//
     S                  LFI%CNOMSY(IRANG)(1:INLNOM)//''''
          ENDIF
C
          CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,.FALSE.,
     S                    CLMESS,CLNSPR,CLACTI)
        ENDIF
C
      ENDIF
C
      IF (LHOOK) CALL DR_HOOK('LFIFER_MT',1,ZHOOK_HANDLE)
      END

