      SUBROUTINE LFIINTLEC_MT (LFI, KREP, KNUMER, CDNOMA, KTAB, KLONG )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C
C****
C        SOUS-PROGRAMME DE LECTURE  D'UN TABLEAU D'ENTIERS A PARTIR 
C     D'UN ARTICLE (DE DONNEES) PAR *NOM*
C     SUR UNE UNITE LOGIQUE OUVERTE POUR LE LOGICIEL DE FICHIERS INDEXES
C     *LFI*; L'ARTICLE EN SORTIE EST UN "BLOC" DE DONNEES ADJACENTES.
C**
C    ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                KNUMER (ENTREE) ==> LFI%NUMERO DE L'UNITE LOGIQUE;
C                CDNOMA (ENTREE) ==> NOM DE L'ARTICLE A RECHERCHER;
C                KTAB   (SORTIE) ==> PREMIER MOT A LIRE;
C                KLONG  (ENTREE) ==> LONGUEUR DE L'ARTICLE A LIRE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      CHARACTER CDNOMA*(*)
      INTEGER KREP, KNUMER, KLONG, KTAB(KLONG)

      INTEGER JI
#ifndef f77
      INTEGER (KIND=JPDBLE)  ITAB (KLONG)
#else
      INTEGER ITAB (KLONG)
#endif
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIINTLEC_MT',0,ZHOOK_HANDLE)
      CALL LFILEC_MT (LFI,  KREP, KNUMER, CDNOMA, ITAB, KLONG )
      DO 10 JI=1,KLONG
        KTAB(JI)=INT(ITAB(JI))
10    CONTINUE 
C
      IF (LHOOK) CALL DR_HOOK('LFIINTLEC_MT',1,ZHOOK_HANDLE)
      END

