C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIMOE_MT ( LFI, KREP, KRANG, KRETIN )
      USE LFIMOD,   ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        SOUS-PROGRAMME *INTERNE* DU LOGICIEL DE FICHIERS INDEXES LFI
C     MODIFICATION DE L'ARTICLE DOCUMENTAIRE, LIMITEE A 3 ELEMENTS,
C     LORSQUE LE FICHIER A SUBI SA PREMIERE MODIFICATION DEPUIS LA
C     DERNIERE OUVERTURE.
C
C     APPELE PAR LFIECR, LFIREN, LFISUP.
C**
C    ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                KRANG  (ENTREE) ==> RANG ( DANS LA TABLE *LFI%NUMERO* )
C                                    DE L'UNITE LOGIQUE CONCERNEE;
C                KRETIN (SORTIE) ==> CODE-RETOUR INTERNE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
#ifndef f77
      INTEGER (KIND=JPDBLE) IDESCR (LFI%JPLARX)
#else
      INTEGER IDESCR (LFI%JPLARX)
#endif
      INTEGER KREP, KRANG, KRETIN, INUMER, IFACTM, IREC
      INTEGER IRANG, INAPHY, IRETOU, INIMES, IRETIN
C
#include "lficom2.h"
#include "lficom_mt.h"
C**
C     1. -  CONTROLES DES PARAMETRES D'APPEL ET INITIALISATIONS.
C-----------------------------------------------------------------------
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIMOE_MT',0,ZHOOK_HANDLE)
      IRETOU=0
C
      IF (KRANG.LE.0.OR.KRANG.GT.LFI%JPNXFI) THEN
        KREP=-16
        GOTO 1001
      ENDIF
C
      IRANG=KRANG
      KREP=0
      INUMER=LFI%NUMERO(IRANG)
      IFACTM=LFI%MFACTM(IRANG)
      IREC=1
C**
C     2. -  LECTURE/MODIFICATION/REECRITURE DE L'ARTICLE DOCUMENTAIRE.
C-----------------------------------------------------------------------
C
      INAPHY=IREC
      CALL LFILDO_MT (LFI, KREP,INUMER,IREC,IDESCR(1),
     S                LFI%NBREAD(IRANG),IFACTM,IRETIN)
C
      IF (IRETIN.NE.0) THEN
        GOTO 904
      ENDIF
C
      IDESCR(LFI%JPFEAM)=1
      CALL LFIDAH_MT (LFI, IDESCR(LFI%JPDMNG),IDESCR(LFI%JPHMNG))
      LFI%MDES1D(IXM(LFI%JPDMNG,IRANG))=IDESCR(LFI%JPDMNG)
      LFI%MDES1D(IXM(LFI%JPHMNG,IRANG))=IDESCR(LFI%JPHMNG)
      CALL LFIEDO_MT (LFI, KREP,INUMER,IREC,IDESCR(1),
     S                LFI%NBWRIT(IRANG),IFACTM,IRETIN)
C
      IF (IRETIN.NE.0) THEN
        GOTO 903
      ENDIF
C
      GOTO 1001
C**
C     9.  - CI-DESSOUS, ETIQUETTES DE BRANCHEMENT EN CAS D'ERREUR E/S.
C      AU CAS OU, ON FORCE LE CODE-REPONSE ENTREE/SORTIE A ETRE POSITIF.
C-----------------------------------------------------------------------
C
  903 CONTINUE
      IRETOU=1
      CLACTI='WRITE'
      GOTO 909
C
  904 CONTINUE
      IRETOU=2
      CLACTI='READ'
C
  909 CONTINUE
      KREP=IABS (KREP)
      LFI%NUMAPH(IRANG)=INAPHY
C**
C    10.  -  PHASE TERMINALE : MESSAGERIE INTERNE EVENTUELLE,
C            VIA LE SOUS-PROGRAMME "LFIEMS", PUIS RETOUR.
C-----------------------------------------------------------------------
C
 1001 CONTINUE
      LLFATA=LLMOER (KREP,KRANG)
C
      IF (KREP.EQ.0) THEN
        KRETIN=0
      ELSEIF (KREP.GT.0) THEN
        KRETIN=IRETOU
      ELSE
        KRETIN=3
      ENDIF
C
      IF (LFI%LMISOP.OR.LLFATA) THEN
        INUMER=LFI%NUMERO(KRANG)
        INIMES=2
        CLNSPR='LFIMOE'
        WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KRANG='',I3,
     S  '', KRETIN='',I2)')
     S    KREP,KRANG,KRETIN
        CALL LFIEMS_MT (LFI, INUMER,INIMES,KREP,.FALSE.,
     S                  CLMESS,CLNSPR,CLACTI)
      ENDIF
C
      IF (LHOOK) CALL DR_HOOK('LFIMOE_MT',1,ZHOOK_HANDLE)
      END

