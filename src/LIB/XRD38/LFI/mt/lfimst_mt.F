C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIMST_MT (LFI, KREP, KNUMER, LDIMST )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME PERMET D'ACTIVER OU DE DESACTIVER L'OPTION
C     D'IMPRESSION DE STATISTIQUES A LA FERMETURE D'UN FICHIER
C     PARTICULIER, OUVERT POUR LE LOGICIEL LFI.
C        CEPENDANT, TANT QUE LE NIVEAU GLOBAL D'IMPRESSION DES STAT.
C     *LFI%NISTAG* VAUT 0 OU 2, L'OPTION PROPRE AU FICHIER EST INOPERANTE.
C     *LFI%NISTAG* VAUT PAR DEFAUT 1, ET EST REGLABLE VIA LE S/P "LFINSG".
C**
C     ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                 KNUMER (ENTREE) ==> LFI%NUMERO D'UNITE LOGIQUE CONCERNEE;
C                 LDIMST (ENTREE) ==> OPTION D'IMPRESSION (VRAI=OUI)
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KREP, KNUMER, IRANG, IREP, INIMES
C
      LOGICAL LDIMST
C
#include "lficom2.h"
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIMST_MT',0,ZHOOK_HANDLE)
      CALL LFINUM_MT (LFI, KNUMER,IRANG)
C
      IF (IRANG.NE.0) THEN
         IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'ON')
        LFI%LISTAT(IRANG)=LDIMST
        LFI%NDEROP(IRANG)=3
         IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'OFF')
        IREP=0
      ELSE
        IREP=-1
      ENDIF
C
      KREP=IREP
      LLFATA=LLMOER (IREP,IRANG)
C
      IF (LLFATA.OR.IXNIMS (IRANG).EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFIMST_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      CLNSPR='LFIMST'
      WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KNUMER='',I3,
     S       '', LDIMST= '',L1)') KREP,KNUMER,LDIMST
      CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFIMST_MT',1,ZHOOK_HANDLE)
      END

