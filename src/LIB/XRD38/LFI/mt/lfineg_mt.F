      SUBROUTINE LFINEG_MT (LFI, KNIVAU )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME SE CHARGE DE METTRE LE NIVEAU GLOBAL D'ERREUR
C     FATALE (*LFI%NERFAG*) A LA VALEUR KNIVAU . PAR  DEFAUT, LFI%NERFAG VAUT 1.
C**
C        ARGUMENT : KNIVAU (ENTREE) ==> NIVEAU GLOBAL D'ERREUR FATALE.
C                                       VALEURS POSSIBLES
C
C     0 : RENDRE FATALE TOUTE ERREUR DETECTEE, MEME SI ELLE CORRESPOND
C         A UN FICHIER OUVERT AVEC L'OPTION "PAS D'ERREUR FATALE".
C     1 : NE REND FATALES QUE CERTAINES ERREURS "GLOBALES", C'EST-A-DIRE
C         NON RELIABLES A UN FICHIER OUVERT, ET LES ERREURS SUR LES  FI-
C         CHIERS OUVERTS AVEC L'OPTION "ERREUR FATALE" (MODE PAR DEFAUT)
C     2 : PASSER OUTRE TOUTE ERREUR DETECTEE, MEME SI ELLE CORRESPOND
C         A UN FICHIER OUVERT AVEC L'OPTION "ERREUR FATALE".
C         NEANMOINS, LE CODE-REPONSE EVENTUEL NE SERA PAS ZERO.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KNIVAU, INIMES, IREP, INUMER
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFINEG_MT',0,ZHOOK_HANDLE)
      IF (LFI%LFINEG_LLPREA) THEN
        CALL LFIINI_MT (LFI, 2)
        LFI%LFINEG_LLPREA=.FALSE.
      ENDIF
C
      IF (KNIVAU.GE.0.AND.KNIVAU.LE.2) THEN
        LFI%NERFAG=KNIVAU
        IREP=0
      ELSE
        IREP=-2
      ENDIF
C
      LLFATA=IREP.NE.0.AND.LFI%NERFAG.NE.2
C
      IF (LLFATA) THEN
        INIMES=2
      ELSEIF (IREP.NE.0) THEN
        INIMES=0
      ELSEIF (LFI%NIMESG.EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFINEG_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      INUMER=LFI%JPNIL
      CLNSPR='LFINEG'
C
      IF (MAX0 (INIMES,LFI%NIMESG).EQ.2) THEN
C
        IF (LFI%LFRANC) THEN
          WRITE (UNIT=CLMESS,
     S           FMT='(''KNIVAU='',I5,'', CODE INTERNE='',
     S           I4)') KNIVAU,IREP
        ELSE
          WRITE (UNIT=CLMESS,
     S           FMT='(''KNIVAU='',I5,'', INTERNAL CODE='',
     S           I4)') KNIVAU,IREP
        ENDIF
C
        IF (INIMES.NE.2) CALL LFIEMS_MT (LFI, INUMER,LFI%NIMESG,IREP,
     S                                   .FALSE.,CLMESS,
     S                                   CLNSPR,CLACTI)
      ENDIF
C
      CALL LFIEMS_MT (LFI, INUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFINEG_MT',1,ZHOOK_HANDLE)
      END

