C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFINIM_MT (LFI, KREP, KNUMER, KNIMES )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME PERMET D'AJUSTER LE NIVEAU DE MESSAGERIE
C     PROPRE AUX ACTIONS FAITES SUR UN FICHIER PARTICULIER, OUVERT POUR
C     LE LOGICIEL LFI.
C        CEPENDANT, TANT QUE LE NIVEAU DE MESSAGERIE GLOBAL *LFI%NIMESG*
C     VAUT 0 OU 2, LE NIVEAU PROPRE AU FICHIER EST INOPERANT.
C     *LFI%NIMESG* VAUT PAR DEFAUT 1, ET EST REGLABLE VIA LE S/P "LFINMG".
C**
C     ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                 KNUMER (ENTREE) ==> LFI%NUMERO D'UNITE LOGIQUE CONCERNEE;
C                 KNIMES (ENTREE) ==> NIVEAU DE MESSAGERIE SOUHAITE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KREP, KNUMER, KNIMES, IRANG, IREP, INIMES, INIMEX
C
#include "lficom2.h"
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFINIM_MT',0,ZHOOK_HANDLE)
      CALL LFINUM_MT (LFI, KNUMER,IRANG)
      INIMEX=0
C
      IF (IRANG.EQ.0) THEN
        IREP=-1
      ELSEIF (KNIMES.GE.0.AND.KNIMES.LE.2) THEN
        INIMEX=IXNIMS (IRANG)
        LFI%NIVMES(IRANG)=KNIMES
        LFI%NDEROP(IRANG)=5
        IREP=0
      ELSE
        IREP=-2
      ENDIF
C
      KREP=IREP
      LLFATA=LLMOER (IREP,IRANG)
C
      IF (LLFATA.OR.MAX0 (IXNIMS (IRANG),INIMEX).EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFINIM_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      CLNSPR='LFINIM'
      WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KNUMER='',I3,
     S       '', KNIMES='',I3)') KREP,KNUMER,KNIMES
      CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFINIM_MT',1,ZHOOK_HANDLE)
      END

