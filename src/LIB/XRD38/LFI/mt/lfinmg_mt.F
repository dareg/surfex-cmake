      SUBROUTINE LFINMG_MT (LFI, KNIVAU )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME SE CHARGE DE METTRE LE NIVEAU GLOBAL
C     D'IMPRESSION DES MESSAGES (*LFI%NIMESG*) A LA VALEUR KNIVAU .
C**
C        ARGUMENT : KNIVAU (ENTREE) ==> NIVEAU GLOBAL D'IMPRESSION
C                                       DES MESSAGES .
C                                       VALEURS POSSIBLES
C
C     0 : N'EMETTRE QUE LES MESSAGES D'ERREURS REELLEMENT IMPORTANTS .
C     1 : N'EMETTRE QU'UN MINIMUM DE MESSAGES "GLOBAUX", ET LES MESSAGES
C         LIES A UN FICHIER OUVERT QUI SONT DE NIVEAU AU PLUS EGAL AU
C         NIVEAU DE LA MESSAGERIE POUR CE FICHIER (MODE PAR DEFAUT) .
C     2 : EMETTRE TOUS LES MESSAGES POSSIBLES, MEME S'ILS NE CORRESPON-
C         DENT PAS A UN FICHIER OUVERT AVEC LE NIVEAU DE MESSAGERIE 2 .
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KNIVAU, INIMES, IREP, INUMER
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFINMG_MT',0,ZHOOK_HANDLE)
      IF (LFI%LFINMG_LLPREA) THEN
        CALL LFIINI_MT (LFI, 2)
        LFI%LFINMG_LLPREA=.FALSE.
      ENDIF
C
      IF (KNIVAU.GE.0.AND.KNIVAU.LE.2) THEN
        INIMES=MAX0 (LFI%NIMESG,KNIVAU)
        LFI%NIMESG=KNIVAU
        IREP=0
      ELSE
        INIMES=LFI%NIMESG
        IREP=-2
      ENDIF
C
      LLFATA=IREP.NE.0.AND.LFI%NERFAG.NE.2
C
      IF (LLFATA) THEN
        INIMES=2
      ELSEIF (IREP.NE.0) THEN
        INIMES=0
      ELSEIF (INIMES.EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFINMG_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      INUMER=LFI%JPNIL
      CLNSPR='LFINMG'
C
      IF (MAX0 (INIMES,LFI%NIMESG).EQ.2) THEN
C
        IF (LFI%LFRANC) THEN
          WRITE (UNIT=CLMESS,
     S           FMT='(''KNIVAU='',I5,'', CODE INTERNE='',
     S           I4)') KNIVAU,IREP
        ELSE
          WRITE (UNIT=CLMESS,
     S           FMT='(''KNIVAU='',I5,'', INTERNAL CODE='',
     S           I4)') KNIVAU,IREP
        ENDIF
C
        IF (INIMES.NE.2) CALL LFIEMS_MT (LFI, INUMER,LFI%NIMESG,IREP,
     S                                   .FALSE.,CLMESS,
     S                                   CLNSPR,CLACTI)
      ENDIF
C
      CALL LFIEMS_MT (LFI, INUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFINMG_MT',1,ZHOOK_HANDLE)
      END

