      SUBROUTINE LFINSG_MT (LFI, KNIVAU )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME SE CHARGE DE METTRE LE NIVEAU GLOBAL
C     D'IMPRESSION DES STATISTIQUES A LA FERMETURE (*LFI%NISTAG*)
C     A LA VALEUR KNIVAU . PAR DEFAUT, LFI%NISTAG VAUT 1 .
C**
C        ARGUMENT : KNIVAU (ENTREE) ==> NIVEAU GLOBAL D'IMPRESSION DES
C                                       STATISTIQUES; VALEURS POSSIBLES
C
C     0 : NE PAS IMPRIMER LES STATISTIQUES A LA FERMETURE D'UN
C         FICHIER, MEME SI CELA AVAIT ETE DEMANDE LORS DE SON OUVERTURE.
C     1 : N'IMPRIMER LES STATISTIQUES A LA FERMETURE QUE SI CELA
C         AVAIT ETE DEMANDE LORS DE L'OUVERTURE (MODE PAR DEFAUT).
C     2 : IMPRIMER LES STATISTIQUES A LA FERMETURE D'UN FICHIER,
C         MEME SI LE FICHIER AVAIT ETE OUVERT SANS CETTE OPTION.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KNIVAU, INIMES, IREP, INUMER
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFINSG_MT',0,ZHOOK_HANDLE)
      IF (LFI%LFINSG_LLPREA) THEN
        CALL LFIINI_MT (LFI, 2)
        LFI%LFINSG_LLPREA=.FALSE.
      ENDIF
C
      IF (KNIVAU.GE.0.AND.KNIVAU.LE.2) THEN
        LFI%NISTAG=KNIVAU
        IREP=0
      ELSE
        IREP=-2
      ENDIF
C
C        MESSAGERIE EVENTUELLE, AVEC ABORT SI NECESSAIRE .
C
      LLFATA=IREP.NE.0.AND.LFI%NERFAG.NE.2
C
      IF (LLFATA) THEN
        INIMES=2
      ELSEIF (IREP.NE.0) THEN
        INIMES=0
      ELSEIF (LFI%NIMESG.EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFINSG_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      INUMER=LFI%JPNIL
      CLNSPR='LFINSG'
C
      IF (MAX0 (INIMES,LFI%NIMESG).EQ.2) THEN
C
        IF (LFI%LFRANC) THEN
          WRITE (UNIT=CLMESS,
     S           FMT='(''KNIVAU='',I5,'', CODE INTERNE='',
     S           I4)') KNIVAU,IREP
        ELSE
          WRITE (UNIT=CLMESS,
     S           FMT='(''KNIVAU='',I5,'', INTERNAL CODE='',
     S           I4)') KNIVAU,IREP
        ENDIF
C
        IF (INIMES.NE.2) CALL LFIEMS_MT (LFI, INUMER,LFI%NIMESG,IREP,
     S                                   .FALSE.,CLMESS,
     S                                   CLNSPR,CLACTI)
      ENDIF
C
      CALL LFIEMS_MT (LFI, INUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFINSG_MT',1,ZHOOK_HANDLE)
      END

