C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFINUM_MT (LFI, KNUMER, KRANG )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME CALCULE LE RANG DU LFI%NUMERO D'UNITE LOGIQUE
C     *KNUMER* DANS LA TABLE DES UNITES LOGIQUES *LFI%NUMERO*;
C     S'IL N'Y EST PAS TROUVE, LE RESULTAT EST ZERO.
C        CE SOUS-PROGRAMME, APPELE PAR *TOUS* LES SOUS-PROGRAMMES NON
C     GLOBAUX DU LOGICIEL DE FICHIERS INDEXES LFI, SE CHARGE LORS DE SON
C     PREMIER APPEL D'APPELER LE SOUS-PROGRAMME PREPARATOIRE LFIINI.
C**
C       ARGUMENTS : KNUMER (ENTREE) ==> LFI%NUMERO D'UNITE LOGIQUE CHERCHE;
C                   KRANG  (SORTIE) ==> RANG DANS LA TABLE DES FICHIERS
C                                       DU LOGICIEL LFI (0 SI ABSENT).
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KNUMER, KRANG, J, IRESUL, IREP, INIMES
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFINUM_MT',0,ZHOOK_HANDLE)
      IF (LFI%LFINUM_LLPREA) THEN
        CALL LFIINI_MT (LFI, 2)
        LFI%LFINUM_LLPREA=.FALSE.
      ENDIF
C
C          VERROUILLAGE GLOBAL (A CAUSE DE L'UTILISATION DE LFI%NBFIOU )
C
       IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERGLA,'ON')
C
      DO 10 J=1,LFI%NBFIOU
C
      IF (KNUMER.EQ.LFI%NUMERO(LFI%NUMIND(J))) THEN
        IRESUL=LFI%NUMIND(J)
        GOTO 20
      ENDIF
C
   10 CONTINUE
C
      IRESUL=0
C
   20 CONTINUE
C
C          DEVERROUILLAGE GLOBAL
C
       IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERGLA,'OFF')
      KRANG=IRESUL
C**
C    10.  -  PHASE TERMINALE : MESSAGERIE INTERNE EVENTUELLE,
C            VIA LE SOUS-PROGRAMME "LFIEMS", PUIS RETOUR.
C-----------------------------------------------------------------------
C
      IF (LFI%LMISOP) THEN
        IREP=0
        INIMES=2
        CLNSPR='LFINUM'
        WRITE (UNIT=CLMESS,FMT='(''KNUMER='',I3,'', KRANG='',I3)')
     S    KNUMER,KRANG
        CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,.FALSE.,
     S                  CLMESS,CLNSPR,CLACTI)
      ENDIF
C
      IF (LHOOK) CALL DR_HOOK('LFINUM_MT',1,ZHOOK_HANDLE)
      END

