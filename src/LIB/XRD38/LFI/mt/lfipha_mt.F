C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIPHA_MT (LFI, KREP, KRANG, KRGPIM, KRETIN )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        SOUS-PROGRAMME *INTERNE* DU LOGICIEL DE FICHIERS INDEXES LFI
C     PHASAGE D'UNE PAGE D'INDEX "LONGUEUR/POSITION"
C     AVEC LA PAGE D'INDEX "NOMS" CORRESPONDANTE.
C        IL EST ABSOLUMENT NECESSAIRE QUE LA PAGE D'INDEX "NOMS" SOIT
C     EFFECTIVEMENT ALIMENTEE AVANT L'APPEL DE CE SOUS-PROGRAMME...
C**
C    ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DE LA LECTURE DE PAGE;
C                KRANG  (ENTREE) ==> RANG DE L'UNITE LOGIQUE CONCERNEE;
C                KRGPIM (ENTREE) ==> LFI%NUMERO DE LA PAGE CONCERNEE;
C                KRETIN (SORTIE) ==> CODE-RETOUR INTERNE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KREP, KRANG, KRGPIM, KRETIN, INUMER, IREC, INAPHY, INIMES
      INTEGER IRETOU, IRETIN
C
#include "lficom2.h"
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIPHA_MT',0,ZHOOK_HANDLE)
      IRETOU=0
      INUMER=LFI%NUMERO(KRANG)
      CALL LFIREC_MT (LFI, LFI%MRGPIF(KRGPIM),KRANG,IREC)
      INAPHY=IREC+1
      CALL LFILDO_MT (LFI, KREP,INUMER,IREC+1,LFI%MLGPOS(IXM(1,KRGPIM)),
     S             LFI%NBREAD(KRANG),LFI%MFACTM(KRANG),IRETIN)
C
      IF (IRETIN.NE.0) THEN
        GOTO 904
      ENDIF
C
      LFI%LPHASP(KRGPIM)=.TRUE.
      GOTO 1001
C
  904 CONTINUE
      IRETOU=2
      CLACTI='READ'
C
C      AU CAS OU, ON FORCE LE CODE-REPONSE ENTREE/SORTIE A ETRE POSITIF.
C
      KREP=IABS (KREP)
      LFI%NUMAPH(KRANG)=INAPHY
C**
C    10.  -  PHASE TERMINALE : MESSAGERIE INTERNE EVENTUELLE,
C            VIA LE SOUS-PROGRAMME "LFIEMS", PUIS RETOUR.
C-----------------------------------------------------------------------
C
 1001 CONTINUE
      LLFATA=LLMOER (KREP,KRANG)
C
      IF (KREP.EQ.0) THEN
        KRETIN=0
      ELSEIF (KREP.GT.0) THEN
        KRETIN=IRETOU
      ELSE
        KRETIN=3
      ENDIF
C
      IF (LFI%LMISOP.OR.LLFATA) THEN
        INIMES=2
        CLNSPR='LFIPHA'
        WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KRANG='',I3,
     S         '', KRGPIM='',I3,'', KRETIN='',I2)')
     S    KREP,KRANG,KRGPIM,KRETIN
        CALL LFIEMS_MT (LFI, INUMER,INIMES,KREP,.FALSE.,
     S                  CLMESS,CLNSPR,CLACTI)
      ENDIF
C
      IF (LHOOK) CALL DR_HOOK('LFIPHA_MT',1,ZHOOK_HANDLE)
      END

