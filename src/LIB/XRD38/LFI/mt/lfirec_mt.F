C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFIREC_MT (LFI, KRGPIF, KRANG, KREC )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        SOUS-PROGRAMME *INTERNE* DU LOGICIEL DE FICHIERS INDEXES LFI
C     DETERMINATION DU LFI%NUMERO D'ENREGISTREMENT D'UNE PAIRE D'ARTICLES
C     D'INDEX ( LFI%NUMERO DE L'ARTICLE "NOMS", EN FAIT ) .
C**
C    ARGUMENTS : KRGPIF (ENTREE) ==> RANG DE LA P.P.I. DANS LE FICHIER;
C                KRANG  (ENTREE) ==> RANG DE L'UNITE DANS LFI%NUMERO.
C                KREC   (SORTIE) ==> LFI%NUMERO D'ENREGISTREMENT DE LA P.A.I
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KRGPIF, KRANG, KREC, INBPIR, INBALO, IFACTM, INALPP
      INTEGER ILARPH, INTPPI, IREP, INIMES, INUMER
C
#include "lficom2.h"
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFIREC_MT',0,ZHOOK_HANDLE)
      INBPIR=LFI%MDES1D(IXM(LFI%JPNPIR,KRANG))
      INBALO=LFI%MDES1D(IXM(LFI%JPNALO,KRANG))
      IFACTM=LFI%MFACTM(KRANG)
      INALPP=LFI%JPNAPP*IFACTM
      ILARPH=LFI%JPLARD*IFACTM
      INTPPI=(INBALO-1+INALPP)/INALPP
C
      IF (KRGPIF.LE.INBPIR) THEN
        KREC=2*KRGPIF
      ELSEIF (KRGPIF.LE.INTPPI) THEN
C
C     CAS OU LES ARTICLES D'INDEX "RESERVES" A LA CREATION DU FICHIER
C     N'ONT PAS SUFFI A STOCKER TOUS LES DESCRIPTEURS D'ARTICLES LOGI-
C     QUES: L'EMPLACEMENT DES PAIRES D'ARTICLES D'INDEX EXCEDENTAIRES
C     EST ALORS STOCKE DANS L'ARTICLE DOCUMENTAIRE, APRES LES VALEURS
C     "UTILES" (LFI%JPLDOC MOTS), EN COMMENCANT PAR LA FIN DE CET ARTICLE.
C       ( CECI POUR MENAGER UNE EVENTUELLE AUGMENTATION DE *LFI%JPLDOC*,
C         EN CAS D'EVOLUTION DU LOGICIEL )
C
        KREC=LFI%MDES1D(IXM(ILARPH+1-(KRGPIF-INBPIR),KRANG))
      ELSE
C
C          CAS OU IL Y A INCOHERENCE ENTRE TABLES ET ARGUMENTS D'APPEL
C
        KREC=0
        IREP=-16
C
C        MESSAGERIE EVENTUELLE, AVEC ABORT SI NECESSAIRE .
C
        LLFATA=LLMOER (IREP,KRANG)
C
        IF (LLFATA.OR.LFI%NIMESG.NE.0) THEN
          INIMES=2
          CLNSPR='LFIREC'
          INUMER=LFI%NUMERO(KRANG)
C
          IF (LFI%LFRANC) THEN
            WRITE (UNIT=CLMESS,FMT='(''KRGPIF='',I4,'', KRANG='',I3,
     S             '', KREC='',I6,'', CODE "INTERNE"='',I4)')
     S        KRGPIF,KRANG,KREC,IREP
          ELSE
            WRITE (UNIT=CLMESS,FMT='(''KRGPIF='',I4,'', KRANG='',I3,
     S             '', KREC='',I6,'', "INTERNAL" CODE='',I4)')
     S        KRGPIF,KRANG,KREC,IREP
          ENDIF
C
          CALL LFIEMS_MT (LFI, INUMER,INIMES,IREP,LLFATA,
     S                    CLMESS,CLNSPR,CLACTI)
        ENDIF
C
      ENDIF
C
      IF (LHOOK) CALL DR_HOOK('LFIREC_MT',1,ZHOOK_HANDLE)
      END

