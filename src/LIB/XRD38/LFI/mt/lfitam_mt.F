C Jan-2011 P. Marguinaud Thread-safe LFI
      SUBROUTINE LFITAM_MT (LFI, KREP, KNUMER, LDTAML, LDTAME )
      USE LFIMOD, ONLY : LFICOM
      USE PARKIND1, ONLY : JPRB
      USE YOMHOOK , ONLY : LHOOK, DR_HOOK
C****
C        CE SOUS-PROGRAMME PERMET D'ACTIVER OU DE DESACTIVER LES OPTIONS
C     D'UTILISATION MAXIMUM DE LA MEMOIRE TAMPON SUR UN FICHIER
C     PARTICULIER, OUVERT POUR LE LOGICIEL LFI.
C        LES OPTIONS INITIALES SONT DEFINIES A L'OUVERTURE PAR LES
C     VARIABLES GLOBALES *LFI%LTAMLG* ET *LFI%LTAMEG*, RESPECTIVEMENT POUR LES
C     OPERATIONS DE LECTURE ET D'ECRITURE .
C     ( CES VARIABLES GLOBALES SONT DEFINIES DANS LE S/P *LFIINI* )
C**
C     ARGUMENTS : KREP   (SORTIE) ==> CODE-REPONSE DU SOUS-PROGRAMME;
C                 KNUMER (ENTREE) ==> LFI%NUMERO D'UNITE LOGIQUE CONCERNEE;
C                 LDTAML (ENTREE) ==> OPTION D'UTILISATION MAXIMUM DE LA
C                                     LA MEMOIRE TAMPON EN LECTURE;
C                 LDTAME (ENTREE) ==> CF. CI-DESSUS, EN ECRITURE.
C
#ifndef f77
#include "precision.h"
#endif
C
      TYPE(LFICOM) :: LFI
      INTEGER KREP, KNUMER, IRANG, IREP, INIMES
C
      LOGICAL LDTAML, LDTAME
C
#include "lficom2.h"
#include "lficom_mt.h"
C
      REAL(KIND=JPRB) :: ZHOOK_HANDLE
      IF (LHOOK) CALL DR_HOOK('LFITAM_MT',0,ZHOOK_HANDLE)
      CALL LFINUM_MT (LFI, KNUMER,IRANG)
C
      IF (IRANG.NE.0) THEN
         IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'ON')
        LFI%LTAMPL(IRANG)=LDTAML
        LFI%LTAMPE(IRANG)=LDTAME
        LFI%NDEROP(IRANG)=6
         IF (LFI%LMULTI) CALL LFIVER_MT (LFI, LFI%VERRUE(IRANG),'OFF')
        IREP=0
      ELSE
        IREP=-1
      ENDIF
C
      LLFATA=LLMOER (IREP,IRANG)
      KREP=IREP
C
      IF (LLFATA.OR.IXNIMS (IRANG).EQ.2) THEN
        INIMES=2
      ELSE
        IF (LHOOK) CALL DR_HOOK('LFITAM_MT',1,ZHOOK_HANDLE)
        RETURN
      ENDIF
C
      CLNSPR='LFITAM'
      WRITE (UNIT=CLMESS,FMT='(''KREP='',I4,'', KNUMER='',I3,
     S  '', LDTAML= '',L1,'', LDTAME= '',L1)') KREP,KNUMER,LDTAML,LDTAME
      CALL LFIEMS_MT (LFI, KNUMER,INIMES,IREP,LLFATA,
     S                CLMESS,CLNSPR,CLACTI)
C
      IF (LHOOK) CALL DR_HOOK('LFITAM_MT',1,ZHOOK_HANDLE)
      END

