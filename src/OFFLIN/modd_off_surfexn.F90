  CALL DIAG_WATFLUX_INIT(YSURF_LIST(J)%DGW)
  CALL DST_INIT(YSURF_LIST(J)%DST)
  CALL DUMMY_SURF_FIELDS_INIT(YSURF_LIST(J)%DUU)
  CALL EMIS_GR_FIELD_INIT(YSURF_LIST(J)%EGF)
  CALL FLAKE_GRID_INIT(YSURF_LIST(J)%FG)
  CALL FLAKE_INIT(YSURF_LIST(J)%F)
  CALL FLAKE_SBL_INIT(YSURF_LIST(J)%FSB)
  CALL GR_BIOG_GARDEN_INIT(YSURF_LIST(J)%GBGD)
  CALL GR_BIOG_GREENROOF_INIT(YSURF_LIST(J)%GBGR)
  CALL GR_BIOG_INIT(YSURF_LIST(J)%GB)
  CALL IDEAL_INIT(YSURF_LIST(J)%L)
