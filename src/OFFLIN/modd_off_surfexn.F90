  CALL TEB_GREENROOF_PGD_INIT(YSURF_LIST(J)%TGRP)
  CALL TEB_GRID_INIT(YSURF_LIST(J)%TG)
  CALL TEB_IRRIG_INIT(YSURF_LIST(J)%TIR)
  CALL TEB_OPTIONS_INIT(YSURF_LIST(J)%TOP)
  CALL TEB_PANEL_INIT(YSURF_LIST(J)%TPN)
  CALL TEB_VEG_OPTIONS_INIT(YSURF_LIST(J)%TVG)
  CALL TRIP_INIT(YSURF_LIST(J)%TP)
  CALL TRIP_GRID_INIT(YSURF_LIST(J)%TPG)
  CALL TRIP_DIAG_INIT(YSURF_LIST(J)%TPDG)
  CALL WATFLUX_GRID_INIT(YSURF_LIST(J)%WG)
  CALL WATFLUX_INIT(YSURF_LIST(J)%W)
  CALL WATFLUX_SBL_INIT(YSURF_LIST(J)%WSB)
  !
  CALL BEM_INIT(YSURF_LIST(J)%B,NTEB_PATCH_MAX)
  CALL DIAG_CUMUL_TEB_INIT(YSURF_LIST(J)%DGCT,NTEB_PATCH_MAX)
  CALL DIAG_MISC_TEB_INIT(YSURF_LIST(J)%DGMT,NTEB_PATCH_MAX)
  CALL TEB_GARDEN_INIT(YSURF_LIST(J)%TGD,NTEB_PATCH_MAX)
