  CALL DIAG_FLAKE_INIT(YSURF_LIST(J)%DGF)
  CALL DIAG_IDEAL_INIT(YSURF_LIST(J)%DGL)
  CALL DIAG_ISBA_INIT(YSURF_LIST(J)%DGI)
  CALL DIAG_MISC_FLAKE_INIT(YSURF_LIST(J)%DGMF)
  CALL DIAG_MISC_ISBA_INIT(YSURF_LIST(J)%DGMI)
  CALL DIAG_MISC_TEB_OPTIONS_INIT(YSURF_LIST(J)%DGMTO)
  CALL DIAG_OCEAN_INIT(YSURF_LIST(J)%DGO)
  CALL DIAG_SEAFLUX_INIT(YSURF_LIST(J)%DGS)
  CALL DIAG_SEAICE_INIT(YSURF_LIST(J)%DGSI)
  CALL DIAG_SURF_ATM_INIT(YSURF_LIST(J)%DGU)
  CALL DIAG_TEB_GARDEN_INIT(YSURF_LIST(J)%DGTGD)
  CALL DIAG_TEB_GREENROOF_INIT(YSURF_LIST(J)%DGTGR)
  CALL DIAG_TEB_INIT(YSURF_LIST(J)%DGT)
