  CALL DATA_COVER_INIT(YSURF_LIST(J)%DTCO)
  CALL DATA_ISBA_INIT(YSURF_LIST(J)%DTI)
  CALL DATA_SEAFLUX_INIT(YSURF_LIST(J)%DTS)
  CALL DATA_TEB_GARDEN_INIT(YSURF_LIST(J)%DTGD)
  CALL DATA_TEB_GREENROOF_INIT(YSURF_LIST(J)%DTGR)
  CALL DATA_TEB_INIT(YSURF_LIST(J)%DTT)
  CALL DATA_TSZ0_INIT(YSURF_LIST(J)%DTZ)
