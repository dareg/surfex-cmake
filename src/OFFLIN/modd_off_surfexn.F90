  CALL OCEAN_REL_INIT(YSURF_LIST(J)%OR)
  CALL PACK_CH_ISBA_INIT(YSURF_LIST(J)%PKCI)
  CALL PACK_DIAG_ISBA_INIT(YSURF_LIST(J)%PKDI)
  CALL PACK_ISBA_INIT(YSURF_LIST(J)%PKI)
  CALL SEAFLUX_GRID_INIT(YSURF_LIST(J)%SG)
  CALL SEAFLUX_INIT(YSURF_LIST(J)%S)
  CALL SEAFLUX_SBL_INIT(YSURF_LIST(J)%SSB)
  CALL SLT_INIT(YSURF_LIST(J)%SLT)
  CALL SSO_CANOPY_INIT(YSURF_LIST(J)%SSCP)
