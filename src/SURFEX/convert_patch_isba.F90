!     #########
      SUBROUTINE CONVERT_PATCH_ISBA (DTCO, DTI, IO, KDEC, KDEC2, PCOVER, OCOVER,&
                                     OAGRIP, HSFTYPE, OALB, IMX, IMT, IMM, IMI, IMA, IP, &
                                     PSOILGRID, PWG1, PWSAT, PPERM )
!     ##############################################################
!
!!**** *CONVERT_PATCH_ISBA* 
!!
!!    PURPOSE
!!    -------
!!
!!    METHOD
!!    ------
!!   
!
!!    EXTERNAL
!!    --------
!!
!!    IMPLICIT ARGUMENTS
!!    ------------------
!!
!!    REFERENCE
!!    ---------
!!
!!    AUTHOR
!!    ------
!!
!!    S. Faroux        Meteo-France
!!
!!    MODIFICATION
!!    ------------
!!
!!    Original    16/11/10
!!      V. Masson    04/14 Garden and Greenroofs can only be initialized by ecoclimap 
!!                         in this routine (not from user specified parameters from
!!                         the nature tile, as the number of points is not the same)
!!    B. Decharme  04/2013  Add CDGAVG (method to average depth)
!!                          Soil depth = Root depth with ISBA-DF
!!                           except for bare soil pft (but limited to 1m)
!!                          With TR_ML (new radiative transfert) and modis
!!                           albedo, UV albedo not defined (conserv nrj when
!!                           coupled to atmosphere)
!!    P Samuelsson  10/2014  MEB
!!
!----------------------------------------------------------------------------
!
!*    0.     DECLARATION
!            -----------
!
!
USE MODD_DATA_COVER_n, ONLY : DATA_COVER_t
USE MODD_DATA_ISBA_n, ONLY : DATA_ISBA_t
USE MODD_ISBA_OPTIONS_n, ONLY : ISBA_OPTIONS_t
USE MODD_ISBA_INIT_n, ONLY : ISBA_INIT_PGD_t
!
USE MODD_ISBA_PARAM_n, ONLY : ISBA_PARAM_FIX_t, ISBA_PARAM_TIME_t, ISBA_PARAM_MEB_t, &
                              ISBA_PARAM_ALB_t, ISBA_PARAM_IRRIG_t
!
USE MODD_DATA_COVER_PAR, ONLY : NVEGTYPE, NVT_NO, NVT_ROCK, NVT_SNOW
!
USE MODD_TYPE_DATE_SURF
!
!
USE MODD_DATA_COVER,     ONLY : XDATA_LAI, XDATA_H_TREE,                &
                                XDATA_VEG, XDATA_Z0, XDATA_Z0_O_Z0H,    &
                                XDATA_EMIS_ECO, XDATA_GAMMA, XDATA_CV,  &
                                XDATA_RGL, XDATA_RSMIN,                 &
                                XDATA_ALBNIR_VEG, XDATA_ALBVIS_VEG,     &
                                XDATA_ALBUV_VEG,                        &
                                XDATA_ALB_VEG_NIR, XDATA_ALB_VEG_VIS,   &
                                XDATA_ALB_SOIL_NIR, XDATA_ALB_SOIL_VIS, &
                                XDATA_GMES, XDATA_BSLAI, XDATA_LAIMIN,  &
                                XDATA_SEFOLD, XDATA_GC, XDATA_WRMAX_CF, &
                                XDATA_STRESS,                           &
                                XDATA_DMAX, XDATA_F2I, XDATA_RE25,      &
                                XDATA_CE_NITRO, XDATA_CF_NITRO,         &
                                XDATA_CNA_NITRO, XDATA_DICE,            &
                                XDATA_GMES_ST, XDATA_BSLAI_ST,          &
                                XDATA_SEFOLD_ST, XDATA_GC_ST,           &
                                XDATA_DMAX_ST, XDATA_WATSUP,            &
                                XDATA_GNDLITTER,                        &
                                XDATA_RGLGV, XDATA_GAMMAGV,             &
                                XDATA_RSMINGV, XDATA_ROOT_DEPTHGV,      &
                                XDATA_WRMAX_CFGV, XDATA_LAIGV,          &
                                XDATA_Z0LITTER, XDATA_H_VEG,            &
                                XDATA_ROOT_EXTINCTIONGV,                &
                                TDATA_SEED, TDATA_REAP,XDATA_IRRIG,     &
                                XDATA_ROOT_DEPTH, XDATA_GROUND_DEPTH,   &
                                XDATA_ROOT_EXTINCTION, XDATA_ROOT_LIN
!   
!
USE MODD_TREEDRAG,       ONLY : LTREEDRAG
!
USE MODI_AV_PGD_PARAM
USE MODI_AV_PGD
USE MODI_SOIL_ALBEDO
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE
!
!*    0.1    Declaration of arguments
!            ------------------------
!
!
TYPE(DATA_COVER_t), INTENT(INOUT) :: DTCO
TYPE(DATA_ISBA_t), INTENT(INOUT) :: DTI
TYPE(ISBA_OPTIONS_t), INTENT(INOUT) :: IO
!
INTEGER,                INTENT(IN)    :: KDEC
INTEGER,                INTENT(IN)    :: KDEC2
REAL, DIMENSION(:,:),   INTENT(IN)    :: PCOVER
LOGICAL, DIMENSION(:),  INTENT(IN)    :: OCOVER
LOGICAL,                INTENT(IN)    :: OAGRIP
CHARACTER(LEN=*),       INTENT(IN)    :: HSFTYPE ! nature / garden
!
LOGICAL, INTENT(IN) :: OALB
!
TYPE(ISBA_PARAM_FIX_t), OPTIONAL, INTENT(INOUT) :: IMX
TYPE(ISBA_PARAM_TIME_t), OPTIONAL, INTENT(INOUT) :: IMT
TYPE(ISBA_PARAM_MEB_t), OPTIONAL, INTENT(INOUT) :: IMM
TYPE(ISBA_PARAM_ALB_t), OPTIONAL, INTENT(INOUT) :: IMA
TYPE(ISBA_PARAM_IRRIG_t), OPTIONAL, INTENT(INOUT) :: IMI
TYPE(ISBA_INIT_PGD_t), OPTIONAL, INTENT(INOUT) :: IP
!
REAL, DIMENSION(:,:),   OPTIONAL, INTENT(IN)   :: PWG1
REAL, DIMENSION(:,:),   OPTIONAL, INTENT(IN)   :: PWSAT
REAL, DIMENSION(:),   OPTIONAL, INTENT(IN)   :: PPERM
!
REAL, DIMENSION(:)  ,   OPTIONAL, INTENT(IN)    :: PSOILGRID
!
!*    0.2    Declaration of local variables
!            ------------------------------
!
 CHARACTER(LEN=3)  :: YTREE, YNAT, YLAI, YVEG, YBAR, YDIF
!
INTEGER               :: JLAYER    ! loop counter on layers
INTEGER               :: JVEGTYPE  ! loop counter on vegtypes
!
LOGICAL               :: GDATA     ! Flag where initialization can be done
!                                  ! either with ecoclimap of data fields specified
!                                  ! by user on the natural points (GDTA=T)
!                                  ! For fields in town, only ecoclimap option
!                                  ! is treated in this routine (GDATA=F)
INTEGER               :: JJ        ! loop counter
!
INTEGER               :: ISIZE_LMEB_PATCH  ! Number of patches with MEB=true
!
REAL, ALLOCATABLE, DIMENSION(:) :: ZH_VEG
!
!
!*    0.3    Declaration of namelists
!            ------------------------
!
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!-------------------------------------------------------------------------------
!
!*    1.      Initializations
!             ---------------
!
IF (LHOOK) CALL DR_HOOK('CONVERT_PATCH_ISBA',0,ZHOOK_HANDLE)
!
IF (ASSOCIATED(DTCO%XDATA_WEIGHT)) DEALLOCATE(DTCO%XDATA_WEIGHT)
!
IF (HSFTYPE=='NAT') THEN
  YNAT='NAT'
  YTREE='TRE'
  YLAI='LAI'
  YVEG='VEG'
  YBAR='BAR'
  YDIF='DVG'
  GDATA=.TRUE.
  ISIZE_LMEB_PATCH = COUNT(IO%LMEB_PATCH(:))
ELSEIF (HSFTYPE=='GRD') THEN
  YNAT='GRD'
  YTREE='GRT'
  YLAI='GRL'
  YVEG='GRV'
  YBAR='GRB'
  YDIF='GDV'
  GDATA=.FALSE.
  ISIZE_LMEB_PATCH = 0
ENDIF
!
! vegtypes fraction
! -----------------
!
IF (PRESENT(IMX)) THEN
  !
  IF (GDATA .AND. DTI%LDATA_VEGTYPE) THEN
    IMX%XVEGTYPE=DTI%XPAR_VEGTYPE
  ELSE
    !classical ecoclimap case
    DO JVEGTYPE=1,NVEGTYPE
      CALL AV_PGD(DTCO, IMX%XVEGTYPE(:,JVEGTYPE),PCOVER ,DTCO%XDATA_VEGTYPE(:,JVEGTYPE),YNAT,'ARI',OCOVER)
    END DO
  ENDIF
  !
  !* soil layers and root fraction
!  -----------------------------
  !
  !   compute soil layers (and root fraction if DIF)
  !
  CALL SET_GRID_PARAM(SIZE(IMX%XDG,1),SIZE(IMX%XDG,2),SIZE(IMX%XDG,3))
!
!        D ICE
!        -----
!
  IF (IO%CISBA/='DIF') THEN
    IF (GDATA .AND. DTI%LDATA_DICE) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                        IMX%XD_ICE,DTI%XPAR_VEGTYPE,DTI%XPAR_DICE,YNAT,'ARI')
    ELSE
      CALL AV_PGD(DTCO, IMX%XD_ICE,PCOVER,XDATA_DICE(:,:),YNAT,'ARI',OCOVER,KDECADE=KDEC)
    ENDIF
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_Z0_O_Z0H) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XZ0_O_Z0H,DTI%XPAR_VEGTYPE,DTI%XPAR_Z0_O_Z0H,YNAT,'ARI')
  ELSE
    CALL AV_PGD(DTCO, IMX%XZ0_O_Z0H,PCOVER,XDATA_Z0_O_Z0H,YNAT,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
!
  IF (IO%CPHOTO/='NON'.OR.LTREEDRAG) THEN
    IF (GDATA .AND. DTI%LDATA_H_TREE) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XH_TREE,DTI%XPAR_VEGTYPE,DTI%XPAR_H_TREE,YTREE,'ARI')
    ELSE
      CALL AV_PGD(DTCO, IMX%XH_TREE,PCOVER,XDATA_H_TREE(:,:),YTREE,'ARI',OCOVER,KDECADE=KDEC)
    ENDIF
  ENDIF
!
  IF (IO%CPHOTO/='NON') THEN
    !
    IF (SIZE(IMX%XRE25)>0) THEN
      IF (GDATA .AND. DTI%LDATA_RE25) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XRE25,DTI%XPAR_VEGTYPE,DTI%XPAR_RE25,YNAT,'ARI')      
      ELSE
        CALL AV_PGD(DTCO, IMX%XRE25,PCOVER,XDATA_RE25,YNAT,'ARI',OCOVER,KDECADE=KDEC)  
      ENDIF
    ENDIF
    !
    IF (SIZE(IMX%XDMAX)>0) THEN
      IF (GDATA .AND. DTI%LDATA_DMAX) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XDMAX,DTI%XPAR_VEGTYPE,DTI%XPAR_DMAX,YTREE,'ARI')
      ELSEIF (IO%CPHOTO == 'AST' .OR. IO%CPHOTO == 'LST' .OR. IO%CPHOTO == 'NIT' .OR. IO%CPHOTO == 'NCB') THEN
        CALL AV_PGD(DTCO, IMX%XDMAX,PCOVER,XDATA_DMAX_ST,YTREE,'ARI',OCOVER,KDECADE=KDEC)  
      ELSE
        CALL AV_PGD(DTCO, IMX%XDMAX,PCOVER,XDATA_DMAX,YTREE,'ARI',OCOVER,KDECADE=KDEC)
      ENDIF
    ENDIF
    !
  ENDIF
!
ENDIF
!
IF (PRESENT(IMT)) THEN
!
 IF (.NOT.OALB) THEN
!   VEG
!   ----
  IF (GDATA .AND. DTI%LDATA_VEG) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, IMT%XVEG,DTI%XPAR_VEGTYPE,DTI%XPAR_VEG(:,KDEC2,:),YNAT,'ARI')
  ELSE
    CALL AV_PGD(DTCO, IMT%XVEG,PCOVER,XDATA_VEG(:,KDEC,:),YNAT,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
!
!   LAI
!   ----
  IF (GDATA .AND. DTI%LDATA_LAI) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XLAI,DTI%XPAR_VEGTYPE,DTI%XPAR_LAI(:,KDEC2,:),YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMT%XLAI,PCOVER,XDATA_LAI(:,KDEC,:),YVEG,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
!
!           EMIS
!           ----
!emis needs VEG by vegtypes is changed at this step
  IF (GDATA .AND. DTI%LDATA_EMIS) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XEMIS ,DTI%XPAR_VEGTYPE,DTI%XPAR_EMIS(:,KDEC2,:),YNAT,'ARI')
  ELSE
    CALL AV_PGD(DTCO, IMT%XEMIS ,PCOVER ,XDATA_EMIS_ECO (:,KDEC,:),YNAT,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
!
!    Z0V
!    ----
  IF (GDATA .AND. DTI%LDATA_Z0) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XZ0,DTI%XPAR_VEGTYPE,DTI%XPAR_Z0(:,KDEC2,:),YNAT,'CDN')
  ELSE
    CALL AV_PGD(DTCO, IMT%XZ0 ,PCOVER ,XDATA_Z0 (:,KDEC,:),YNAT,'CDN',OCOVER,KDECADE=KDEC)
  ENDIF
!
 ENDIF

  IF (GDATA .AND. DTI%LDATA_ALBNIR_VEG) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XALBNIR_VEG,DTI%XPAR_VEGTYPE,DTI%XPAR_ALBNIR_VEG,YVEG,'ARI',KDECADE=KDEC2)
  ELSEIF (IO%CALBEDO=='CM13') THEN
    CALL AV_PGD(DTCO, IMT%XALBNIR_VEG,PCOVER,XDATA_ALB_VEG_NIR(:,KDEC,:),YVEG,'ARI', OCOVER,KDECADE=KDEC)    
  ELSE
    CALL AV_PGD(DTCO, IMT%XALBNIR_VEG,PCOVER,XDATA_ALBNIR_VEG,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_ALBVIS_VEG) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XALBVIS_VEG,DTI%XPAR_VEGTYPE,DTI%XPAR_ALBVIS_VEG,YVEG,'ARI',KDECADE=KDEC2)
  ELSEIF (IO%CALBEDO=='CM13') THEN
    CALL AV_PGD(DTCO, IMT%XALBVIS_VEG,PCOVER,XDATA_ALB_VEG_VIS(:,KDEC,:),YVEG,'ARI',OCOVER,KDECADE=KDEC)      
  ELSE
    CALL AV_PGD(DTCO, IMT%XALBVIS_VEG,PCOVER,XDATA_ALBVIS_VEG,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF ((IO%CALBEDO=='CM13'.OR.IO%LTR_ML)) THEN
    IMT%XALBUV_VEG(:,:)=IMT%XALBVIS_VEG(:,:)
  ELSEIF (GDATA .AND. DTI%LDATA_ALBUV_VEG) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XALBUV_VEG,DTI%XPAR_VEGTYPE,DTI%XPAR_ALBUV_VEG,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMT%XALBUV_VEG,PCOVER,XDATA_ALBUV_VEG,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
 IF (.NOT.OALB) THEN
!        Other parameters
!        ----------------
  IF( SIZE(IMT%XRSMIN)>0) THEN
    IF (GDATA .AND. DTI%LDATA_RSMIN) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XRSMIN,DTI%XPAR_VEGTYPE,DTI%XPAR_RSMIN,YLAI,'INV',KDECADE=KDEC2)
    ELSE
      CALL AV_PGD(DTCO, IMT%XRSMIN,PCOVER,XDATA_RSMIN,YLAI,'INV',OCOVER,KDECADE=KDEC)  
    ENDIF
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_GAMMA) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XGAMMA,DTI%XPAR_VEGTYPE,DTI%XPAR_GAMMA,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMT%XGAMMA,PCOVER,XDATA_GAMMA,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_WRMAX_CF) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XWRMAX_CF,DTI%XPAR_VEGTYPE,DTI%XPAR_WRMAX_CF,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMT%XWRMAX_CF,PCOVER,XDATA_WRMAX_CF,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_RGL) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XRGL,DTI%XPAR_VEGTYPE,DTI%XPAR_RGL,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMT%XRGL,PCOVER,XDATA_RGL,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_CV) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XCV,DTI%XPAR_VEGTYPE,DTI%XPAR_CV,YVEG,'INV',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMT%XCV,PCOVER,XDATA_CV,YVEG,'INV',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (ISIZE_LMEB_PATCH>0 .OR. IO%CPHOTO/='NON') THEN

    IF( SIZE(IMT%XBSLAI)>0) THEN
      IF (GDATA .AND. DTI%LDATA_BSLAI) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XBSLAI,DTI%XPAR_VEGTYPE,DTI%XPAR_BSLAI,YVEG,'ARI',KDECADE=KDEC2)
      ELSEIF (IO%CPHOTO == 'AST' .OR. IO%CPHOTO == 'LST' .OR. IO%CPHOTO == 'NIT' .OR. IO%CPHOTO == 'NCB') THEN
        CALL AV_PGD(DTCO, IMT%XBSLAI,PCOVER,XDATA_BSLAI_ST,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ELSE
        CALL AV_PGD(DTCO, IMT%XBSLAI,PCOVER,XDATA_BSLAI,YVEG,'ARI',OCOVER,KDECADE=KDEC)
      ENDIF
    ENDIF
  ENDIF
!
  IF (IO%CPHOTO/='NON') THEN
  !
    IF (SIZE(IMT%XLAIMIN)>0) THEN
      IF (GDATA .AND. DTI%LDATA_LAIMIN) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XLAIMIN,DTI%XPAR_VEGTYPE,DTI%XPAR_LAIMIN,YVEG,'ARI',KDECADE=KDEC2)
      ELSE
        CALL AV_PGD(DTCO, IMT%XLAIMIN,PCOVER,XDATA_LAIMIN,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ENDIF
    ENDIF    
  !
    IF (SIZE(IMT%XSEFOLD)>0) THEN
      IF (GDATA .AND. DTI%LDATA_SEFOLD) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XSEFOLD,DTI%XPAR_VEGTYPE,DTI%XPAR_SEFOLD,YVEG,'ARI',KDECADE=KDEC2)
      ELSEIF (IO%CPHOTO == 'AST' .OR. IO%CPHOTO == 'LST' .OR. IO%CPHOTO == 'NIT' .OR. IO%CPHOTO == 'NCB') THEN
        CALL AV_PGD(DTCO, IMT%XSEFOLD,PCOVER,XDATA_SEFOLD_ST,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ELSE
        CALL AV_PGD(DTCO, IMT%XSEFOLD,PCOVER,XDATA_SEFOLD,YVEG,'ARI',OCOVER,KDECADE=KDEC)
      ENDIF
    ENDIF
    !
    IF ( SIZE(IMT%XGMES)>0) THEN
      IF (GDATA .AND. DTI%LDATA_GMES) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XGMES,DTI%XPAR_VEGTYPE,DTI%XPAR_GMES,YVEG,'ARI',KDECADE=KDEC2)
      ELSEIF (IO%CPHOTO == 'AST' .OR. IO%CPHOTO == 'LST' .OR. IO%CPHOTO == 'NIT' .OR. IO%CPHOTO == 'NCB') THEN
        CALL AV_PGD(DTCO, IMT%XGMES,PCOVER,XDATA_GMES_ST,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ELSE
        CALL AV_PGD(DTCO, IMT%XGMES,PCOVER,XDATA_GMES,YVEG,'ARI',OCOVER,KDECADE=KDEC)
      ENDIF
    ENDIF
    !
    IF ( SIZE(IMT%XGC)>0) THEN
      IF (GDATA .AND. DTI%LDATA_GC) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                          IMT%XGC,DTI%XPAR_VEGTYPE,DTI%XPAR_GC,YVEG,'ARI',KDECADE=KDEC2)
      ELSEIF (IO%CPHOTO == 'AST' .OR. IO%CPHOTO == 'LST' .OR. IO%CPHOTO == 'NIT' .OR. IO%CPHOTO == 'NCB') THEN
        CALL AV_PGD(DTCO, IMT%XGC,PCOVER,XDATA_GC_ST,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ELSE
        CALL AV_PGD(DTCO, IMT%XGC,PCOVER,XDATA_GC,YVEG,'ARI',OCOVER,KDECADE=KDEC)
      ENDIF
    ENDIF
    !
    IF (IO%CPHOTO/='AGS' .AND. IO%CPHOTO/='LAI') THEN
    !
      IF (SIZE(IMT%XF2I)>0) THEN
        IF (GDATA .AND. DTI%LDATA_F2I) THEN
          CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XF2I,DTI%XPAR_VEGTYPE,DTI%XPAR_F2I,YVEG,'ARI',KDECADE=KDEC2)
        ELSE
          CALL AV_PGD(DTCO, IMT%XF2I,PCOVER,XDATA_F2I,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
        ENDIF
      ENDIF
      !
      IF (IO%CPHOTO=='NIT' .OR. IO%CPHOTO=='NCB') THEN
      !
        IF (SIZE(IMT%XCE_NITRO)>0) THEN
          IF (GDATA .AND. DTI%LDATA_CE_NITRO) THEN
            CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XCE_NITRO,DTI%XPAR_VEGTYPE,DTI%XPAR_CE_NITRO,YVEG,'ARI',KDECADE=KDEC2)
          ELSE
            CALL AV_PGD(DTCO, IMT%XCE_NITRO,PCOVER,XDATA_CE_NITRO,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
          ENDIF
        ENDIF
        !
        IF (SIZE(IMT%XCF_NITRO)>0) THEN
          IF (GDATA .AND. DTI%LDATA_CF_NITRO) THEN
            CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XCF_NITRO,DTI%XPAR_VEGTYPE,DTI%XPAR_CF_NITRO,YVEG,'ARI',KDECADE=KDEC2)
          ELSE
            CALL AV_PGD(DTCO, IMT%XCF_NITRO,PCOVER,XDATA_CF_NITRO,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
          ENDIF
        ENDIF
        !
        IF (SIZE(IMT%XCNA_NITRO)>0) THEN
          IF (GDATA .AND. DTI%LDATA_CNA_NITRO) THEN
            CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMT%XCNA_NITRO,DTI%XPAR_VEGTYPE,DTI%XPAR_CNA_NITRO,YVEG,'ARI',KDECADE=KDEC2)
          ELSE
            CALL AV_PGD(DTCO, IMT%XCNA_NITRO,PCOVER,XDATA_CNA_NITRO,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
          ENDIF
        ENDIF
        !
      ENDIF
      !
    ENDIF
    !
  ENDIF
!
!       STRESS
!       --------
  IF (SIZE(IMT%LSTRESS)>0) THEN
    CALL SET_STRESS(SIZE(IMT%LSTRESS,1),SIZE(IMT%LSTRESS,2))      
  ENDIF
!
 ENDIF
!
ENDIF
!
IF (PRESENT(IMM) .AND. .NOT.OALB) THEN
  !
!   GNDLITTER
!   ---------
  IF (GDATA .AND. DTI%LDATA_GNDLITTER) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, IMM%XGNDLITTER,DTI%XPAR_VEGTYPE,&
                        DTI%XPAR_GNDLITTER(:,KDEC2,:),YNAT,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMM%XGNDLITTER,PCOVER,XDATA_GNDLITTER(:,KDEC,:),YNAT,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
!
!   LAIGV
!   ----
  IF (GDATA .AND. DTI%LDATA_LAIGV) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XLAIGV,DTI%XPAR_VEGTYPE,DTI%XPAR_LAIGV(:,KDEC2,:),YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMM%XLAIGV,PCOVER,XDATA_LAIGV(:,KDEC,:),YVEG,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
!
!        H_VEG
!        -----
  IF (GDATA .AND. DTI%LDATA_H_VEG) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XH_VEG,DTI%XPAR_VEGTYPE,DTI%XPAR_H_VEG(:,KDEC2,:),YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMM%XH_VEG,PCOVER,XDATA_H_VEG(:,KDEC,:),YVEG,'ARI',OCOVER,KDECADE=KDEC)
  ENDIF
! In case of MEB, force 0<PH_VEG<XUNDEF for those patches where LMEB_PATCH=.T.
  IF (ISIZE_LMEB_PATCH>0)THEN
    ALLOCATE(ZH_VEG(SIZE(IMM%XH_VEG,1)))
    DO JJ=1,SIZE(IO%LMEB_PATCH)
      IF(IO%LMEB_PATCH(JJ))THEN
        ZH_VEG=IMM%XH_VEG(:,JJ)
        WHERE(ZH_VEG>1000.) ZH_VEG=0.
        ZH_VEG=MAX(ZH_VEG,1.0E-3)
        IMM%XH_VEG(:,JJ)=ZH_VEG
      ENDIF
    ENDDO
  ENDIF
!
!    Z0LITTER
!    --------
  IF (GDATA .AND. DTI%LDATA_Z0LITTER) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XZ0LITTER,DTI%XPAR_VEGTYPE,DTI%XPAR_Z0LITTER(:,KDEC2,:),YNAT,'CDN')
  ELSE
    CALL AV_PGD(DTCO, IMM%XZ0LITTER ,PCOVER ,XDATA_Z0LITTER (:,KDEC,:),YNAT,'CDN',OCOVER)
  ENDIF
!
  IF( SIZE(IMM%XRSMINGV)>0) THEN
    IF (GDATA .AND. DTI%LDATA_RSMINGV) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XRSMINGV,DTI%XPAR_VEGTYPE,DTI%XPAR_RSMINGV,YLAI,'INV',KDECADE=KDEC2)
    ELSE
      CALL AV_PGD(DTCO, IMM%XRSMINGV,PCOVER,XDATA_RSMINGV,YLAI,'INV',OCOVER,KDECADE=KDEC)  
    ENDIF
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_GAMMAGV) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XGAMMAGV,DTI%XPAR_VEGTYPE,DTI%XPAR_GAMMAGV,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMM%XGAMMAGV,PCOVER,XDATA_GAMMAGV,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_WRMAX_CFGV) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XWRMAX_CFGV,DTI%XPAR_VEGTYPE,DTI%XPAR_WRMAX_CFGV,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMM%XWRMAX_CFGV,PCOVER,XDATA_WRMAX_CFGV,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_RGLGV) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XRGLGV,DTI%XPAR_VEGTYPE,DTI%XPAR_RGLGV,YVEG,'ARI',KDECADE=KDEC2)
  ELSE
    CALL AV_PGD(DTCO, IMM%XRGLGV,PCOVER,XDATA_RGLGV,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
  ENDIF
!
ENDIF
!
IF (PRESENT(IMI) .AND. .NOT.OALB) THEN
!
  IF ((IO%CPHOTO == 'LAI' .OR. IO%CPHOTO == 'LST' .OR. IO%CPHOTO == 'NIT' .OR. IO%CPHOTO=='NCB') .AND. OAGRIP)  THEN
  !
  ! date of seeding
  ! ---------------
  !
     IF(SIZE(IMI%TSEED)>0) THEN
      CALL AV_PGD (IMI%TSEED ,PCOVER,TDATA_SEED(:,:),YVEG,'MAJ',OCOVER,KDECADE=KDEC)  
     ENDIF
  !
  ! date of reaping
  ! ---------------
  !
    IF (SIZE(IMI%TREAP)>0) THEN
      CALL AV_PGD (IMI%TREAP ,PCOVER,TDATA_REAP(:,:),YVEG,'MAJ',OCOVER,KDECADE=KDEC)  
    ENDIF
  !
    IF (SIZE(IMI%XIRRIG)>0) THEN
      IF (GDATA .AND. DTI%LDATA_IRRIG) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMI%XIRRIG,DTI%XPAR_VEGTYPE,DTI%XPAR_IRRIG(:,KDEC2,:),YVEG,'ARI',KDECADE=KDEC2)
      ELSE
        CALL AV_PGD(DTCO, IMI%XIRRIG,PCOVER,XDATA_IRRIG,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ENDIF
    ENDIF
!
    IF (SIZE(IMI%XWATSUP)>0) THEN
      IF (GDATA .AND. DTI%LDATA_WATSUP) THEN
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMI%XWATSUP,DTI%XPAR_VEGTYPE,DTI%XPAR_WATSUP(:,KDEC2,:),YVEG,'ARI',KDECADE=KDEC2)
      ELSE
        CALL AV_PGD(DTCO, IMI%XWATSUP,PCOVER,XDATA_WATSUP,YVEG,'ARI',OCOVER,KDECADE=KDEC)  
      ENDIF
    ENDIF
    !
  ENDIF
!
ENDIF
!
IF (PRESENT(IMA)) THEN
!
  IF (GDATA .AND. DTI%LDATA_ALBNIR_SOIL) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMA%XALBNIR_SOIL,DTI%XPAR_VEGTYPE,DTI%XPAR_ALBNIR_SOIL,YBAR,'ARI',KDECADE=KDEC2)
  ELSEIF (IO%CALBEDO=='CM13') THEN
    CALL AV_PGD(DTCO, IMA%XALBNIR_SOIL,PCOVER,XDATA_ALB_SOIL_NIR(:,KDEC,:),YBAR,'ARI',OCOVER,KDECADE=KDEC)
  ELSE
    CALL SOIL_ALBEDO (IO%CALBEDO, PWSAT(:,1), PWG1, IP, IMA, "NIR" )
  ENDIF
!
  IF (GDATA .AND. DTI%LDATA_ALBVIS_SOIL) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMA%XALBVIS_SOIL,DTI%XPAR_VEGTYPE,DTI%XPAR_ALBVIS_SOIL,YBAR,'ARI',KDECADE=KDEC2)
  ELSEIF (IO%CALBEDO=='CM13') THEN
    CALL AV_PGD(DTCO, IMA%XALBVIS_SOIL,PCOVER,XDATA_ALB_SOIL_VIS(:,KDEC,:),YBAR,'ARI',OCOVER,KDECADE=KDEC)    
  ELSE
   CALL SOIL_ALBEDO (IO%CALBEDO, PWSAT(:,1), PWG1, IP, IMA, "VIS" )
  ENDIF
!

  IF (IO%CALBEDO=='CM13'.OR.IO%LTR_ML) THEN
    IMA%XALBUV_SOIL(:,:)=IMA%XALBVIS_SOIL(:,:)
  ELSEIF (GDATA .AND. DTI%LDATA_ALBUV_SOIL) THEN
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMA%XALBUV_SOIL,DTI%XPAR_VEGTYPE,DTI%XPAR_ALBUV_SOIL,YNAT,'ARI',KDECADE=KDEC2)
  ELSE
    CALL SOIL_ALBEDO (IO%CALBEDO, PWSAT(:,1), PWG1, IP, IMA, "UV"  )
  ENDIF
!
ENDIF
!
IF (ASSOCIATED(DTCO%XDATA_WEIGHT)) DEALLOCATE(DTCO%XDATA_WEIGHT)
!
IF (LHOOK) CALL DR_HOOK('CONVERT_PATCH_ISBA',1,ZHOOK_HANDLE)
!
!-------------------------------------------------------------------------------
CONTAINS
!-------------------------------------------------------------------------------
!
SUBROUTINE SET_STRESS(KSIZE1,KSIZE2)
!
IMPLICIT NONE
!
INTEGER, INTENT(IN) :: KSIZE1
INTEGER, INTENT(IN) :: KSIZE2
!
REAL, DIMENSION(KSIZE1,KSIZE2)   :: ZWORK
REAL, DIMENSION(KSIZE1,NVEGTYPE) :: ZSTRESS
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('CONVERT_PATCH_ISBA:SET_STRESS',0,ZHOOK_HANDLE)
!
IF (GDATA .AND. DTI%LDATA_STRESS) THEN
  ZSTRESS(:,:)=0.
  DO JVEGTYPE=1,NVEGTYPE
    WHERE (DTI%LPAR_STRESS(:,JVEGTYPE)) ZSTRESS(:,JVEGTYPE)=1.
  ENDDO
  CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      ZWORK,DTI%XPAR_VEGTYPE,ZSTRESS,YVEG,'ARI',KDECADE=KDEC2)
ELSE
  CALL AV_PGD(DTCO, ZWORK,PCOVER,XDATA_STRESS(:,:),YVEG,'ARI',OCOVER,KDECADE=KDEC)
ENDIF
!
WHERE (ZWORK(:,:)<0.5)
  IMT%LSTRESS(:,:) = .FALSE.
ELSEWHERE
  IMT%LSTRESS(:,:) = .TRUE.
END WHERE
!
IF (LHOOK) CALL DR_HOOK('CONVERT_PATCH_ISBA:SET_STRESS',1,ZHOOK_HANDLE)
END SUBROUTINE SET_STRESS
!
!-------------------------------------------------------------------------------
SUBROUTINE SET_GRID_PARAM(KNI,KGROUND,KPATCH )
!
USE MODD_SURF_PAR, ONLY : XUNDEF, NUNDEF
USE MODD_ISBA_PAR, ONLY : XPERMFRAC
!
USE MODD_REPROD_OPER, ONLY : CDGAVG, CDGDIF
!
USE MODI_INI_DATA_ROOTFRAC
USE MODI_INI_DATA_SOIL
USE MODI_PERMAFROST_DEPTH
USE MODI_ABOR1_SFX
!
IMPLICIT NONE
!
REAL, PARAMETER     :: ZPREC=1.0E+6
!
INTEGER, INTENT(IN) :: KNI
INTEGER, INTENT(IN) :: KGROUND
INTEGER, INTENT(IN) :: KPATCH
!
REAL,    DIMENSION (SIZE(XDATA_GROUND_DEPTH,1),NVEGTYPE) :: ZDATA_GROUND_DEPTH
!
REAL,    DIMENSION (KNI,KPATCH)         :: ZDTOT, ZDG2, ZROOT_EXT, ZROOT_LIN
!
INTEGER :: JJ, JL, JPATCH
!
! flags taking general surface type flag into account
LOGICAL :: GDATA_DG, GDATA_GROUND_DEPTH, GDATA_ROOT_DEPTH, GDATA_ROOTFRAC, &
           GDATA_ROOTFRACGV, GNOECO, GMEB
!-------------------------------------------------------------------------!
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('CONVERT_PATCH_ISBA:SET_GRID_PARAM',0,ZHOOK_HANDLE)
!
IF(IO%CISBA=='DIF')THEN
  IF(.NOT.PRESENT(IMX)) CALL ABOR1_SFX('CONVERT_PATCH_ISBA: SET_GRID_PARAM: KWG_LAYER, PDROOT and PGD2 must be present with DIF')
 
ENDIF
!
GMEB = (PRESENT(IMM) .AND. (ISIZE_LMEB_PATCH>0))
!
ZDTOT    (:,:) = XUNDEF
ZDG2     (:,:) = XUNDEF
!
IMX%NWG_LAYER(:,:) = NUNDEF
IMX%XROOTFRAC(:,:,:) = XUNDEF
!
ZDATA_GROUND_DEPTH(:,:) = XDATA_GROUND_DEPTH(:,:)
!
GDATA_DG           = GDATA .AND. DTI%LDATA_DG
GDATA_GROUND_DEPTH = GDATA .AND. DTI%LDATA_GROUND_DEPTH
GDATA_ROOT_DEPTH   = GDATA .AND. DTI%LDATA_ROOT_DEPTH
GDATA_ROOTFRAC     = GDATA .AND. DTI%LDATA_ROOTFRAC
GDATA_ROOTFRACGV   = GDATA .AND. DTI%LDATA_ROOTFRACGV
!
!####################################################################################
!
!CDGAVG : old for reprod = 'ARI' Arithmetic average for all depth 
!         recommended    = 'INV' Harmonic average for all depth (default)
!
!CDGDIF : old for reprod = 'SOIL' d3 soil depth from ecoclimap for isba-df
!         recommended    = 'ROOT' d2 soil depth from ecoclimap for isba-df (default)
!
!####################################################################################
!n
!DG IN NAMELIST => GROUND_DEPTH KNOWN, ROOT_DEPTH UNKNOWN 
IF (GDATA_DG) THEN
  !
  DO JLAYER=1,KGROUND
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XDG(:,JLAYER,:),DTI%XPAR_VEGTYPE,DTI%XPAR_DG(:,JLAYER,:),YNAT,CDGAVG)
  ENDDO
  !
ENDIF
!
IF(.NOT.GDATA_GROUND_DEPTH.AND.IO%CISBA=='DIF'.AND.CDGDIF=='ROOT')THEN
  !
  DO JVEGTYPE=1,NVEGTYPE
    IF(JVEGTYPE==NVT_NO)THEN
      WHERE(XDATA_GROUND_DEPTH(:,JVEGTYPE)/=XUNDEF)
        ZDATA_GROUND_DEPTH(:,JVEGTYPE) = MIN(1.0,XDATA_GROUND_DEPTH(:,JVEGTYPE))
      ENDWHERE
    ELSEIF(JVEGTYPE/=NVT_ROCK.AND.JVEGTYPE/=NVT_SNOW)THEN
      ZDATA_GROUND_DEPTH(:,JVEGTYPE) = MAX(1.0,XDATA_ROOT_DEPTH(:,JVEGTYPE))
    ELSE
      ZDATA_GROUND_DEPTH(:,JVEGTYPE) = XDATA_ROOT_DEPTH(:,JVEGTYPE)
    ENDIF
  ENDDO
  !
ENDIF
!
!CALCULATION OF GROUND_DEPTH IN ZDTOT : ECOCLIMAP OR LDATA_GROUND_DEPTH
IF (IO%CISBA/='2-L') THEN 
  !
  IF (GDATA_GROUND_DEPTH .AND. (IO%CISBA=='DIF' .OR. .NOT.GDATA_DG)) THEN
    !GROUND DEPTH IN NAMELIST
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      ZDTOT(:,:),DTI%XPAR_VEGTYPE,DTI%XPAR_GROUND_DEPTH(:,:),YNAT,CDGAVG)
    !Error Due to machine precision
    WHERE(ZDTOT(:,:)/=XUNDEF) ZDTOT(:,:)=INT(ZDTOT(:,:)*ZPREC)/ZPREC
    !CONSISTENCY CHECK
    IF (GDATA_DG) ZDTOT(:,:) = MIN(ZDTOT(:,:),IMX%XDG(:,KGROUND,:))
  ELSEIF (GDATA_DG) THEN
    !GROUND DEPTH FROM NAMELIST DG
    ZDTOT(:,:) = IMX%XDG(:,KGROUND,:)
  ELSE
    !GROUND DEPTH FROM ECOCLIMAP
    CALL AV_PGD(DTCO, ZDTOT(:,:),PCOVER,ZDATA_GROUND_DEPTH(:,:),YNAT,CDGAVG,OCOVER,KDECADE=KDEC)
    IF(IO%CISBA=='DIF'.AND.CDGDIF=='ROOT')ZDG2(:,:)=ZDTOT(:,:)
  ENDIF
  !
ENDIF
!
!CALCULATION OF GROUND_DEPTH : Permafrost depth put to 12m
IF(IO%CISBA=='DIF'.AND.IO%LPERM) CALL PERMAFROST_DEPTH(KNI,KPATCH,PPERM,ZDTOT)
!
!IN BOTH CASES, ROOT_DEPTH IS NEEDED: PUT IN DG2
IF (IO%CISBA=='DIF' .OR. .NOT.GDATA_DG) THEN
  !
  GNOECO=(GDATA_ROOT_DEPTH .AND. .NOT.GDATA_ROOTFRAC)
  IF (GNOECO) THEN
    !ROOT_DEPTH IN NAMELIST
    CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      ZDG2(:,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOT_DEPTH(:,:),YNAT,CDGAVG)
    !Error Due to machine precision
    WHERE(ZDG2(:,:)/=XUNDEF) ZDG2(:,:)=INT(ZDG2(:,:)*ZPREC)/ZPREC  
    !CONSISTENCY CHECKS
    IF (DTI%LDATA_DG) ZDG2(:,:) = MIN(ZDG2(:,:),IMX%XDG(:,KGROUND,:))
    ZDTOT(:,:) = MAX(ZDG2(:,:),ZDTOT(:,:))
    IF (IO%CISBA=='DIF') THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XDROOT(:,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOT_DEPTH(:,:),YDIF,CDGAVG)
     !Error Due to machine precision
      WHERE(IMX%XDROOT(:,:)/=XUNDEF)
          IMX%XDROOT(:,:)=INT(IMX%XDROOT(:,:)*ZPREC)/ZPREC
      ENDWHERE 
       IF(CDGDIF=='ROOT')THEN
         WHERE(IMX%XDROOT(:,:).NE.XUNDEF) ZDTOT(:,:) = MAX(IMX%XDROOT(:,:),ZDTOT(:,:))
         WHERE(IMX%XDROOT(:,:).NE.XUNDEF) ZDG2 (:,:) = MAX(IMX%XDROOT(:,:),ZDG2 (:,:))
       ELSE
         CALL AV_PGD(DTCO, ZDG2(:,:),PCOVER,XDATA_ROOT_DEPTH(:,:),YNAT,CDGAVG,OCOVER,KDECADE=KDEC)
       ENDIF      
     !CONSISTENCY CHECKS
      IF (GDATA_DG) WHERE (IMX%XDROOT(:,:).NE.XUNDEF) IMX%XDROOT(:,:) = MIN(IMX%XDROOT(:,:),IMX%XDG(:,KGROUND,:))   
    ENDIF
  ELSE 
    !ROOT_DEPTH FROM ECOCLIMAP
    IF (IO%CISBA=='DIF')THEN
       CALL AV_PGD(DTCO, IMX%XDROOT(:,:),PCOVER,XDATA_ROOT_DEPTH(:,:),YDIF,CDGAVG,OCOVER,KDECADE=KDEC)
       IF(CDGDIF=='ROOT')THEN
         WHERE(IMX%XDROOT(:,:).NE.XUNDEF) ZDTOT(:,:) = MAX(IMX%XDROOT(:,:),ZDTOT(:,:))
         WHERE(IMX%XDROOT(:,:).NE.XUNDEF) ZDG2 (:,:) = MAX(IMX%XDROOT(:,:),ZDG2 (:,:))
       ELSE
         CALL AV_PGD(DTCO, ZDG2(:,:),PCOVER,XDATA_ROOT_DEPTH(:,:),YNAT,CDGAVG,OCOVER,KDECADE=KDEC)
       ENDIF
    ELSE
       CALL AV_PGD(DTCO, ZDG2(:,:),PCOVER,XDATA_ROOT_DEPTH(:,:),YNAT,CDGAVG,OCOVER,KDECADE=KDEC)
    ENDIF
    IF ( GDATA_GROUND_DEPTH .OR. GDATA_DG ) THEN
      ZDG2  (:,:) = MIN(ZDG2  (:,:),ZDTOT(:,:))
      IF (IO%CISBA=='DIF') WHERE (IMX%XDROOT(:,:).NE.XUNDEF) IMX%XDROOT(:,:) = MIN(IMX%XDROOT(:,:),ZDTOT(:,:))
    ENDIF
  ENDIF
  !
  !CALCULATION OF DG IF NOT IN NAMELIST
  IF (.NOT.GDATA_DG) THEN
    !
    IF (IO%CISBA=='DIF') THEN
      IF( MAXVAL(ZDTOT,ZDTOT/=XUNDEF)>PSOILGRID(KGROUND) ) THEN
        CALL ABOR1_SFX('CONVERT_PATCH_ISBA: not enough soil layer with optimized grid')
      ENDIF
    ENDIF
    !
    WHERE(ZDG2(:,:)==XUNDEF.AND.ZDTOT(:,:)/=XUNDEF) ZDG2(:,:)=0.0 !No vegetation
    !
    !IF CISBA=DIF CALCULATES ALSO KWG_LAYER WITH USE OF SOILGRID $
    CALL INI_DATA_SOIL(IO%CISBA, IMX%XDG,PROOTDEPTH=ZDG2, PSOILDEPTH=ZDTOT,&
                       PSOILGRID=PSOILGRID, KWG_LAYER=IMX%NWG_LAYER )
    IF (.NOT.GNOECO.AND.IO%CISBA=='DIF'.AND.CDGDIF=='ROOT')THEN
       DO JPATCH=1,KPATCH
          DO JJ=1,KNI
             IF(IO%LPERM.AND.IMX%NWG_LAYER(JJ,JPATCH)/=NUNDEF)THEN
               IF(PPERM(JJ)<XPERMFRAC) ZDG2(JJ,JPATCH)=IMX%XDG(JJ,IMX%NWG_LAYER(JJ,JPATCH),JPATCH)
             ELSEIF(IMX%NWG_LAYER(JJ,JPATCH)/=NUNDEF)THEN
               ZDG2(JJ,JPATCH)=IMX%XDG(JJ,IMX%NWG_LAYER(JJ,JPATCH),JPATCH)
             ELSE
               ZDG2(JJ,JPATCH)=XUNDEF
             ENDIF
          ENDDO
       ENDDO
    ENDIF
               
    !
  ELSEIF ( IO%CISBA=='DIF') THEN
    !
    !CALCULATION OF KWG_LAYER IF DG IN NAMELIST
    IF(GDATA_GROUND_DEPTH)THEN
      DO JPATCH=1,KPATCH
        DO JJ=1,KNI
          DO JL=1,KGROUND
            IF( IMX%XDG(JJ,JL,JPATCH) <= ZDTOT(JJ,JPATCH) .AND. ZDTOT(JJ,JPATCH) < XUNDEF ) &
                IMX%NWG_LAYER(JJ,JPATCH) = JL
          ENDDO
        ENDDO
      ENDDO                
    ELSE
      IMX%NWG_LAYER(:,:) = KGROUND
    ENDIF
    !
  ENDIF
  !
  ! DROOT AND DG2 LIMITED BY KWG_LAYER
  IF (IO%CISBA=='DIF' .AND. .NOT.DTI%LDATA_ROOTFRAC) THEN
    !
    DO JPATCH=1,KPATCH
      DO JJ=1,KNI
        IF(IMX%NWG_LAYER(JJ,JPATCH)/=NUNDEF) THEN
          JL = IMX%NWG_LAYER(JJ,JPATCH)
          ZDG2  (JJ,JPATCH)=MIN(ZDG2  (JJ,JPATCH),IMX%XDG(JJ,JL,JPATCH))
          IF (IMX%XDROOT(JJ,JPATCH)/=XUNDEF) IMX%XDROOT(JJ,JPATCH)=MIN(IMX%XDROOT(JJ,JPATCH),IMX%XDG(JJ,JL,JPATCH))    
        ENDIF
      ENDDO
    ENDDO
    !
  ENDIF
  !
ENDIF
!
!CALCULATION OF ROOTFRAC
IF (IO%CISBA=='DIF') THEN
  !
  IF (GDATA_ROOTFRAC .OR. GDATA_ROOTFRACGV) THEN
    !
    !ROOTFRACGV IN NAMELIST
    IF(GMEB)THEN
      DO JL=1,KGROUND
        CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMM%XROOTFRACGV(:,JL,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOTFRACGV(:,JL,:),YNAT,'ARI')
      ENDDO
    ENDIF
    !
    !ROOTFRAC IN NAMELIST
    DO JL=1,KGROUND
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      IMX%XROOTFRAC(:,JL,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOTFRAC(:,JL,:),YNAT,'ARI',KDECADE=KDEC)
    ENDDO
    !    
    ZDG2  (:,:)=0.0
    IMX%XDROOT(:,:)=0.0    
    DO JPATCH=1,KPATCH
      DO JJ=1,KNI
        !
        !DROOT DEPENDS ON ROOTFRAC
        DO JL=KGROUND,1,-1
          IF( IMX%XROOTFRAC(JJ,JL,JPATCH)>=1.0 )THEN
            ZDG2  (JJ,JPATCH) = IMX%XDG(JJ,JL,JPATCH)
            IMX%XDROOT(JJ,JPATCH) = IMX%XDG(JJ,JL,JPATCH)
          ELSEIF (JL<KGROUND.AND.IMX%XROOTFRAC(JJ,JL,JPATCH)>0.0) THEN
            IF (IMX%NWG_LAYER(JJ,JPATCH)<=JL) IMX%NWG_LAYER(JJ,JPATCH) = JL+1
            EXIT
          ENDIF
        ENDDO
        !
        IF(IMX%XDROOT(JJ,JPATCH)==0.0.AND.ZDG2(JJ,JPATCH)==0.0)THEN
          JL=IMX%NWG_LAYER(JJ,JPATCH)
          ZDG2(JJ,JPATCH)=MIN(0.6,IMX%XDG(JJ,JL,JPATCH))
        ENDIF
        !
      ENDDO
    ENDDO
    !
  ELSE
    !
    !DEPENDS ON DROOT
    IF (GDATA .AND. DTI%LDATA_ROOT_LIN) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                      ZROOT_LIN(:,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOT_LIN(:,:),YDIF,'ARI')
    ELSE
      CALL AV_PGD(DTCO, ZROOT_LIN(:,:),PCOVER,XDATA_ROOT_LIN(:,:),YDIF,'ARI',OCOVER,KDECADE=KDEC)
    ENDIF
    !
    IF (GDATA .AND. DTI%LDATA_ROOT_EXTINCTION) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                    ZROOT_EXT(:,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOT_EXTINCTION(:,:),YDIF,'ARI')
    ELSE
      CALL AV_PGD(DTCO, ZROOT_EXT(:,:),PCOVER,XDATA_ROOT_EXTINCTION(:,:),YDIF,'ARI',OCOVER,KDECADE=KDEC)
    ENDIF
    !
    CALL INI_DATA_ROOTFRAC(IMX%XDG,IMX%XDROOT,ZROOT_EXT,ZROOT_LIN,IMX%XROOTFRAC)
  ENDIF
  IF(GMEB)THEN
    IF (GDATA .AND. DTI%LDATA_ROOT_EXTINCTIONGV) THEN
      CALL AV_PGD_PARAM(DTI%XPAR_LAI, DTI%XPAR_VEG, &
                    ZROOT_EXT(:,:),DTI%XPAR_VEGTYPE,DTI%XPAR_ROOT_EXTINCTIONGV(:,:),YDIF,'ARI')
    ELSE
      CALL AV_PGD(DTCO, ZROOT_EXT(:,:),PCOVER,XDATA_ROOT_EXTINCTIONGV(:,:),YDIF,'ARI',OCOVER,KDECADE=KDEC)
    ENDIF
    !
    CALL INI_DATA_ROOTFRAC(IMX%XDG,IMX%XDROOT,ZROOT_EXT,ZROOT_LIN,  &
                           IMM%XROOTFRACGV,OGV=GMEB)
    !
  ENDIF
  !
  IMX%XDG2(:,:) = ZDG2(:,:)
  !
ENDIF
!
IF (LHOOK) CALL DR_HOOK('CONVERT_PATCH_ISBA:SET_GRID_PARAM',1,ZHOOK_HANDLE)
!
END SUBROUTINE SET_GRID_PARAM
!
!-------------------------------------------------------------------------------
END SUBROUTINE CONVERT_PATCH_ISBA
