SUBROUTINE DIAG_EVAP_ISBA_n (OSURF_BUDGETC, DGEI, DGEIP, DGEIPC, DGIPC, DGEIPK, DGIPK, IRK, &
                             IO, HSNOW_SCHEME, PTSTEP, KMASK, KSIZE, KPATCH, PRHOA)
!     ###############################################################################
!
!!****  *DIAG_EVAP-ISBA_n * - additional diagnostics for ISBA
!!
!!    PURPOSE
!!    -------
!
!!**  METHOD
!!    ------
!!
!!    REFERENCE
!!    ---------
!!      
!!
!!    AUTHOR
!!    ------
!!     P. LeMoigne 
