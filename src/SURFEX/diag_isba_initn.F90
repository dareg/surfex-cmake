!     #########
      SUBROUTINE DIAG_ISBA_INIT_n (&
                                    CHI, DGEI, DGEIC, DGEIP, DGEIPC, &
                                    DGI, DGIC, DGIP, DGIPC, &
                                    DGMI, DGMIP, DGU, GB, IO, &
                                    HSNOW_SCHEME, KSNOW_LAYER, KABC, &
                                   HPROGRAM,KLU,KSW)
!     #####################
!
!!****  *DIAG_ISBA_INIT_n* - routine to initialize ISBA-AGS diagnostic variables
!!
!!    PURPOSE
!!    -------
!!
!!**  METHOD
!!    ------
!!
!!    EXTERNAL
!!    --------
!!
!!
!!    IMPLICIT ARGUMENTS
!!    ------------------
!!
!!    REFERENCE
!!    ---------
!!
!!
!!    AUTHOR
!!    ------
!!      V. Masson   *Meteo France*
!!
!!    MODIFICATIONS
!!    -------------
!!      Original    02/2003 
!!      modified    11/2003 by P. LeMoigne: surface cumulated energy budget
!!      modified    10/2004 by P. LeMoigne: surface miscellaneous fields
!!      B. Decharme    2008    New diag for water budget and allow to reset
!                               cumulatives variables at the beginning of a run
!!      B. Decharme 06/2009    add patch budget switch 
!!      B. Decharme 08/2009    add cummulative diag
!!      A.L. Gibelin 04/2009 : Add respiration diagnostics
!!      A.L. Gibelin 05/2009 : Add carbon spinup
!!      A.L. Gibelin 07/2009 : Suppress RDK and transform GPP as a diagnostic
!!      B. Decharme  05/12   : Carbon fluxes in diag_evap
!!      B. Decharme  10/12     Isba water budget diag
!!      B. Decharme  10/12     New diag for DIF:
!!                             F2 stress
!!                             Root zone swi, wg and wgi
!!                             swi, wg and wgi comparable to ISBA-FR-DG2 and DG3 layers
!!                             active layer thickness over permafrost
!!                             frozen layer thickness over non-permafrost
!!      B. Vincendon 02/2014 : condition added for RAD_BUDGET variables (needed for
!!                             restart mode)
!       B. decharme 04/2013 : Add new diag for coupling
!                             Delete XTSRAD (because same than XTSRAD_NAT)
!!      P. Samuelsson 10/2014: MEB
!-------------------------------------------------------------------------------
!
!*       0.0    DECLARATIONS
!              ------------
!
USE MODD_CH_ISBA_n, ONLY : CH_ISBA_t
USE MODD_DIAG_EVAP_ISBA_n, ONLY : DIAG_EVAP_ISBA_t, DIAG_EVAP_ISBA_PATCH_t
USE MODD_DIAG_n, ONLY : DIAG_t, DIAG_PATCH_t
USE MODD_DIAG_MISC_ISBA_n, ONLY : DIAG_MISC_ISBA_t, DIAG_MISC_ISBA_PATCH_t
USE MODD_GR_BIOG_n, ONLY : GR_BIOG_t
USE MODD_ISBA_OPTIONS_n, ONLY : ISBA_OPTIONS_t
!
#ifdef SFX_OL
USE MODN_IO_OFFLINE,     ONLY : LRESTART
#endif
USE MODD_SURF_PAR,       ONLY : XUNDEF
USE MODD_TYPE_DATE_SURF
USE MODD_AGRI,           ONLY : LAGRIP
!
USE MODI_READ_SURF
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE
!
!*       0.01   Declarations of arguments
!              -------------------------
!
TYPE(CH_ISBA_t), INTENT(INOUT) :: CHI
TYPE(DIAG_EVAP_ISBA_t), INTENT(INOUT) :: DGEI
TYPE(DIAG_EVAP_ISBA_t), INTENT(INOUT) :: DGEIC
TYPE(DIAG_EVAP_ISBA_PATCH_t), INTENT(INOUT) :: DGEIP
TYPE(DIAG_EVAP_ISBA_PATCH_t), INTENT(INOUT) :: DGEIPC
TYPE(DIAG_t), INTENT(INOUT) :: DGI
TYPE(DIAG_t), INTENT(INOUT) :: DGIC
TYPE(DIAG_PATCH_t), INTENT(INOUT) :: DGIP
TYPE(DIAG_PATCH_t), INTENT(INOUT) :: DGIPC
TYPE(DIAG_MISC_ISBA_t), INTENT(INOUT) :: DGMI
TYPE(DIAG_MISC_ISBA_PATCH_t), INTENT(INOUT) :: DGMIP
TYPE(DIAG_t), INTENT(INOUT) :: DGU
TYPE(GR_BIOG_t), INTENT(INOUT) :: GB
TYPE(ISBA_OPTIONS_t), INTENT(INOUT) :: IO
!
 CHARACTER(LEN=*), INTENT(IN) :: HSNOW_SCHEME
INTEGER, INTENT(IN) :: KSNOW_LAYER
INTEGER, INTENT(IN) :: KABC
!
INTEGER, INTENT(IN)         :: KLU       ! size of arrays
INTEGER, INTENT(IN)         :: KSW       ! spectral bands
 CHARACTER(LEN=6), INTENT(IN):: HPROGRAM  ! program calling
!
!*       0.02   Declarations of local variables
!              -------------------------------
!
REAL, DIMENSION(:,:), ALLOCATABLE :: ZWORK
LOGICAL :: GCUMUL
INTEGER :: JPATCH
INTEGER           :: IVERSION, IBUG
INTEGER           :: IRESP          ! IRESP  : return-code if a problem appears
INTEGER           :: ISIZE_LMEB_PATCH   ! Number of patches where multi-energy balance should be applied
 CHARACTER(LEN=12) :: YREC           ! Name of the article to be read
 CHARACTER(LEN=4) :: YREC2
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
!-------------------------------------------------------------------------------
!
!////////////////NOT CUMULATED DIAGNOSTICS//////////////////////////////
!
!* surface energy budget
!
IF (LHOOK) CALL DR_HOOK('DIAG_ISBA_INIT_N',0,ZHOOK_HANDLE)
!
ISIZE_LMEB_PATCH=COUNT(IO%LMEB_PATCH(:))
!
IF (DGI%LSURF_BUDGET) THEN
  !
  CALL ALLOC_SURF_BUD(DGI,KLU,KLU,KSW)
  DO JPATCH = 1,IO%NPATCH
    CALL ALLOC_SURF_BUD(DGIP%AL(JPATCH),KLU,KLU,KSW)
  ENDDO
  !
ELSE
  !
  CALL ALLOC_SURF_BUD(DGI,0,0,0)
  DO JPATCH = 1,IO%NPATCH
    CALL ALLOC_SURF_BUD(DGIP%AL(JPATCH),0,0,0)
  ENDDO
  !
END IF
!
!* detailed surface energy budget
!
IF (DGEI%LSURF_EVAP_BUDGET) THEN
  ! 
  CALL ALLOC_EVAP_BUD(DGEI,KLU)
  DO JPATCH = 1,IO%NPATCH
    CALL ALLOC_EVAP_BUD(DGEIP%AL(JPATCH),KLU)
  ENDDO
  !
  IF (ISIZE_LMEB_PATCH>0) THEN
    !
    CALL ALLOC_MEB_BUD(DGEI,KLU)
    DO JPATCH = 1,IO%NPATCH
      CALL ALLOC_MEB_BUD(DGEIP%AL(JPATCH),KLU)
    ENDDO
    !
  ENDIF
  !
  IF(DGEI%LWATER_BUDGET)THEN
    !      
    ALLOCATE(DGEI%XRAINFALL  (KLU))
    ALLOCATE(DGEI%XSNOWFALL  (KLU))
    DGEI%XRAINFALL   = XUNDEF
    DGEI%XSNOWFALL   = XUNDEF    
    !
    CALL ALLOC_WATER_BUD(DGEI,KLU)
    DO JPATCH=1,IO%NPATCH
      CALL ALLOC_WATER_BUD(DGEIP%AL(JPATCH),KLU)
    ENDDO
    ! 
  ENDIF
  !
ELSE
  !
  CALL ALLOC_EVAP_BUD(DGEI,0)
  DO JPATCH=1,IO%NPATCH
    CALL ALLOC_EVAP_BUD(DGEIP%AL(JPATCH),0)
  ENDDO
  !
ENDIF
!
IF (.NOT.DGEI%LSURF_EVAP_BUDGET .OR. .NOT.DGEI%LWATER_BUDGET) THEN
  !
  ALLOCATE(DGEI%XRAINFALL  (0))
  ALLOCATE(DGEI%XSNOWFALL  (0))
  !
  CALL ALLOC_WATER_BUD(DGEI,0)
  DO JPATCH=1,IO%NPATCH
    CALL ALLOC_WATER_BUD(DGEIP%AL(JPATCH),0)
  ENDDO
  !
ENDIF
!
IF (.NOT.DGEI%LSURF_EVAP_BUDGET .OR. ISIZE_LMEB_PATCH<=0) THEN
  !
  CALL ALLOC_MEB_BUD(DGEI,0)
  DO JPATCH=1,IO%NPATCH
    CALL ALLOC_MEB_BUD(DGEIP%AL(JPATCH),0)
  ENDDO
  ! 
END IF
!
!////////////////CUMULATED DIAGNOSTICS//////////////////////////////
!
!* surface cumulated energy budget
!
#ifdef SFX_OL
GCUMUL = (DGEI%LSURF_BUDGETC .OR. (LRESTART .AND. .NOT.DGEI%LRESET_BUDGETC))
#else
GCUMUL = (DGEI%LSURF_BUDGETC .OR. .NOT.DGEI%LRESET_BUDGETC)
#endif
!
IF ( GCUMUL ) THEN
  !
  !///////////////////////ALLOCATIONS//////////////////////
  !
  CALL ALLOC_EVAP_BUD(DGEIC,KLU)
  DO JPATCH=1,IO%NPATCH
    CALL ALLOC_EVAP_BUD(DGEIPC%AL(JPATCH),KLU)
  ENDDO
    !
  IF (ISIZE_LMEB_PATCH>0) THEN
    !
    CALL ALLOC_MEB_BUD(DGEIC,KLU)
    DO JPATCH=1,IO%NPATCH
      CALL ALLOC_MEB_BUD(DGEIPC%AL(JPATCH),KLU)
    ENDDO
    !
  ENDIF
  !
  CALL ALLOC_SURF_BUD(DGIC,0,KLU,0)
  DO JPATCH=1,IO%NPATCH
    CALL ALLOC_SURF_BUD(DGIPC%AL(JPATCH),0,KLU,0)
  ENDDO
  !
  IF(IO%LGLACIER)THEN
    ALLOCATE(DGEIC%XICEFLUX(KLU))
    DO JPATCH=1,IO%NPATCH
      ALLOCATE(DGEIPC%AL(JPATCH)%XICEFLUX(KLU))
    ENDDO
  ENDIF
  !
#ifdef SFX_OL
  IF(DGEI%LWATER_BUDGET .OR. (LRESTART .AND. .NOT.DGEI%LRESET_BUDGETC))THEN
#else
  IF(DGEI%LWATER_BUDGET .OR. .NOT.DGEI%LRESET_BUDGETC)THEN
#endif          
    !      
    ALLOCATE(DGEIC%XRAINFALL  (KLU))
    ALLOCATE(DGEIC%XSNOWFALL  (KLU))
    !
    CALL ALLOC_WATER_BUD(DGEIC,KLU)
    DO JPATCH=1,IO%NPATCH
      CALL ALLOC_WATER_BUD(DGEIPC%AL(JPATCH),KLU)
    ENDDO
    !     
  ENDIF
  !
  !/////////////////INITIALISATIONS//////////////////////////
  !
  IF (.NOT.DGU%LREAD_BUDGETC .OR. (DGU%LREAD_BUDGETC.AND.DGEI%LRESET_BUDGETC)) THEN
    !
    CALL INIT_EVAP_BUD(DGEIC)
    DO JPATCH=1,IO%NPATCH
      CALL INIT_EVAP_BUD(DGEIPC%AL(JPATCH))
    ENDDO
    !
    IF (ISIZE_LMEB_PATCH>0) THEN
      !
      CALL INIT_MEB_BUD(DGEIC)
      DO JPATCH=1,IO%NPATCH
        CALL INIT_MEB_BUD(DGEIPC%AL(JPATCH))
      ENDDO
      !
    ENDIF
    !
    CALL INIT_SURF_BUD(DGIC)
    !
    DO JPATCH=1,IO%NPATCH
      CALL INIT_SURF_BUD(DGIPC%AL(JPATCH))
    ENDDO
    !
    IF(IO%LGLACIER)THEN
       DGEIC%XICEFLUX = 0.0
       DO JPATCH=1,IO%NPATCH
         DGEIPC%AL(JPATCH)%XICEFLUX     = 0.0
       ENDDO
    ENDIF
    !
#ifdef SFX_OL
    IF(DGEI%LWATER_BUDGET .OR. (LRESTART .AND. .NOT.DGEI%LRESET_BUDGETC))THEN
#else
    IF(DGEI%LWATER_BUDGET .OR. .NOT.DGEI%LRESET_BUDGETC)THEN
#endif      
      !      
      DGEIC%XRAINFALL   = 0.0
      DGEIC%XSNOWFALL   = 0.0
      !
      CALL INIT_WATER_BUD(DGEIC)
      DO JPATCH=1,IO%NPATCH
        CALL INIT_WATER_BUD(DGEIPC%AL(JPATCH))
      ENDDO
      !
    ENDIF
    !     
  ELSE
    !      
    CALL READ_SURF(HPROGRAM,'VERSION',IVERSION,IRESP)
    CALL READ_SURF(HPROGRAM,'BUG ',IBUG,IRESP)
    !
    !/////////////////EVAP ISBA/////////////////////
    !
    YREC='LEGC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLEG   ,IRESP)
    YREC='LEGIC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLEGI  ,IRESP)
    YREC='LEVC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLEV   ,IRESP)
    YREC='LESC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLES   ,IRESP)
    !
    IF(HSNOW_SCHEME=='3-L' .OR. HSNOW_SCHEME=='CRO')THEN
       IF(IVERSION>7 .OR. IVERSION==7 .AND. IBUG>=3)THEN
         YREC='LESLC_ISBA'
         CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLESL,IRESP)  
       ELSE
         DGEIC%XLESL=0.0
       ENDIF
       IF(IVERSION>=8)THEN
         YREC='SNDRIFC_ISBA'
         CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSNDRIFT,IRESP)      
       ELSE
         DGEIC%XSNDRIFT = 0.0
       ENDIF
    ELSE
      DGEIC%XLESL = 0.0
      DGEIC%XSNDRIFT = 0.0
    ENDIF
    YREC='LERC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLER   ,IRESP)
    YREC='LETRC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLETR  ,IRESP)
    YREC='EVAPC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XEVAP  ,IRESP)
    IF (IVERSION<8)THEN
       DGIC%XSUBL = 0.0
    ELSE
       YREC='SUBLC_ISBA'
       CALL READ_SURF(HPROGRAM,YREC,DGIC%XSUBL  ,IRESP) 
    ENDIF    
    YREC='DRAINC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XDRAIN ,IRESP)
    YREC='RUNOFFC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XRUNOFF,IRESP)
    YREC='DRIVEGC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XDRIP  ,IRESP)
    YREC='RRVEGC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XRRVEG ,IRESP)
    YREC='SNOMLTC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGEIC%XMELT,IRESP)
    !
    IF (LAGRIP) THEN
      YREC='IRRIGC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XIRRIG_FLUX,IRESP)    
    ELSE
      DGEIC%XIRRIG_FLUX = 0.0
    ENDIF
    !
    IF(IO%CPHOTO/='NON' .AND. (IVERSION>7 .OR. IVERSION==7 .AND. IBUG>=3))THEN
      YREC='GPPC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XGPP,IRESP)
      YREC='RC_AUTO_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XRESP_AUTO,IRESP)
      YREC='RC_ECO_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XRESP_ECO,IRESP)        
    ELSE
      DGEIC%XGPP = 0.0
      DGEIC%XRESP_AUTO = 0.0
      DGEIC%XRESP_ECO = 0.0
    ENDIF
    !
    IF((IO%CRUNOFF=='SGH'.AND.IO%CISBA=='DIF').AND.IVERSION>=8)THEN
      YREC='QSBC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XQSB,IRESP)              
    ELSE
      DGEIC%XQSB = 0.0
    ENDIF
    !
    IF(IO%CHORT=='SGH'.OR.IO%CISBA=='DIF')THEN
      YREC='HORTONC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XHORT,IRESP)
    ELSE
      DGEIC%XHORT = 0.0
    ENDIF
    !
    IF(IO%LFLOOD)THEN
      YREC='IFLOODC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XIFLOOD,IRESP)
      YREC='PFLOODC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XPFLOOD,IRESP)
      YREC='LEFC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLE_FLOOD,IRESP)
      YREC='LEIFC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLEI_FLOOD,IRESP)
    ELSE
      DGEIC%XIFLOOD   = 0.0
      DGEIC%XPFLOOD   = 0.0
      DGEIC%XLE_FLOOD = 0.0
      DGEIC%XLEI_FLOOD = 0.0
    ENDIF
    !
    !//////////////MEB AGGREGATED///////////////////////
    !
    IF (ISIZE_LMEB_PATCH>0) THEN
      YREC='LEVCVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLEVCV ,IRESP)
      YREC='LESCC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLESC ,IRESP)
      YREC='LETRGVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLETRGV ,IRESP)
      YREC='LETRCVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLETRCV ,IRESP)
      YREC='LERGVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLERGV ,IRESP)
      YREC='LERCVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLERCV ,IRESP)
      YREC='LE_C_AC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLE_C_A ,IRESP)
      YREC='LE_V_CC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLE_V_C ,IRESP)
      YREC='LE_G_CC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLE_G_C ,IRESP)
      YREC='LE_N_CC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLE_N_C ,IRESP)
      !
      YREC='SWNT_VC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSWNET_V ,IRESP)
      YREC='SWNT_GC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSWNET_G ,IRESP)
      YREC='SWNT_NC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSWNET_N ,IRESP)
      YREC='SWNT_NSC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSWNET_NS ,IRESP)
      YREC='LWNT_VC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLWNET_V ,IRESP)
      YREC='LWNT_GC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLWNET_G ,IRESP)
      YREC='LWNT_NC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLWNET_N ,IRESP)
      YREC='SWDN_GNC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSWDOWN_GN ,IRESP)
      YREC='LWDN_GNC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XLWDOWN_GN ,IRESP)
      YREC='H_V_CC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XH_V_C ,IRESP)
      YREC='H_G_CC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XH_G_C ,IRESP)
      YREC='H_C_AC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XH_C_A ,IRESP)
      YREC='H_N_CC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XH_N_C ,IRESP)
      YREC='SR_GNC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSR_GN ,IRESP)
      YREC='MELTCVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XMELTCV ,IRESP)
      YREC='FRZCVC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XFRZCV ,IRESP)
    ENDIF
    !
    !/////////////////SURF AGGREGATED
    !
    YREC='RNC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XRN    ,IRESP)
    YREC='HC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XH     ,IRESP)
    YREC='LEC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XLE    ,IRESP)
    YREC='LEIC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XLEI   ,IRESP)      
    YREC='GFLUXC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XGFLUX ,IRESP)
   !
    IF (DGI%LRAD_BUDGET) THEN
      YREC='SWDC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGIC%XSWD,IRESP)
      YREC='SWUC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGIC%XSWU,IRESP)
      YREC='LWDC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGIC%XLWD,IRESP)
      YREC='LWUC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGIC%XLWU,IRESP)
    ENDIF
    YREC='FMUC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XFMU,IRESP)
    YREC='FMVC_ISBA'
    CALL READ_SURF(HPROGRAM,YREC,DGIC%XFMV,IRESP)      
    !
    IF(IO%LGLACIER)THEN
      YREC='ICE_FC_ISBA'         
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XICEFLUX,IRESP)      
    ENDIF
    !
    !////////////// WATER AGGREGATED/////////////////////////
    !
#ifdef SFX_OL
    IF(DGEI%LWATER_BUDGET .OR. (LRESTART .AND. .NOT.DGEI%LRESET_BUDGETC))THEN
#else
    IF(DGEI%LWATER_BUDGET .OR. .NOT.DGEI%LRESET_BUDGETC)THEN
#endif     
     IF(IVERSION>7 .OR. IVERSION==7 .AND. IBUG>=3)THEN 
      YREC='RAINFC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XRAINFALL,IRESP)
      YREC='SNOWFC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XSNOWFALL,IRESP)
      YREC='DWGC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XDWG,IRESP)
      YREC='DWGIC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XDWGI,IRESP)
      YREC='DWRC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XDWR,IRESP)
      YREC='DSWEC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XDSWE,IRESP)
      YREC='WATBUDC_ISBA'
      CALL READ_SURF(HPROGRAM,YREC,DGEIC%XWATBUD,IRESP)
     ELSE
      DGEIC%XRAINFALL = 0.0
      DGEIC%XSNOWFALL = 0.0
      DGEIC%XDWG = 0.0
      DGEIC%XDWGI = 0.0
      DGEIC%XDWR = 0.0
      DGEIC%XDSWE = 0.0
      DGEIC%XWATBUD = 0.0
     ENDIF
    ENDIF
    !
    IF(DGI%LPATCH_BUDGET .AND. IO%NPATCH>1)THEN
      !
      CALL READ_SURF(HPROGRAM,'VERSION',IVERSION,IRESP)
      CALL READ_SURF(HPROGRAM,'BUG ',IBUG,IRESP)
      !
      YREC2=''
      IF (IVERSION<7 .OR. IVERSION==7 .AND. IBUG<3) YREC2='ATCH'
      !
      ALLOCATE(ZWORK(SIZE(DGEIPC%AL(1)%XLEG),IO%NPATCH))
      !
      !/////////////EVAP PATCH/////////////////////////////
      !
      YREC='LEGC_P'
      CALL READ_SURF(HPROGRAM,TRIM(YREC)//YREC2,ZWORK   ,IRESP)
