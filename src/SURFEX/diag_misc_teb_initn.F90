  DGMT%XDRAIN_GREENROOF   = XUNDEF  
  DGMT%XDRAIN_GARDEN      = XUNDEF  
  DGMT%XIRRIG_GREENROOF   = XUNDEF  
  DGMT%XIRRIG_GARDEN      = XUNDEF  
  DGMT%XIRRIG_ROAD        = XUNDEF  
