  DGMT%XABS_LW_SNOW_ROOF  = XUNDEF  
  DGMT%XABS_SW_ROAD       = XUNDEF  
  DGMT%XABS_SW_SNOW_ROAD  = XUNDEF  
  DGMT%XABS_LW_ROAD       = XUNDEF  
  DGMT%XABS_LW_SNOW_ROAD  = XUNDEF  
  DGMT%XABS_SW_WALL_A     = XUNDEF  
  DGMT%XABS_SW_WALL_B     = XUNDEF  
  DGMT%XABS_LW_WALL_A     = XUNDEF  
  DGMT%XABS_LW_WALL_B     = XUNDEF  
