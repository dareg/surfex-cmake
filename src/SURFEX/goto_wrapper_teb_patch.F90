SUBROUTINE GOTO_WRAPPER_TEB_PATCH(KTO_PATCH, B, DGCT, DGMT, T, TGDR, TGDMT, TGRR, TGRMT)
!
USE MODD_DIAG_CUMUL_TEB_n, ONLY : DIAG_CUMUL_TEB_t, DIAG_CUMUL_TEB_GOTO_PATCH
USE MODD_DIAG_MISC_TEB_n, ONLY : DIAG_MISC_TEB_t, DIAG_MISC_TEB_GOTO_PATCH
USE MODD_TEB_n, ONLY : TEB_t, TEB_GOTO_PATCH
USE MODD_BEM_n, ONLY : BEM_t, BEM_GOTO_PATCH
USE MODD_TEB_VEG_n, ONLY : TEB_VEG_PROG_t, TEB_VEG_PROG_GOTO_PATCH
USE MODD_TEB_VEG_PARAM_n, ONLY : TEB_VEG_PARAM_TIME_t, TEB_VEG_PARAM_TIME_GOTO_PATCH
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE 
!
INTEGER,INTENT(IN) :: KTO_PATCH
!
TYPE(BEM_t), INTENT(INOUT), OPTIONAL :: B
TYPE(DIAG_CUMUL_TEB_t), INTENT(INOUT), OPTIONAL :: DGCT
TYPE(DIAG_MISC_TEB_t), INTENT(INOUT), OPTIONAL :: DGMT
TYPE(TEB_t), INTENT(INOUT), OPTIONAL :: T
TYPE(TEB_VEG_PROG_t), INTENT(INOUT), OPTIONAL :: TGDR
TYPE(TEB_VEG_PARAM_TIME_t), INTENT(INOUT), OPTIONAL :: TGDMT
TYPE(TEB_VEG_PROG_t), INTENT(INOUT), OPTIONAL :: TGRR
TYPE(TEB_VEG_PARAM_TIME_t), INTENT(INOUT), OPTIONAL :: TGRMT
!
INTEGER            :: ICURRENT_PATCH
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('GOTO_WRAPPER_TEB_PATCH',0,ZHOOK_HANDLE)
!
IF (PRESENT(T)) CALL TEB_GOTO_PATCH(T,KTO_PATCH)
IF (PRESENT(B))  CALL BEM_GOTO_PATCH(B,KTO_PATCH)
IF (PRESENT(TGDR)) CALL TEB_VEG_PROG_GOTO_PATCH(TGDR,KTO_PATCH)
IF (PRESENT(TGDMT)) CALL TEB_VEG_PARAM_TIME_GOTO_PATCH(TGDMT,KTO_PATCH)
IF (PRESENT(TGRR))  CALL TEB_VEG_PROG_GOTO_PATCH(TGRR,KTO_PATCH)
IF (PRESENT(TGRMT)) CALL TEB_VEG_PARAM_TIME_GOTO_PATCH(TGRMT,KTO_PATCH)
IF (PRESENT(DGCT)) CALL DIAG_CUMUL_TEB_GOTO_PATCH(DGCT,KTO_PATCH)
IF (PRESENT(DGMT)) CALL DIAG_MISC_TEB_GOTO_PATCH(DGMT,KTO_PATCH) 
!
IF (LHOOK) CALL DR_HOOK('GOTO_WRAPPER_TEB_PATCH',1,ZHOOK_HANDLE)
!
END SUBROUTINE GOTO_WRAPPER_TEB_PATCH
