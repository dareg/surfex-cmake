USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE

TYPE GR_BIOG_GREENROOF_t
!
!
!
!* Emission potential for isoprene and monoterpenes 
  REAL, DIMENSION(:), POINTER :: XISOPOT 
  REAL, DIMENSION(:), POINTER :: XMONOPOT 
!
!* Radiation at different level(cf Gauss) in the canopy
  REAL, DIMENSION(:), POINTER :: XP_IACAN !pack radiation
  REAL, DIMENSION(:,:,:),POINTER ::XIACAN ! PAR at 3 gauss level for each patch
!
!* XFISO  = isoprene emission flux (ppp.m.s-1)
!  XFMONO = monoterpenes emission flux (ppp m s-1)
  REAL, DIMENSION(:), POINTER :: XFISO, XFMONO
!
!
END TYPE GR_BIOG_GREENROOF_t

TYPE(GR_BIOG_GREENROOF_t), ALLOCATABLE, TARGET, SAVE :: GR_BIOG_GREENROOF_MODEL(:)

TYPE(GR_BIOG_GREENROOF_t), POINTER :: GR_BIOG_GREENROOF => NULL()
!$OMP THREADPRIVATE(GR_BIOG_GREENROOF)

CONTAINS

SUBROUTINE GR_BIOG_GREENROOF_GOTO_MODEL(KFROM, KTO, LKFROM)
LOGICAL, INTENT(IN) :: LKFROM
INTEGER, INTENT(IN) :: KFROM, KTO
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
! Current model is set to model KTO
IF (LHOOK) CALL DR_HOOK('MODD_GR_BIOG_GREENROOF_N:GR_BIOG_GREENROOF_GOTO_MODEL',0,ZHOOK_HANDLE)

GR_BIOG_GREENROOF => GR_BIOG_GREENROOF_MODEL(KTO)

IF (LHOOK) CALL DR_HOOK('MODD_GR_BIOG_GREENROOF_N:GR_BIOG_GREENROOF_GOTO_MODEL',1,ZHOOK_HANDLE)

END SUBROUTINE GR_BIOG_GREENROOF_GOTO_MODEL

SUBROUTINE GR_BIOG_GREENROOF_ALLOC(KMODEL)
INTEGER, INTENT(IN) :: KMODEL
INTEGER :: J
REAL(KIND=JPRB) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK("MODD_GR_BIOG_GREENROOF_N:GR_BIOG_GREENROOF_ALLOC",0,ZHOOK_HANDLE)
ALLOCATE(GR_BIOG_GREENROOF_MODEL(KMODEL))
GR_BIOG_GREENROOF => GR_BIOG_GREENROOF_MODEL(KMODEL)
DO J=1,KMODEL
  NULLIFY(GR_BIOG_GREENROOF_MODEL(J)%XISOPOT)
  NULLIFY(GR_BIOG_GREENROOF_MODEL(J)%XMONOPOT)
  NULLIFY(GR_BIOG_GREENROOF_MODEL(J)%XP_IACAN)
  NULLIFY(GR_BIOG_GREENROOF_MODEL(J)%XIACAN)
  NULLIFY(GR_BIOG_GREENROOF_MODEL(J)%XFISO)
  NULLIFY(GR_BIOG_GREENROOF_MODEL(J)%XFMONO)
ENDDO
IF (LHOOK) CALL DR_HOOK("MODD_GR_BIOG_GREENROOF_N:GR_BIOG_GREENROOF_ALLOC",1,ZHOOK_HANDLE)
END SUBROUTINE GR_BIOG_GREENROOF_ALLOC

SUBROUTINE GR_BIOG_GREENROOF_DEALLO
REAL(KIND=JPRB) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK("MODD_GR_BIOG_GREENROOF_N:GR_BIOG_GREENROOF_DEALLO",0,ZHOOK_HANDLE)
IF (ALLOCATED(GR_BIOG_GREENROOF_MODEL)) DEALLOCATE(GR_BIOG_GREENROOF_MODEL)
IF (ASSOCIATED(GR_BIOG_GREENROOF)) NULLIFY(GR_BIOG_GREENROOF)
IF (LHOOK) CALL DR_HOOK("MODD_GR_BIOG_GREENROOF_N:GR_BIOG_GREENROOF_DEALLO",1,ZHOOK_HANDLE)
END SUBROUTINE GR_BIOG_GREENROOF_DEALLO

END MODULE MODD_GR_BIOG_GREENROOF_n
