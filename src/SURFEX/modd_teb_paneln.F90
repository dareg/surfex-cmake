USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE

TYPE TEB_PANEL_t
!
  REAL,    POINTER, DIMENSION(:) :: XEMIS_PANEL       ! emissivity of solar panels               (-)
  REAL,    POINTER, DIMENSION(:) :: XALB_PANEL        ! albedo of soolar panels                  (-)
  REAL,    POINTER, DIMENSION(:) :: XEFF_PANEL        ! Efficiency coefficient of solar panels   (-)
  REAL,    POINTER, DIMENSION(:) :: XFRAC_PANEL       ! Fraction of SOLAR panels on roofs        (-)
  REAL,    POINTER, DIMENSION(:) :: XTHER_PRODC_DAY   ! Present day integrated thermal production of energy    (J/m2 panel)
!
END TYPE TEB_PANEL_t

TYPE(TEB_PANEL_t), ALLOCATABLE, TARGET, SAVE :: TEB_PANEL_MODEL(:)

REAL,    POINTER, DIMENSION(:) :: XEMIS_PANEL=>NULL()
!$OMP THREADPRIVATE(XEMIS_PANEL)
REAL,    POINTER, DIMENSION(:) :: XALB_PANEL=>NULL()
!$OMP THREADPRIVATE(XALB_PANEL)
REAL,    POINTER, DIMENSION(:) :: XEFF_PANEL=>NULL()
!$OMP THREADPRIVATE(XEFF_PANEL)
REAL,    POINTER, DIMENSION(:) :: XFRAC_PANEL=>NULL()
!$OMP THREADPRIVATE(XFRAC_PANEL)
REAL,    POINTER, DIMENSION(:) :: XTHER_PRODC_DAY=>NULL()
!$OMP THREADPRIVATE(XTHER_PRODC_DAY)

CONTAINS

SUBROUTINE TEB_PANEL_GOTO_MODEL(KFROM, KTO, LKFROM)
LOGICAL, INTENT(IN) :: LKFROM
INTEGER, INTENT(IN) :: KFROM, KTO
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
! Save current state for allocated arrays
IF (LKFROM) THEN
TEB_PANEL_MODEL(KFROM)%XEMIS_PANEL=>XEMIS_PANEL
TEB_PANEL_MODEL(KFROM)%XALB_PANEL=>XALB_PANEL
TEB_PANEL_MODEL(KFROM)%XEFF_PANEL=>XEFF_PANEL
TEB_PANEL_MODEL(KFROM)%XFRAC_PANEL=>XFRAC_PANEL
TEB_PANEL_MODEL(KFROM)%XTHER_PRODC_DAY=>XTHER_PRODC_DAY
ENDIF
!
! Current model is set to model KTO
IF (LHOOK) CALL DR_HOOK('MODD_TEB_PANEL_N:TEB_PANEL_GOTO_MODEL',0,ZHOOK_HANDLE)
XEMIS_PANEL=>TEB_PANEL_MODEL(KTO)%XEMIS_PANEL
XALB_PANEL=>TEB_PANEL_MODEL(KTO)%XALB_PANEL
XEFF_PANEL=>TEB_PANEL_MODEL(KTO)%XEFF_PANEL
XFRAC_PANEL=>TEB_PANEL_MODEL(KTO)%XFRAC_PANEL
XTHER_PRODC_DAY=>TEB_PANEL_MODEL(KTO)%XTHER_PRODC_DAY
IF (LHOOK) CALL DR_HOOK('MODD_TEB_PANEL_N:TEB_PANEL_GOTO_MODEL',1,ZHOOK_HANDLE)

END SUBROUTINE TEB_PANEL_GOTO_MODEL

SUBROUTINE TEB_PANEL_ALLOC(KMODEL)
INTEGER, INTENT(IN) :: KMODEL
INTEGER :: J
REAL(KIND=JPRB) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK("MODD_TEB_PANEL_N:TEB_PANEL_ALLOC",0,ZHOOK_HANDLE)
ALLOCATE(TEB_PANEL_MODEL(KMODEL))
DO J=1,KMODEL
  NULLIFY(TEB_PANEL_MODEL(J)%XEMIS_PANEL)
  NULLIFY(TEB_PANEL_MODEL(J)%XALB_PANEL)
  NULLIFY(TEB_PANEL_MODEL(J)%XEFF_PANEL)
  NULLIFY(TEB_PANEL_MODEL(J)%XFRAC_PANEL)
  NULLIFY(TEB_PANEL_MODEL(J)%XTHER_PRODC_DAY)
ENDDO
IF (LHOOK) CALL DR_HOOK("MODD_TEB_PANEL_N:TEB_PANEL_ALLOC",1,ZHOOK_HANDLE)
END SUBROUTINE TEB_PANEL_ALLOC

SUBROUTINE TEB_PANEL_DEALLO
REAL(KIND=JPRB) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK("MODD_TEB_PANEL_N:TEB_PANEL_DEALLO",0,ZHOOK_HANDLE)
IF (ALLOCATED(TEB_PANEL_MODEL)) DEALLOCATE(TEB_PANEL_MODEL)
IF (LHOOK) CALL DR_HOOK("MODD_TEB_PANEL_N:TEB_PANEL_DEALLO",1,ZHOOK_HANDLE)
END SUBROUTINE TEB_PANEL_DEALLO

END MODULE MODD_TEB_PANEL_n
