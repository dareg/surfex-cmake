SUBROUTINE ALLOC_SURF_BUD(DGIA,KLUA,KLUAC,KSWA)
!
TYPE(DIAG_t), INTENT(INOUT) :: DGIA
INTEGER, INTENT(IN) :: KLUA
INTEGER, INTENT(IN) :: KLUAC
INTEGER, INTENT(IN) :: KSWA
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
