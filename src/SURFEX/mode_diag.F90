!
ALLOCATE(DGIA%XRN           (KLUAC))
ALLOCATE(DGIA%XH            (KLUAC))
ALLOCATE(DGIA%XLE           (KLUAC))
ALLOCATE(DGIA%XLEI          (KLUAC))
ALLOCATE(DGIA%XGFLUX        (KLUAC))
ALLOCATE(DGIA%XEVAP      (KLUAC))
ALLOCATE(DGIA%XSUBL      (KLUAC))
!
ALLOCATE(DGIA%XSWD          (KLUAC))
ALLOCATE(DGIA%XSWU          (KLUAC))
ALLOCATE(DGIA%XLWD          (KLUAC))
ALLOCATE(DGIA%XLWU          (KLUAC))
ALLOCATE(DGIA%XFMU          (KLUAC))
ALLOCATE(DGIA%XFMV          (KLUAC))
!
IF (KLUAC>0) THEN
  DGIA%XRN      = XUNDEF
  DGIA%XH       = XUNDEF
  DGIA%XLE      = XUNDEF
  DGIA%XLEI     = XUNDEF
  DGIA%XGFLUX   = XUNDEF
  DGIA%XEVAP       = XUNDEF
  DGIA%XSUBL       = XUNDEF  
  DGIA%XSWD     = XUNDEF
  DGIA%XSWU     = XUNDEF
  DGIA%XLWD     = XUNDEF
  DGIA%XLWU     = XUNDEF
  DGIA%XFMU     = XUNDEF
  DGIA%XFMV     = XUNDEF
ENDIF
!
ALLOCATE(DGIA%XSWBD         (KLUA,KSWA))
ALLOCATE(DGIA%XSWBU         (KLUA,KSWA))
!
IF (KLUA>0) THEN
  DGIA%XSWBD    = XUNDEF
  DGIA%XSWBU    = XUNDEF
ENDIF
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:ALLOC_SURF_BUD',1,ZHOOK_HANDLE)
