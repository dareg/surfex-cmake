IF (DGO%LCOEF) CALL INIT_COEF_BUD(DGIA,PVAL)
DGIA%XTS = PVAL
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:INIT_BUD',1,ZHOOK_HANDLE)
!
END SUBROUTINE INIT_BUD

