SUBROUTINE DIAG_EVAP(DGO, DG, DGC, HPROGRAM, DGUP, DGUPC, KMASK )
!
IMPLICIT NONE
!
TYPE(DIAG_OPTIONS_t), INTENT(IN) :: DGO
TYPE(DIAG_t), INTENT(INOUT) :: DG
TYPE(DIAG_t), INTENT(INOUT) :: DGC
 CHARACTER(LEN=6),   INTENT(IN)  :: HPROGRAM ! program calling surf. schemes
TYPE(DIAG_t), INTENT(INOUT) :: DGUP
TYPE(DIAG_t), INTENT(INOUT) :: DGUPC
INTEGER, DIMENSION(:), INTENT(IN) :: KMASK
!
INTEGER :: JJ, ISIZE
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:DIAG_EVAP',0,ZHOOK_HANDLE)
!
ISIZE = SIZE(KMASK)
!
 CALL DIAG_CUMUL(DGO, DG, DGC, HPROGRAM, DGUP, DGUPC, KMASK)
!
IF (DGO%LSURF_BUDGET) THEN
  DO JJ=1,ISIZE
    DGUP%XEVAP    (KMASK(JJ))  = DG%XEVAP     (JJ)
    DGUP%XSUBL    (KMASK(JJ))  = DG%XSUBL     (JJ)
  ENDDO
END IF
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:DIAG_EVAP',1,ZHOOK_HANDLE)
!
END SUBROUTINE DIAG_EVAP
!
SUBROUTINE DIAG_CUMUL(DGO, DG, DGC, HPROGRAM, DGUP, DGUPC, KMASK )
!
IMPLICIT NONE
!
TYPE(DIAG_OPTIONS_t), INTENT(IN) :: DGO
TYPE(DIAG_t), INTENT(INOUT) :: DG
TYPE(DIAG_t), INTENT(INOUT) :: DGC
 CHARACTER(LEN=6),   INTENT(IN)  :: HPROGRAM ! program calling surf. schemes
TYPE(DIAG_t), INTENT(INOUT) :: DGUP
TYPE(DIAG_t), INTENT(INOUT) :: DGUPC
INTEGER, DIMENSION(:), INTENT(IN) :: KMASK
!
INTEGER :: JJ, ISIZE
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:DIAG_CUMUL',0,ZHOOK_HANDLE)
!
ISIZE = SIZE(KMASK)
!
 CALL DIAG(DGO, DG, HPROGRAM, DGUP, KMASK)
!
IF (DGO%LSURF_BUDGETC) THEN
  DO JJ=1,ISIZE
    DGUPC%XRN      (KMASK(JJ))  = DGC%XRN       (JJ)
    DGUPC%XH       (KMASK(JJ))  = DGC%XH        (JJ)
    DGUPC%XLE      (KMASK(JJ))  = DGC%XLE       (JJ)
    DGUPC%XLEI     (KMASK(JJ))  = DGC%XLEI      (JJ)
    DGUPC%XGFLUX   (KMASK(JJ))  = DGC%XGFLUX    (JJ)
    DGUPC%XEVAP    (KMASK(JJ))  = DGC%XEVAP     (JJ)
    DGUPC%XSUBL    (KMASK(JJ))  = DGC%XSUBL     (JJ)
    DGUPC%XSWD     (KMASK(JJ))  = DGC%XSWD      (JJ)
    DGUPC%XSWU     (KMASK(JJ))  = DGC%XSWU      (JJ)
    DGUPC%XLWD     (KMASK(JJ))  = DGC%XLWD      (JJ)
    DGUPC%XLWU     (KMASK(JJ))  = DGC%XLWU      (JJ)
    DGUPC%XFMU     (KMASK(JJ))  = DGC%XFMU      (JJ)
    DGUPC%XFMV     (KMASK(JJ))  = DGC%XFMV      (JJ)
  ENDDO        
END IF
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:DIAG_CUMUL',1,ZHOOK_HANDLE)
!
END SUBROUTINE DIAG_CUMUL
!
SUBROUTINE DIAG(DGO, DG, HPROGRAM, DGUP, KMASK )
!
IMPLICIT NONE
!
TYPE(DIAG_OPTIONS_t), INTENT(IN) :: DGO
TYPE(DIAG_t), INTENT(INOUT) :: DG
 CHARACTER(LEN=6),   INTENT(IN)  :: HPROGRAM ! program calling surf. schemes
TYPE(DIAG_t), INTENT(INOUT) :: DGUP
INTEGER, DIMENSION(:), INTENT(IN) :: KMASK
!
INTEGER :: JJ, ISIZE
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:DIAG',0,ZHOOK_HANDLE)
!
ISIZE = SIZE(KMASK)
!
IF (DGO%LSURF_BUDGET) THEN
  DO JJ=1,ISIZE
    DGUP%XRN      (KMASK(JJ))  = DG%XRN       (JJ)
    DGUP%XH       (KMASK(JJ))  = DG%XH        (JJ)
    DGUP%XLE      (KMASK(JJ))  = DG%XLE       (JJ)
    DGUP%XLEI     (KMASK(JJ))  = DG%XLEI      (JJ)
    DGUP%XGFLUX   (KMASK(JJ))  = DG%XGFLUX    (JJ)
    DGUP%XSWD     (KMASK(JJ))  = DG%XSWD      (JJ)
    DGUP%XSWU     (KMASK(JJ))  = DG%XSWU      (JJ)
    DGUP%XLWD     (KMASK(JJ))  = DG%XLWD      (JJ)
    DGUP%XLWU     (KMASK(JJ))  = DG%XLWU      (JJ)
    DGUP%XFMU     (KMASK(JJ))  = DG%XFMU      (JJ)
    DGUP%XFMV     (KMASK(JJ))  = DG%XFMV      (JJ)
    DGUP%XSWBD    (KMASK(JJ),:) = DG%XSWBD     (JJ,:)
    DGUP%XSWBU    (KMASK(JJ),:) = DG%XSWBU     (JJ,:)
  ENDDO
END IF
!
IF (DGO%N2M>=1 .OR. DGO%LSURF_BUDGET) THEN
  DO JJ=1,ISIZE
    DGUP%XTS       (KMASK(JJ))  = DG%XTS      (JJ)
  ENDDO        
ENDIF
!
IF (DGO%N2M>=1) THEN
  DO JJ=1,ISIZE
    DGUP%XRI      (KMASK(JJ))  = DG%XRI       (JJ)
    DGUP%XT2M     (KMASK(JJ))  = DG%XT2M      (JJ)
    DGUP%XT2M_MIN (KMASK(JJ))  = DG%XT2M_MIN  (JJ)
    DGUP%XT2M_MAX (KMASK(JJ))  = DG%XT2M_MAX  (JJ)
    DGUP%XQ2M     (KMASK(JJ))  = DG%XQ2M      (JJ)
    DGUP%XHU2M    (KMASK(JJ))  = DG%XHU2M     (JJ)
    DGUP%XHU2M_MIN(KMASK(JJ))  = DG%XHU2M_MIN (JJ)
    DGUP%XHU2M_MAX(KMASK(JJ))  = DG%XHU2M_MAX (JJ)
    DGUP%XZON10M  (KMASK(JJ))  = DG%XZON10M   (JJ)
    DGUP%XMER10M  (KMASK(JJ))  = DG%XMER10M   (JJ)
    DGUP%XWIND10M (KMASK(JJ))  = DG%XWIND10M   (JJ)
    DGUP%XWIND10M_MAX (KMASK(JJ))  = DG%XWIND10M_MAX   (JJ)
  ENDDO        
END IF 
!
IF (DGO%LCOEF) THEN
  DO JJ=1,ISIZE
    DGUP%XCD      (KMASK(JJ))  = DG%XCD       (JJ)
    DGUP%XCH      (KMASK(JJ))  = DG%XCH       (JJ)
    DGUP%XCE      (KMASK(JJ))  = DG%XCE       (JJ)
    DGUP%XQS      (KMASK(JJ))  = DG%XQS       (JJ)
    DGUP%XZ0      (KMASK(JJ))  = DG%XZ0       (JJ)
    DGUP%XZ0H     (KMASK(JJ))  = DG%XZ0H      (JJ)
  ENDDO        
END IF
!
IF (DGO%LSURF_VARS) THEN
  DO JJ=1,ISIZE
    DGUP%XQS      (KMASK(JJ))  = DG%XQS       (JJ)
  ENDDO          
ENDIF
!
IF (LHOOK) CALL DR_HOOK('MODE_DIAG:DIAG',1,ZHOOK_HANDLE)
!
END SUBROUTINE DIAG
