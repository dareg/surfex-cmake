  IF (LHOOK) CALL DR_HOOK('MODN_TEB_N:INIT_NAM_DIAG_TEBN',0,ZHOOK_HANDLE)
  LPGD = DGT%LPGD
  LPGD_FIX = DGT%LPGD_FIX
  LSURF_MISC_BUDGET = DGMTO%LSURF_MISC_BUDGET
  LSURF_DIAG_ALBEDO = DGMTO%LSURF_DIAG_ALBEDO
  LUTCI = DGUT%LUTCI
