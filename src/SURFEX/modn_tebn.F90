  DGT%LPGD = LPGD
  DGT%LPGD_FIX = LPGD_FIX
  DGMTO%LSURF_MISC_BUDGET = LSURF_MISC_BUDGET
  DGMTO%LSURF_DIAG_ALBEDO = LSURF_DIAG_ALBEDO
  DGUT%LUTCI = LUTCI
