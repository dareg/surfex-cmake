  DO JK=1,SIZE(PK%I%R%XLIGNIN_STRUC,2)
    PK%I%R%XLIGNIN_STRUC(:,JK,1) = IR%XLIGNIN_STRUC(KMASK(:),JK,KPATCH)
  ENDDO
  DO JK=1,SIZE(PK%I%IP%XTURNOVER,2)
    PK%I%IP%XTURNOVER(:,JK,1) = IP%XTURNOVER(KMASK(:),JK,KPATCH)
  ENDDO
