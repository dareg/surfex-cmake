  PK%I%I%XFFLOOD  (:)   = 0.0
  PK%I%I%XPIFLOOD (:)   = 0.0
  PK%I%I%XFF      (:,1) = 0.0
  PK%I%I%XFFG     (:,1) = 0.0
  PK%I%I%XFFROZEN (:,1) = 0.0
  PK%I%I%XFFV     (:,1) = 0.0
  PK%I%I%XALBF    (:,1) = 0.0
  PK%I%I%XEMISF   (:,1) = 0.0
ENDIF
!
IF(IR%TSNOW%SCHEME=='EBA') THEN
  PK%I%R%XPSNV_A (:,1) = IR%XPSNV_A(KMASK(:), KPATCH)
END IF
!
IF (IR%TSNOW%SCHEME=='3-L' .OR. IR%TSNOW%SCHEME=='CRO') THEN
  DO JK=1,SIZE(PK%I%R%TSNOW%HEAT,2)
    PK%I%R%TSNOW%HEAT   (:, JK,1) =  IR%TSNOW%HEAT   (KMASK(:), JK, KPATCH)
    PK%I%R%TSNOW%AGE    (:, JK,1) =  IR%TSNOW%AGE    (KMASK(:), JK, KPATCH)
  END DO
  PK%I%R%TSNOW%ALBVIS   (:,1) =  IR%TSNOW%ALBVIS  (KMASK(:), KPATCH) 
  PK%I%R%TSNOW%ALBNIR   (:,1) =  IR%TSNOW%ALBNIR  (KMASK(:), KPATCH) 
  PK%I%R%TSNOW%ALBFIR   (:,1) =  IR%TSNOW%ALBFIR  (KMASK(:), KPATCH) 
END IF
!
IF (IR%TSNOW%SCHEME=='CRO') THEN
  DO JK=1,SIZE(PK%I%R%TSNOW%GRAN1,2)
    PK%I%R%TSNOW%GRAN1  (:, JK,1) =  IR%TSNOW%GRAN1  (KMASK(:), JK, KPATCH)
    PK%I%R%TSNOW%GRAN2  (:, JK,1) =  IR%TSNOW%GRAN2  (KMASK(:), JK, KPATCH)
    PK%I%R%TSNOW%HIST   (:, JK,1) =  IR%TSNOW%HIST   (KMASK(:), JK, KPATCH)
  ENDDO
END IF
!
IF(IO%LGLACIER)THEN
  PK%I%R%XICE_STO(:,1) = IR%XICE_STO  (KMASK(:),KPATCH)
ENDIF
!  
IF (IO%CSCOND=='PL98'.OR.IO%CISBA=='DIF') THEN
  DO JK=1,SIZE(IP%XHCAPSOIL,2)
    PK%I%IP%XHCAPSOIL   (:, JK) =  IP%XHCAPSOIL    (KMASK(:), JK)
    PK%I%IP%XCONDDRY    (:, JK) =  IP%XCONDDRY     (KMASK(:), JK)
    PK%I%IP%XCONDSLD    (:, JK) =  IP%XCONDSLD     (KMASK(:), JK)
  ENDDO
END IF
!
IF (IO%CISBA=='2-L' .OR. IO%CISBA=='3-L') THEN
  PK%I%IP%XC4B        (:) =  IP%XC4B          (KMASK(:))
  PK%I%IP%XACOEF      (:) =  IP%XACOEF        (KMASK(:))
  PK%I%IP%XPCOEF      (:) =  IP%XPCOEF        (KMASK(:))
  PK%I%IP%XCGSAT      (:) =  IP%XCGSAT        (KMASK(:)) 
  PK%I%IP%XC1SAT      (:,1) =  IP%XC1SAT        (KMASK(:), KPATCH)
  PK%I%IP%XC2REF      (:,1) =  IP%XC2REF        (KMASK(:), KPATCH)     
  PK%I%IP%XC4REF      (:,1) =  IP%XC4REF        (KMASK(:), KPATCH)      
  !
  DO JK=1,SIZE(IP%XC3,2)
    PK%I%IP%XC3         (:,JK,1)  =  IP%XC3           (KMASK(:), JK, KPATCH)
  ENDDO
