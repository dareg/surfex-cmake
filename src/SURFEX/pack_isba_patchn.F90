  PK%I%I%XFFLOOD  (:)   = INI%XFFLOOD  (KMASK(:))
  PK%I%I%XPIFLOOD (:)   = INI%XPIFLOOD (KMASK(:))
  PK%I%I%XFF      (:,1) = INI%XFF      (KMASK(:),KPATCH)
