!
DO JK=1,SIZE(IP%XBCOEF,2)
  PK%I%IP%XMPOTSAT (:, JK) =  IP%XMPOTSAT (KMASK(:), JK)
  PK%I%IP%XBCOEF   (:, JK) =  IP%XBCOEF   (KMASK(:), JK)
ENDDO
!
IF (IO%CISBA=='DIF') THEN
  DO JK=1,SIZE(IPM%X%XROOTFRAC,2)
    PK%I%M%X%XROOTFRAC   (:, JK,1) = IPM%X%XROOTFRAC   (KMASK(:), JK, KPATCH)
