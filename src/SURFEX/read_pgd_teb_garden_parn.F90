    DTGD%XPAR_CF_NITRO(JI,1) =  ( ZDATA_CF_NITRO(JI,1)*DTGD%XPAR_FRAC_HVEG(JI)     &
                          + ZDATA_CF_NITRO(JI,2)*DTGD%XPAR_FRAC_LVEG(JI)   ) &
                        / ( DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI)    )  
!
! Nitrogen concentration of active biomass
 ZDATA_CNA_NITRO(JI,:)=1.3
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.0
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.0
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.0
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.0
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.0
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BONE)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.8
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TENE)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.8
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOND)>0. )  ZDATA_CNA_NITRO(JI,1)= 2.8
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBE)>0. )  ZDATA_CNA_NITRO(JI,1)= 1.7
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_C4  )>0. )  ZDATA_CNA_NITRO(JI,2)= 1.9
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_IRR )>0. )  ZDATA_CNA_NITRO(JI,2)= 1.9
 IF (DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI) .GT. 0.)                      &
    DTGD%XPAR_CNA_NITRO(JI,1) =  ( ZDATA_CNA_NITRO(JI,1)*DTGD%XPAR_FRAC_HVEG(JI)     &
                           + ZDATA_CNA_NITRO(JI,2)*DTGD%XPAR_FRAC_LVEG(JI)   ) &
                         / ( DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI)     )  
!
! Ground layers
 IF (TGDO%NGROUND_LAYER<=3) THEN
   ZDATA_DG(JI,1,:) = 0.01
   ZDATA_DG(JI,2,:) = 1.50
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_BONE)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_TENE)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOND)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBE)>0. )  ZDATA_DG(JI,2,1)= 2.0
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_NO  )>0. )  ZDATA_DG(JI,2,3)= 0.5
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_ROCK)>0. )  ZDATA_DG(JI,2,3)= 0.5
   IF(DTGD%XPAR_VEGTYPE(JI,NVT_SNOW)>0. )  ZDATA_DG(JI,2,3)= 0.5
   IF (TGDO%NGROUND_LAYER==3) THEN
      ZDATA_DG(JI,3,:) = 2.00
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_BONE)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_TENE)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOND)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBE)>0. )  ZDATA_DG(JI,3,1)= 3.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_NO  )>0. )  ZDATA_DG(JI,3,3)= 1.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_ROCK)>0. )  ZDATA_DG(JI,3,3)= 1.0
      IF(DTGD%XPAR_VEGTYPE(JI,NVT_SNOW)>0. )  ZDATA_DG(JI,3,3)= 1.0
   ENDIF
   DTGD%XPAR_DG(JI,:,1) =    ZDATA_DG(JI,:,1)*DTGD%XPAR_FRAC_HVEG(JI)   &
                       + ZDATA_DG(JI,:,2)*DTGD%XPAR_FRAC_LVEG(JI) &
                       + ZDATA_DG(JI,:,3)*DTGD%XPAR_FRAC_NVEG(JI)  
 ELSEIF (TGDO%NGROUND_LAYER<=NOPTIMLAYER) THEN
   DTGD%XPAR_DG(JI,:,1) = XOPTIMGRID(:)
 ELSE
   CALL ABOR1_SFX("READ_PGD_TEB_GARDEN_PAR: WITH MORE THAN 14 SOIL LAYERS, "//&
     "WITHOUT ECOCLIMAP, GARDEN CANNOT RUN")
 ENDIF 
!
! Root fractions
 DTGD%XPAR_ROOTFRAC(JI,TGDO%NGROUND_LAYER,1) = 1.
 DTGD%XPAR_ROOTFRAC(JI,1,1) = 0.20
 IF (TGDO%NGROUND_LAYER>2) THEN
   DO JLAYER = TGDO%NGROUND_LAYER-1,2,-1
     DTGD%XPAR_ROOTFRAC(JI,JLAYER,1) = DTGD%XPAR_ROOTFRAC(JI,JLAYER+1,1)-0.8/(TGDO%NGROUND_LAYER-1)
   ENDDO
 ENDIF
!
 DTGD%XPAR_DICE(JI,1) = DTGD%XPAR_DG(JI,2,1)
!
 DO JTIME=1,DTGD%NTIME
! Leaf Area Index
 IF (DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI) .GT. 0.)                           &
     DTGD%XPAR_LAI     (JI,JTIME,1) = ( DTGD%XPAR_LAI_HVEG(JI,JTIME)*DTGD%XPAR_FRAC_HVEG(JI)  &
                                + DTGD%XPAR_LAI_LVEG(JI,JTIME)*DTGD%XPAR_FRAC_LVEG(JI)) &
                               /( DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI))  
! Fraction of vegetation
  DTGD%XPAR_VEG     (JI,JTIME,1) = VEG_FROM_LAI  (DTGD%XPAR_LAI    (JI,JTIME,1),       &
                                            DTGD%XPAR_VEGTYPE(JI,:),GAGRI_TO_GRASS)  
! Roughness length for momentum
  DTGD%XPAR_Z0      (JI,JTIME,1) = Z0V_FROM_LAI  (DTGD%XPAR_LAI    (JI,JTIME,1),       &
                                            DTGD%XPAR_H_TREE (JI,1),           &
                                            DTGD%XPAR_VEGTYPE(JI,:),GAGRI_TO_GRASS)  
! Emissivity
  DTGD%XPAR_EMIS    (JI,JTIME,1) = EMIS_FROM_VEG (DTGD%XPAR_VEG    (JI,JTIME,1),       &
                                            DTGD%XPAR_VEGTYPE(JI,:))
 END DO
!
ENDDO
IF (LHOOK) CALL DR_HOOK('READ_PGD_TEB_GARDEN_PAR_N',1,ZHOOK_HANDLE)
!
!-------------------------------------------------------------------------------
!
END SUBROUTINE READ_PGD_TEB_GARDEN_PAR_n
