!     #########
      SUBROUTINE READ_PGD_TEB_GARDEN_PAR_n (&
                                             DTGD, TGDO, TGDP, TGDIP, TG, &
                                            HPROGRAM)
!     ################################################
!
!!****  *READ_PGD_TEB_GARDEN_PAR_n* - reads ISBA physiographic fields
!!                        
!!
!!    PURPOSE
!!    -------
!!
!!**  METHOD
!!    ------
!!
!!    EXTERNAL
!!    --------
!!
!!
!!    IMPLICIT ARGUMENTS
!!    ------------------
!!
!!    REFERENCE
!!    ---------
!!
!!
!!    AUTHOR
!!    ------
!!      V. Masson   *Meteo France*
!!
!!    MODIFICATIONS
!!    -------------
!!      Original    01/2003 
!!      P. Le Moigne 12/2004 : add type of photosynthesis
!!      R. Alkama    05/2012 : Add 7 new vegtypes (19 rather than 12)
!!      B. Decharme    05/13 : new param for equatorial forest
!-------------------------------------------------------------------------------
!
!*       0.    DECLARATIONS
!              ------------
!
!
!
!
!
USE MODD_DATA_ISBA_n, ONLY : DATA_ISBA_t
USE MODD_ISBA_OPTIONS_n, ONLY : ISBA_OPTIONS_t
USE MODD_ISBA_PGD_n, ONLY : ISBA_PGD_t
USE MODD_ISBA_INIT_n, ONLY : ISBA_INIT_PGD_t
USE MODD_TEB_GRID_n, ONLY : TEB_GRID_t
!
USE MODD_CSTS,              ONLY : XDAY
USE MODD_SURF_PAR,          ONLY : XUNDEF
USE MODD_ISBA_PAR,          ONLY : XOPTIMGRID, NOPTIMLAYER
USE MODD_DATA_COVER_PAR,    ONLY : NVT_NO, NVT_ROCK, NVT_SNOW, NVT_TEBD,     & 
                                     NVT_BONE, NVT_TRBE, NVT_C3, NVT_C4,     &
                                     NVT_IRR, NVT_GRAS, NVT_TROG,NVT_PARK,   &
                                     NVT_TRBD, NVT_TEBE, NVT_TENE, NVT_BOBD, &
                                     NVT_BOND, NVT_BOGR, NVT_SHRB, NVEGTYPE
!
USE MODI_READ_SURF
USE MODI_VEG_FROM_LAI
USE MODI_Z0V_FROM_LAI
USE MODI_EMIS_FROM_VEG
USE MODI_DRY_WET_SOIL_ALBEDOS
USE MODI_SOIL_ALBEDO
USE MODI_ABOR1_SFX
!
USE MODD_REPROD_OPER,    ONLY : XEVERG_RSMIN
!
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK
USE PARKIND1  ,ONLY : JPRB
!
IMPLICIT NONE
!
!*       0.1   Declarations of arguments
!              -------------------------
!
!
!
!
TYPE(DATA_ISBA_t), INTENT(INOUT) :: DTGD
TYPE(ISBA_OPTIONS_t), INTENT(INOUT) :: TGDO
TYPE(ISBA_PGD_t), INTENT(INOUT) :: TGDP
TYPE(ISBA_INIT_PGD_t), INTENT(INOUT) :: TGDIP
TYPE(TEB_GRID_t), INTENT(INOUT) :: TG
!
 CHARACTER(LEN=6),  INTENT(IN)  :: HPROGRAM ! program calling
!
!*       0.2   Declarations of local variables
!              -------------------------------
!
INTEGER                               :: IRESP          ! IRESP  : return-code if a problem appears
CHARACTER(LEN=12)                     :: YRECFM         ! Name of the article to be read
CHARACTER(LEN=100)                    :: YCOMMENT       ! Comment string
INTEGER                               :: JI, JLAYER     ! loop index
INTEGER                               :: JTIME          ! loop index
!
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_RSMIN
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_GAMMA
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_WRMAX_CF
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_RGL
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_CV
REAL, DIMENSION(TG%NDIM,TGDO%NGROUND_LAYER,3) :: ZDATA_DG
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_ALBNIR_VEG
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_ALBVIS_VEG
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_ALBUV_VEG
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_GMES
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_RE25
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_BSLAI
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_LAIMIN
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_SEFOLD
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_GC
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_DMAX
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_CE_NITRO
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_CF_NITRO
REAL, DIMENSION(TG%NDIM,3)               :: ZDATA_CNA_NITRO
!
REAL, DIMENSION(TG%NDIM,1)               :: ZDATA_WG1
REAL, DIMENSION(TG%NDIM)                 :: ZDATA_WGSAT
!
LOGICAL :: GAGRI_TO_GRASS
!
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
!-------------------------------------------------------------------------------
!
!*       1.    Reading of PGD file
!              --------------------
!
IF (LHOOK) CALL DR_HOOK('READ_PGD_TEB_GARDEN_PAR_N',0,ZHOOK_HANDLE)
DTGD%NTIME= 12
!
GAGRI_TO_GRASS=.FALSE.
!
YRECFM='GD_NTIME'
CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%NTIME,IRESP,HCOMMENT=YCOMMENT)
!
ALLOCATE(DTGD%XPAR_FRAC_HVEG (TG%NDIM))
ALLOCATE(DTGD%XPAR_FRAC_LVEG (TG%NDIM))
ALLOCATE(DTGD%XPAR_FRAC_NVEG (TG%NDIM))
ALLOCATE(DTGD%XPAR_LAI_HVEG  (TG%NDIM,DTGD%NTIME))
ALLOCATE(DTGD%XPAR_LAI_LVEG  (TG%NDIM,DTGD%NTIME))
ALLOCATE(DTGD%XPAR_H_HVEG    (TG%NDIM))
!
! Read type of high vegetation
YRECFM='D_TYPE_HVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,TGDO%CTYPE_HVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read type of low vegetation
YRECFM='D_TYPE_LVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,TGDO%CTYPE_LVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read type of bare soil (no vegetation)
YRECFM='D_TYPE_NVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,TGDO%CTYPE_NVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read fraction of high vegetation
YRECFM='D_FRAC_HVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%XPAR_FRAC_HVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read fraction of low vegetation
YRECFM='D_FRAC_LVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%XPAR_FRAC_LVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read fraction of bare soil (no vegetation)
YRECFM='D_FRAC_NVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%XPAR_FRAC_NVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read height of trees( for high vegetation)
YRECFM='D_H_HVEG'
 CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%XPAR_H_HVEG,IRESP,HCOMMENT=YCOMMENT)
!
! Read LAI of high vegetation
DO JTIME=1,DTGD%NTIME
  WRITE(YRECFM,FMT='(A10,I2.2)') 'D_LAI_HVEG',JTIME
  CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%XPAR_LAI_HVEG(:,JTIME),IRESP,HCOMMENT=YCOMMENT)
  WRITE(YRECFM,FMT='(A10,I2.2)') 'D_LAI_LVEG',JTIME
  CALL READ_SURF(&
               HPROGRAM,YRECFM,DTGD%XPAR_LAI_LVEG(:,JTIME),IRESP,HCOMMENT=YCOMMENT)
END DO
!
!-------------------------------------------------------------------------------
!
!*       2.    Definition of ISBA parameters
!              -----------------------------
!
ALLOCATE(DTGD%XPAR_LAI        (TG%NDIM,DTGD%NTIME,1))
ALLOCATE(DTGD%XPAR_VEG        (TG%NDIM,DTGD%NTIME,1))
ALLOCATE(DTGD%XPAR_RSMIN      (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_GAMMA      (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_WRMAX_CF   (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_RGL        (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_CV         (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_DG         (TG%NDIM,TGDO%NGROUND_LAYER,1))
ALLOCATE(DTGD%XPAR_ROOTFRAC   (TG%NDIM,TGDO%NGROUND_LAYER,1))
ALLOCATE(DTGD%XPAR_DICE       (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_Z0         (TG%NDIM,DTGD%NTIME,1))
ALLOCATE(DTGD%XPAR_Z0_O_Z0H   (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_ALBNIR_VEG (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_ALBVIS_VEG (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_ALBUV_VEG  (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_ALBNIR_SOIL(TG%NDIM,1))
ALLOCATE(DTGD%XPAR_ALBVIS_SOIL(TG%NDIM,1))
ALLOCATE(DTGD%XPAR_ALBUV_SOIL (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_EMIS       (TG%NDIM,DTGD%NTIME,1))
ALLOCATE(DTGD%XPAR_VEGTYPE    (TG%NDIM,NVEGTYPE))
ALLOCATE(DTGD%XPAR_GMES       (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_RE25       (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_BSLAI      (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_LAIMIN     (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_SEFOLD     (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_GC         (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_DMAX       (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_F2I        (TG%NDIM,1))
ALLOCATE(DTGD%LPAR_STRESS     (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_H_TREE     (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_CE_NITRO   (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_CF_NITRO   (TG%NDIM,1))
ALLOCATE(DTGD%XPAR_CNA_NITRO  (TG%NDIM,1))
!
DTGD%XPAR_LAI        (:,:,:) = XUNDEF
DTGD%XPAR_VEG        (:,:,:) = XUNDEF
DTGD%XPAR_RSMIN        (:,:) = XUNDEF
DTGD%XPAR_GAMMA        (:,:) = XUNDEF
DTGD%XPAR_WRMAX_CF     (:,:) = XUNDEF
DTGD%XPAR_RGL          (:,:) = XUNDEF
DTGD%XPAR_CV           (:,:) = XUNDEF
DTGD%XPAR_DG         (:,:,:) = XUNDEF
DTGD%XPAR_DICE       (:,:)   = XUNDEF
DTGD%XPAR_ROOTFRAC   (:,:,:) = XUNDEF
DTGD%XPAR_Z0         (:,:,:) = XUNDEF
DTGD%XPAR_Z0_O_Z0H     (:,:) = XUNDEF
DTGD%XPAR_ALBNIR_VEG   (:,:) = XUNDEF
DTGD%XPAR_ALBVIS_VEG   (:,:) = XUNDEF
DTGD%XPAR_ALBUV_VEG    (:,:) = XUNDEF
DTGD%XPAR_ALBNIR_SOIL  (:,:) = XUNDEF
DTGD%XPAR_ALBVIS_SOIL  (:,:) = XUNDEF
DTGD%XPAR_ALBUV_SOIL   (:,:) = XUNDEF
DTGD%XPAR_EMIS       (:,:,:) = XUNDEF
DTGD%XPAR_VEGTYPE    (:,:) = XUNDEF
DTGD%XPAR_GMES         (:,:) = XUNDEF
DTGD%XPAR_RE25         (:,:) = XUNDEF
DTGD%XPAR_BSLAI        (:,:) = XUNDEF
DTGD%XPAR_LAIMIN       (:,:) = XUNDEF
DTGD%XPAR_SEFOLD       (:,:) = XUNDEF
DTGD%XPAR_GC           (:,:) = XUNDEF
DTGD%XPAR_DMAX         (:,:) = XUNDEF
DTGD%XPAR_F2I          (:,:) = XUNDEF
DTGD%LPAR_STRESS       (:,:) = .FALSE.
DTGD%XPAR_H_TREE       (:,:) = XUNDEF
DTGD%XPAR_CE_NITRO     (:,:) = XUNDEF
DTGD%XPAR_CF_NITRO     (:,:) = XUNDEF
DTGD%XPAR_CNA_NITRO    (:,:) = XUNDEF
!
! Vegtypes
DTGD%XPAR_VEGTYPE(:,:) = 0.
IF (TGDO%CTYPE_NVEG == 'NO  ') DTGD%XPAR_VEGTYPE(:, NVT_NO  ) = DTGD%XPAR_FRAC_NVEG(:)
IF (TGDO%CTYPE_NVEG == 'ROCK') DTGD%XPAR_VEGTYPE(:, NVT_ROCK) = DTGD%XPAR_FRAC_NVEG(:)
IF (TGDO%CTYPE_NVEG == 'SNOW') DTGD%XPAR_VEGTYPE(:, NVT_SNOW) = DTGD%XPAR_FRAC_NVEG(:)
IF (TGDO%CTYPE_HVEG == 'TEBD') DTGD%XPAR_VEGTYPE(:, NVT_TEBD) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'TRBD') DTGD%XPAR_VEGTYPE(:, NVT_TRBD) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'TEBE') DTGD%XPAR_VEGTYPE(:, NVT_TEBE) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'BOBD') DTGD%XPAR_VEGTYPE(:, NVT_BOBD) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'SHRB') DTGD%XPAR_VEGTYPE(:, NVT_SHRB) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'BONE') DTGD%XPAR_VEGTYPE(:, NVT_BONE) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'TENE') DTGD%XPAR_VEGTYPE(:, NVT_TENE) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'BOND') DTGD%XPAR_VEGTYPE(:, NVT_BOND) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_HVEG == 'TRBE') DTGD%XPAR_VEGTYPE(:, NVT_TRBE) = DTGD%XPAR_FRAC_HVEG(:)
IF (TGDO%CTYPE_LVEG == 'C3  ') DTGD%XPAR_VEGTYPE(:, NVT_C3  ) = DTGD%XPAR_FRAC_LVEG(:)
IF (TGDO%CTYPE_LVEG == 'C4  ') DTGD%XPAR_VEGTYPE(:, NVT_C4  ) = DTGD%XPAR_FRAC_LVEG(:)
IF (TGDO%CTYPE_LVEG == 'IRR ') DTGD%XPAR_VEGTYPE(:, NVT_IRR ) = DTGD%XPAR_FRAC_LVEG(:)
IF (TGDO%CTYPE_LVEG == 'GRAS') DTGD%XPAR_VEGTYPE(:, NVT_GRAS) = DTGD%XPAR_FRAC_LVEG(:)
IF (TGDO%CTYPE_LVEG == 'BOGR') DTGD%XPAR_VEGTYPE(:, NVT_BOGR) = DTGD%XPAR_FRAC_LVEG(:)
IF (TGDO%CTYPE_LVEG == 'TROG') DTGD%XPAR_VEGTYPE(:, NVT_TROG) = DTGD%XPAR_FRAC_LVEG(:)
IF (TGDO%CTYPE_LVEG == 'PARK') DTGD%XPAR_VEGTYPE(:, NVT_PARK) = DTGD%XPAR_FRAC_LVEG(:)

!
! Dry/Wet soil albedo
ALLOCATE(TGDIP%XALBNIR_DRY (TG%NDIM))
ALLOCATE(TGDIP%XALBVIS_DRY (TG%NDIM))
ALLOCATE(TGDIP%XALBUV_DRY (TG%NDIM))
ALLOCATE(TGDIP%XALBNIR_WET (TG%NDIM))
ALLOCATE(TGDIP%XALBVIS_WET (TG%NDIM))
ALLOCATE(TGDIP%XALBUV_WET (TG%NDIM))
CALL DRY_WET_SOIL_ALBEDOS(TGDP%XSAND(:,1),TGDP%XCLAY(:,1),                             &
                          DTGD%XPAR_VEGTYPE,                                     &
                          TGDIP%XALBNIR_DRY,TGDIP%XALBVIS_DRY,TGDIP%XALBUV_DRY, &
                          TGDIP%XALBNIR_WET,TGDIP%XALBVIS_WET,TGDIP%XALBUV_WET  )  
!
! Height of trees
DTGD%XPAR_H_TREE  (:,1) = DTGD%XPAR_H_HVEG(:)
!
! Critical normilized soil water content for stress parameterisation
DTGD%XPAR_F2I     (:,1) = 0.3
!
! Ratio between roughness length for momentum and heat
DTGD%XPAR_Z0_O_Z0H(:,1) = 10.
!
! Defensive/offensive strategy (1/0)
DTGD%LPAR_STRESS  (:,1) = .FALSE. 
!
DO JI=1,TG%NDIM
!
! Near-IR, visible, and UV albedo (vegetation only)

 ZDATA_ALBNIR_VEG(JI,:)= 0.30
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.25
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.25
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.25
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.25
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.25
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BONE)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.15
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TENE)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.15
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOND)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.15
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBE)>0. )  ZDATA_ALBNIR_VEG(JI,1)= 0.21

 ZDATA_ALBVIS_VEG(JI,:)= 0.10
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BONE)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TENE)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOND)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBE)>0. )  ZDATA_ALBVIS_VEG(JI,1)= 0.05

 ZDATA_ALBUV_VEG (JI,:)= 0.06
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0525
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0525
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0525
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0525
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0525
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BONE)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0425
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TENE)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0425
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOND)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0425
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBE)>0. )  ZDATA_ALBUV_VEG(JI,1)= 0.0380 
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_GRAS)>0. )  ZDATA_ALBUV_VEG(JI,2)= 0.0800
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOGR)>0. )  ZDATA_ALBUV_VEG(JI,2)= 0.0800 
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TROG)>0. )  ZDATA_ALBUV_VEG(JI,2)= 0.1250
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_IRR )>0. )  ZDATA_ALBUV_VEG(JI,2)= 0.0450
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_PARK)>0. )  ZDATA_ALBUV_VEG(JI,2)= 0.0450

 IF (DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI) .GT. 0.) THEN
  DTGD%XPAR_ALBNIR_VEG(JI,1) =  ( ZDATA_ALBNIR_VEG(JI,1)*DTGD%XPAR_FRAC_HVEG(JI)   &
                            + ZDATA_ALBNIR_VEG(JI,2)*DTGD%XPAR_FRAC_LVEG(JI) ) &
                          / ( DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI)    )  
!
  DTGD%XPAR_ALBVIS_VEG(JI,1) =  ( ZDATA_ALBVIS_VEG(JI,1)*DTGD%XPAR_FRAC_HVEG(JI)   &
                            + ZDATA_ALBVIS_VEG(JI,2)*DTGD%XPAR_FRAC_LVEG(JI) ) &
                          / ( DTGD%XPAR_FRAC_HVEG(JI)+DTGD%XPAR_FRAC_LVEG(JI)    )  
! 
  DTGD%XPAR_ALBUV_VEG (JI,1) =  ( ZDATA_ALBUV_VEG (JI,1)*DTGD%XPAR_FRAC_HVEG(JI)   &
                            + ZDATA_ALBUV_VEG (JI,2)*DTGD%XPAR_FRAC_LVEG(JI) ) &
                          / ( DTGD%XPAR_FRAC_HVEG (JI)+DTGD%XPAR_FRAC_LVEG(JI)   )  
 ENDIF
!
! Soil albedo
 ZDATA_WGSAT(:) = 0.
 ZDATA_WG1  (:,:) = 0.
 CALL SOIL_ALBEDO('DRY',                                               &
                    ZDATA_WGSAT, ZDATA_WG1,                              &
                    TGDIP%XALBVIS_DRY, TGDIP%XALBNIR_DRY, TGDIP%XALBUV_DRY, &
                    TGDIP%XALBVIS_WET, TGDIP%XALBNIR_WET, TGDIP%XALBUV_WET, &
                    DTGD%XPAR_ALBVIS_SOIL,DTGD%XPAR_ALBNIR_SOIL,DTGD%XPAR_ALBUV_SOIL )  
!
! Min stomatal resistance
 ZDATA_RSMIN(JI,:)= 40.
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBD)>0. )  ZDATA_RSMIN(JI,1)= 150.
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TRBD)>0. )  ZDATA_RSMIN(JI,1)= 150.
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_TEBE)>0. )  ZDATA_RSMIN(JI,1)= 150.
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_BOBD)>0. )  ZDATA_RSMIN(JI,1)= 150.
 IF(DTGD%XPAR_VEGTYPE(JI,NVT_SHRB)>0. )  ZDATA_RSMIN(JI,1)= 150.
