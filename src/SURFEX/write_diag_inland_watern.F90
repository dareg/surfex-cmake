  CALL WRITE_DIAG_FLAKE_n(BOP, BDD, CHE, CHI, CHS, CHN, CHU, CHT, CHW, DTCO, DTS, &
                                DTT, DTZ, DGEI, DGI, DGMI, DGMTO, DGO, DGS, DGSI, DGT, DGUT, &
