!
SUBROUTINE PROVAR_TO_DIAG
!
REAL, DIMENSION(SIZE(IR%XTG,1))             :: ZPATCH, ZWORK
REAL, DIMENSION(SIZE(IR%XWG,1),SIZE(IR%XWG,2)) :: ZWG
REAL, DIMENSION(SIZE(IR%XWG,1),SIZE(IR%XWG,2)) :: ZWGI
REAL, DIMENSION(SIZE(IR%XTG,1),SIZE(IR%XTG,2)) :: ZTG
REAL, DIMENSION(SIZE(IMX%XDG,1),SIZE(IMX%XDG,2)) :: ZDG_TOT
REAL, DIMENSION(SIZE(IMX%XDG,1),SIZE(IMX%XDG,2),SIZE(IMX%XDG,3)) :: ZDG
!
REAL, DIMENSION(SIZE(IMX%XDG,1),IO%NNBIOMASS)   :: ZBIOMASS
REAL, DIMENSION(SIZE(IMX%XDG,1),IO%NNSOILCARB)  :: ZSOILCARB
REAL, DIMENSION(SIZE(IMX%XDG,1),IO%NNLITTLEVS)  :: ZLIGNIN_STRUC
REAL, DIMENSION(SIZE(IMX%XDG,1),IO%NNLITTER,IO%NNLITTLEVS)  :: ZLITTER
!
CHARACTER(LEN=4 ) :: YLVL
REAL              :: ZMISS
INTEGER           :: JLAYER, JPATCH, JJ, INI, IWORK, IDEPTH
!
REAL(KIND=JPRB) :: ZHOOK_HANDLE
!
IF (LHOOK) CALL DR_HOOK('WRITE_DIAG_SEB_ISBA_N:PROVAR_TO_DIAG',0,ZHOOK_HANDLE)
!
INI=SIZE(IMX%XDG,1)
!
! * soil temperatures (K)
!
IF(IO%LTEMP_ARP)THEN
  IWORK=IO%NTEMPLAYER_ARP
ELSEIF(IO%CISBA/='DIF')THEN
  IWORK=2
ELSE
  IWORK=IO%NGROUND_LAYER
ENDIF
!
ZTG(:,:)=0.0
DO JPATCH=1,IO%NPATCH
   DO JLAYER=1,IWORK
      DO JJ=1,INI 
         ZTG(JJ,JLAYER) = ZTG(JJ,JLAYER) + IP%XPATCH(JJ,JPATCH) * IR%XTG(JJ,JLAYER,JPATCH)
      ENDDO
   ENDDO
ENDDO
!
DO JLAYER=1,IWORK
  WRITE(YLVL,'(I4)') JLAYER
  YRECFM='TG'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
  YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (K)'
  CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZTG(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)
END DO
!
! * Compute soil liquid and ice water content (kg/m2 and m3/m3) 
!
ZWG (:,:)=0.0
ZWGI(:,:)=0.0
ZDG_TOT(:,:)=0.0
!  
IF(IO%CISBA=='DIF')THEN
  !
  DO JPATCH=1,IO%NPATCH
     DO JLAYER=1,IO%NGROUND_LAYER
        DO JJ=1,INI 
!
!          liquid and ice water content
           IDEPTH=IMX%NWG_LAYER(JJ,JPATCH)
           IF(JLAYER<=IDEPTH)THEN    
             ZWG    (JJ,JLAYER)=ZWG    (JJ,JLAYER)+&
                     IP%XPATCH(JJ,JPATCH)*IR%XWG (JJ,JLAYER,JPATCH)*IP%XDZG(JJ,JLAYER,JPATCH)
             ZWGI   (JJ,JLAYER)=ZWGI   (JJ,JLAYER)+&
                     IP%XPATCH(JJ,JPATCH)*IR%XWGI(JJ,JLAYER,JPATCH)*IP%XDZG(JJ,JLAYER,JPATCH)
             ZDG_TOT(JJ,JLAYER)=ZDG_TOT(JJ,JLAYER)+&
                     IP%XPATCH(JJ,JPATCH)*IP%XDZG(JJ,JLAYER,JPATCH)
           ENDIF
!                      
        ENDDO
     ENDDO
  ENDDO
!  
ELSE
  !
  ZDG(:,1,:) = IMX%XDG(:,1,:)
  ZDG(:,2,:) = IMX%XDG(:,2,:)
  IF(IO%CISBA=='3-L')THEN
    ZDG(:,3,:) = IMX%XDG(:,3,:)-IMX%XDG(:,2,:)
  ENDIF
!
  DO JPATCH=1,IO%NPATCH
     DO JLAYER=1,IO%NGROUND_LAYER
        DO JJ=1,INI 
           ZWG    (JJ,JLAYER)=ZWG    (JJ,JLAYER)+&
                   IP%XPATCH(JJ,JPATCH)*IR%XWG (JJ,JLAYER,JPATCH)*ZDG(JJ,JLAYER,JPATCH)
           ZWGI   (JJ,JLAYER)=ZWGI   (JJ,JLAYER)+&
                   IP%XPATCH(JJ,JPATCH)*IR%XWGI(JJ,JLAYER,JPATCH)*ZDG(JJ,JLAYER,JPATCH)
           ZDG_TOT(JJ,JLAYER)=ZDG_TOT(JJ,JLAYER)+&
                   IP%XPATCH(JJ,JPATCH)*ZDG(JJ,JLAYER,JPATCH)
        ENDDO
     ENDDO
  ENDDO
!  
ENDIF
!
IF(HPROGRAM=='AROME '.OR.HPROGRAM=='FA    ')THEN
  ZMISS=0.0
ELSE
  ZMISS=XUNDEF
ENDIF
!
WHERE(ZDG_TOT(:,:)>0.0)
      ZWG   (:,:)=ZWG (:,:)/ZDG_TOT(:,:)
      ZWGI  (:,:)=ZWGI(:,:)/ZDG_TOT(:,:)
ELSEWHERE
      ZWG   (:,:)=ZMISS
      ZWGI  (:,:)=ZMISS    
ENDWHERE
!
! * soil liquid water content (m3/m3) and soil moisture (kg/m2)
!
DO JLAYER=1,IO%NGROUND_LAYER
  WRITE(YLVL,'(I4)') JLAYER
  YRECFM='WG'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
  YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
  YCOMMENT='Soil liquid water content (m3/m3)' 
  CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWG(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)
END DO
!
! * soil ice water content (m3/m3) and soil ice mass (kg/m2)
!
IWORK=IO%NGROUND_LAYER
IF(IO%CISBA/='DIF')THEN
  IWORK=2 ! No ice in the FR 3-layers
ENDIF
!
DO JLAYER=1,IWORK
  WRITE(YLVL,'(I4)') JLAYER
  YRECFM='WGI'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
  YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
  YCOMMENT='Soil solid water content (m3/m3)' 
  CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWGI(:,JLAYER),IRESP,HCOMMENT=YCOMMENT) 
END DO   
!
! * water intercepted on leaves (kg/m2)
!
ZWORK(:)=0.0
DO JPATCH=1,IO%NPATCH
   DO JJ=1,INI 
      ZWORK(JJ) = ZWORK(JJ) + IP%XPATCH(JJ,JPATCH) * IR%XWR(JJ,JPATCH)
   ENDDO
ENDDO
!
YRECFM='WR_ISBA'
YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
!
! * Glacier ice storage (semi-prognostic) (kg/m2)
!
IF(IO%LGLACIER)THEN
  !
  ZWORK(:)=0.0
  DO JPATCH=1,IO%NPATCH
    DO JJ=1,INI 
       ZWORK(JJ) = ZWORK(JJ) + IP%XPATCH(JJ,JPATCH) * IR%XICE_STO(JJ,JPATCH)
    ENDDO    
  ENDDO    
  !
  YRECFM='ICE_STO_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
  CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
  !
ENDIF
!
! * Snow albedo (-) 
!
ZPATCH(:) = 0.0
ZWORK (:) = 0.0
DO JPATCH=1,IO%NPATCH
   DO JJ=1,INI 
      IF(IR%TSNOW%ALB(JJ,JPATCH)/=XUNDEF)THEN
        ZWORK (JJ) = ZWORK (JJ) + IP%XPATCH(JJ,JPATCH) * IR%TSNOW%ALB(JJ,JPATCH)
        ZPATCH(JJ) = ZPATCH(JJ) + IP%XPATCH(JJ,JPATCH)
      ENDIF
   ENDDO
ENDDO
!
WHERE(ZPATCH(:)>0.0)
  ZWORK(:) = ZWORK(:) / ZPATCH(:)
ELSEWHERE
  ZWORK(:) = XUNDEF
ENDWHERE
!
YRECFM='ASN_ISBA'
YCOMMENT='X_Y_'//YRECFM//' (-)'
CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
!  
IF(IR%TSNOW%SCHEME=='3-L' .OR. IR%TSNOW%SCHEME=='CRO')THEN
  !
  ! * Snow reservoir (kg/m2) by layer
  !
  DO JLAYER = 1,IR%TSNOW%NLAYER
    !
    ZWORK(:)=0.0
    DO JPATCH=1,IO%NPATCH
       DO JJ=1,INI 
          ZWORK(JJ) = ZWORK(JJ) + IP%XPATCH(JJ,JPATCH) * IR%TSNOW%WSNOW(JJ,JLAYER,JPATCH)
       ENDDO
    ENDDO
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='WSN_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
    CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
  ! * Snow depth (m)
  !
  DO JLAYER = 1,IR%TSNOW%NLAYER
    !
    ZWORK(:)=0.0
    DO JPATCH=1,IO%NPATCH
       DO JJ=1,INI 
         ZWORK(JJ) = ZWORK(JJ) + &
                 IP%XPATCH(JJ,JPATCH) * IR%TSNOW%WSNOW(JJ,JLAYER,JPATCH)/IR%TSNOW%RHO(JJ,JLAYER,JPATCH)
       ENDDO
    ENDDO
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='DSN_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
    CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
  ! * Snow temperature (k)
  !  
  IF(HPROGRAM=='AROME '.OR.HPROGRAM=='FA    ')THEN
    ZMISS=XTT
  ELSE
    ZMISS=XUNDEF
  ENDIF
  !  
  DO JLAYER = 1,IR%TSNOW%NLAYER
    !
    ZWORK (:) = 0.0
    ZPATCH(:) = 0.0
    DO JPATCH=1,IO%NPATCH
       DO JJ=1,INI 
          IF(IR%TSNOW%WSNOW(JJ,JLAYER,JPATCH)>0.)THEN
             ZWORK (JJ) = ZWORK (JJ) + IP%XPATCH(JJ,JPATCH) * IR%TSNOW%TEMP(JJ,JLAYER,JPATCH) 
             ZPATCH(JJ) = ZPATCH(JJ) + IP%XPATCH(JJ,JPATCH)
          ENDIF
       ENDDO
    ENDDO
    !
    WHERE(ZPATCH(:)>0.0)
      ZWORK(:) = ZWORK(:) / ZPATCH(:)
    ELSEWHERE
      ZWORK(:) = ZMISS
    ENDWHERE
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='TSN_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (K)'
    CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
  ! * Snow age (day)
  !    
  DO JLAYER = 1,IR%TSNOW%NLAYER
    !
    ZWORK (:) = 0.0
    ZPATCH(:) = 0.0
    DO JPATCH=1,IO%NPATCH
       DO JJ=1,INI 
          IF(IR%TSNOW%WSNOW(JJ,JLAYER,JPATCH)>0.)THEN    
             ZWORK (JJ) = ZWORK (JJ) + IP%XPATCH(JJ,JPATCH) * IR%TSNOW%AGE(JJ,JLAYER,JPATCH) 
             ZPATCH(JJ) = ZPATCH(JJ) + IP%XPATCH(JJ,JPATCH)
          ENDIF
       ENDDO
    ENDDO
    !
    WHERE(ZPATCH(:)>0.0)
      ZWORK(:) = ZWORK(:) / ZPATCH(:)
    ENDWHERE
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='AGSN_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (day_since_snowfall)'
    CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
ENDIF
!
! * Isba-Ags biomass reservoir
!
IF(IO%CPHOTO=='NIT'.OR.IO%CPHOTO=='NCB')THEN
!
  ZBIOMASS(:,:)=0.0
  DO JPATCH=1,IO%NPATCH
     DO JLAYER=1,IO%NNBIOMASS
        DO JJ=1,INI 
         ZBIOMASS(JJ,JLAYER) = ZBIOMASS(JJ,JLAYER) + IP%XPATCH(JJ,JPATCH) * IR%XBIOMASS(JJ,JLAYER,JPATCH)
        ENDDO
     ENDDO
  ENDDO
!
  DO JLAYER = 1,IO%NNBIOMASS
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='BIOM'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (kgDM/m2)'
    CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZBIOMASS(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)  
  ENDDO
!
ENDIF
!
! * Isba-CC carbon reservoir
!
IF(IO%CRESPSL=='CNT')THEN
!
  ZLITTER(:,:,:)=0.0
  ZLIGNIN_STRUC(:,:)=0.0
  DO JPATCH=1,IO%NPATCH
     DO JLAYER=1,IO%NNLITTLEVS
       DO JJ=1,INI 
          ZLITTER(JJ,1,JLAYER) = ZLITTER(JJ,1,JLAYER) + &
                  IP%XPATCH(JJ,JPATCH) * IR%XLITTER(JJ,1,JLAYER,JPATCH)
          ZLITTER(JJ,2,JLAYER) = ZLITTER(JJ,2,JLAYER) + &
                  IP%XPATCH(JJ,JPATCH) * IR%XLITTER(JJ,2,JLAYER,JPATCH)
          ZLIGNIN_STRUC(JJ,JLAYER) = ZLIGNIN_STRUC(JJ,JLAYER) + &
                  IP%XPATCH(JJ,JPATCH) * IR%XLIGNIN_STRUC(JJ,JLAYER,JPATCH)
       ENDDO
    ENDDO
  ENDDO
!       
  DO JLAYER=1,IO%NNLITTLEVS
     WRITE(YLVL,'(I4)') JLAYER
     YRECFM='LIT1_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
     YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
     YCOMMENT='X_Y_'//YRECFM//' (gC/m2)'
     CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZLITTER(:,1,JLAYER),IRESP,HCOMMENT=YCOMMENT)  
     WRITE(YLVL,'(I4)') JLAYER
     YRECFM='LIT2_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
     YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
     YCOMMENT='X_Y_'//YRECFM//' (gC/m2)'
     CALL WRITE_SURF(DUO%CSELECT, &
                  HPROGRAM,YRECFM,ZLITTER(:,2,JLAYER),IRESP,HCOMMENT=YCOMMENT)
     WRITE(YLVL,'(I4)') JLAYER
     YRECFM='LIGSTR'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
     YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
     YCOMMENT='X_Y_'//YRECFM//' (-)'
     CALL WRITE_SURF(DUO%CSELECT,HPROGRAM,YRECFM,ZLIGNIN_STRUC(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)      
  END DO
!
  ZSOILCARB(:,:)=0.0
  DO JPATCH=1,IO%NPATCH
     DO JLAYER=1,IO%NNSOILCARB
       DO JJ=1,INI 
          ZSOILCARB(JJ,JLAYER) = ZSOILCARB(JJ,JLAYER) + IP%XPATCH(JJ,JPATCH) * IR%XSOILCARB(JJ,JLAYER,JPATCH)
       ENDDO
    ENDDO
  ENDDO
!
  DO JLAYER = 1,IO%NNSOILCARB
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='SCARB'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (gC/m2)'
    CALL WRITE_SURF(DUO%CSELECT, HPROGRAM,YRECFM,ZSOILCARB(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)  
  ENDDO
!
ENDIF
!
IF (LHOOK) CALL DR_HOOK('WRITE_DIAG_SEB_ISBA_N:PROVAR_TO_DIAG',1,ZHOOK_HANDLE)
!
END SUBROUTINE PROVAR_TO_DIAG
!
END SUBROUTINE WRITE_DIAG_SEB_ISBA_n
