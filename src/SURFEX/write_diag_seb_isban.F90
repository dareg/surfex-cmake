  !
  YRECFM='H_C_A'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (W/m2)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XH_C_A(:),ISIZE)
  ENDDO
  !
  YRECFM='H_N_C'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (W/m2)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XH_N_C(:),ISIZE)
  ENDDO
  !
  YRECFM='SR_GN'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XSR_GN(:),ISIZE)
  ENDDO
  !
  YRECFM='MELTCV'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XMELTCV(:),ISIZE)
  ENDDO
  !
  YRECFM='FRZCV'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XFRZCV(:),ISIZE)
  ENDDO

ENDIF
! END MEB STUFF
!
IF(LAGRIP)THEN
  YRECFM='IRRIG'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (Kg/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XIRRIG_FLUX(:),ISIZE)
  ENDDO
ENDIF
!
IF(IO%LFLOOD)THEN
  !
  YRECFM='IFLOOD'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (Kg/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XIFLOOD(:),ISIZE)
  ENDDO
  !
  YRECFM='PFLOOD'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (Kg/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XPFLOOD(:),ISIZE)
  ENDDO
  !

  YRECFM='LEF'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (W/m2)'
  DO JP=1,IO%NPATCH
  CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XLE_FLOOD(:),ISIZE)
ENDDO
  !

  YRECFM='LEIF'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (W/m2)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XLEI_FLOOD(:),ISIZE)
  ENDDO
  !
ENDIF
!
IF(IO%CPHOTO/='NON')THEN
  !
 
  YRECFM='GPP'//TRIM(HTERM)
  YCOMMENT='gross primary production per patch (kgCO2/m2/s)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XGPP(:),ISIZE)
  ENDDO
  !
  IF (HTERM(1:1)=="C") THEN
    YRECFM='RC_AUTO'//TRIM(HTERM(2:))
  ELSE
    YRECFM='R_AUTO'//TRIM(HTERM)
