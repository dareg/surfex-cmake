    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XH_V_C(:),ISIZE)
  ENDDO
  !
  YRECFM='H_G_C'//TRIM(HTERM)
  YCOMMENT='X_Y_'//YRECFM//' (W/m2)'
  DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XH_G_C(:),ISIZE)
