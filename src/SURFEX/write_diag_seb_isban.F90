  YCOMMENT='autotrophic respiration per patch (kgCO2/m2/s)'
    DO JP=1,IO%NPATCH
    CALL WRITE_FIELD_1D_PATCH(DUO%CSELECT,HPROGRAM,YRECFM,YCOMMENT,JP,&
        NP%AL(JP)%NR_P,DEPA%AL(JP)%XRESP_AUTO(:),ISIZE)
