  YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (K)'
  CALL WRITE_SURF(HPROGRAM,YRECFM,ZTG(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)
END DO
!
! * Compute soil liquid and ice water content (kg/m2) 
!
ZWG (:,:)=0.0
ZWGI(:,:)=0.0
!  
IF(CISBA=='DIF')THEN
!        
  IWORK = MAXVAL(NWG_LAYER(:,:),NWG_LAYER(:,:)/=NUNDEF)
!
  DO JPATCH=1,NPATCH
     DO JLAYER=1,NGROUND_LAYER
        DO JJ=1,INI 
!
!          liquid water content
           IDEPTH=NWG_LAYER(JJ,JPATCH)
           IF(JLAYER<=IDEPTH)THEN        
             ZWG (JJ,JLAYER)=ZWG (JJ,JLAYER)+XPATCH(JJ,JPATCH)*XWG (JJ,JLAYER,JPATCH)*XDZG(JJ,JLAYER,JPATCH)*XRHOLW
           ELSE
             ZWG (JJ,JLAYER)=XUNDEF
           ENDIF
!           
!          ice water content
           ZWGI(JJ,JLAYER)=ZWGI(JJ,JLAYER)+XPATCH(JJ,JPATCH)*XWGI(JJ,JLAYER,JPATCH)*XDZG(JJ,JLAYER,JPATCH)*XRHOLW
!           
        ENDDO
     ENDDO
  ENDDO
!  
ELSE
!        
  IWORK = NGROUND_LAYER
!  
  ZDG(:,1,:) = XDG(:,1,:)
  ZDG(:,2,:) = XDG(:,2,:)
  IF(CISBA=='3-L')THEN
    IWORK = NGROUND_LAYER
    ZDG(:,3,:) = XDG(:,3,:)-XDG(:,2,:)
  ENDIF
!
  DO JPATCH=1,NPATCH
     DO JLAYER=1,NGROUND_LAYER
        DO JJ=1,INI 
           ZWG (JJ,JLAYER)=ZWG (JJ,JLAYER)+XPATCH(JJ,JPATCH)* XWG (JJ,JLAYER,JPATCH)*ZDG(JJ,JLAYER,JPATCH)*XRHOLW
           ZWGI(JJ,JLAYER)=ZWGI(JJ,JLAYER)+XPATCH(JJ,JPATCH)* XWGI(JJ,JLAYER,JPATCH)*ZDG(JJ,JLAYER,JPATCH)*XRHOLW
        ENDDO
     ENDDO
  ENDDO
!  
ENDIF
!
! * soil liquid water content (kg/m2)
!
DO JLAYER=1,IWORK
  WRITE(YLVL,'(I4)') JLAYER
  YRECFM='WG'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
  YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
  CALL WRITE_SURF(HPROGRAM,YRECFM,ZWG(:,JLAYER),IRESP,HCOMMENT=YCOMMENT)
END DO
!
! * soil ice water content (kg/m2)
!
IWORK=NGROUND_LAYER
IF(CISBA/='DIF')THEN
  IWORK=NGROUND_LAYER-1 ! No ice in the FR 3-layers
ENDIF
!
DO JLAYER=1,IWORK
  WRITE(YLVL,'(I4)') JLAYER
  YRECFM='WGI'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
  YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
  CALL WRITE_SURF(HPROGRAM,YRECFM,ZWGI(:,JLAYER),IRESP,HCOMMENT=YCOMMENT) 
END DO   
!
! * water intercepted on leaves (kg/m2)
!
ZWORK(:)=0.0
DO JPATCH=1,NPATCH
  ZWORK(:) = ZWORK(:) + XPATCH(:,JPATCH) * XWR(:,JPATCH)
ENDDO
!
YRECFM='WR_ISBA'
YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
!
! * Glacier ice storage (semi-prognostic) (kg/m2)
!
IF(LGLACIER)THEN
  !
  ZWORK(:)=0.0
  DO JPATCH=1,NPATCH
    ZWORK(:) = ZWORK(:) + XPATCH(:,JPATCH) * XICE_STO(:,JPATCH)
  ENDDO    
  !
  YRECFM='ICE_STO_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
  CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
  !
ENDIF
!
! * Snow albedo (-) 
!
ZPATCH(:) = 0.0
ZWORK (:) = 0.0
DO JPATCH=1,NPATCH
  WHERE(TSNOW%ALB(:,JPATCH)/=XUNDEF)
    ZWORK (:) = ZWORK(:)  + XPATCH(:,JPATCH) * TSNOW%ALB(:,JPATCH)
    ZPATCH(:) = ZPATCH(:) + XPATCH(:,JPATCH)
  ENDWHERE
ENDDO
!
WHERE(ZPATCH(:)>0.0)
  ZWORK(:) = ZWORK(:) / ZPATCH(:)
ELSEWHERE
  ZWORK(:) = XUNDEF
ENDWHERE
!
YRECFM='ASNOW_ISBA'
YCOMMENT='X_Y_'//YRECFM//' (-)'
CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
!  
IF(TSNOW%SCHEME=='3-L' .OR. TSNOW%SCHEME=='CRO')THEN
  !
  ! * Snow reservoir (kg/m2) by layer
  !
  DO JLAYER = 1,TSNOW%NLAYER
    !
    ZWORK(:)=0.0
    DO JPATCH=1,NPATCH
      ZWORK(:) = ZWORK(:) + XPATCH(:,JPATCH) * TSNOW%WSNOW(:,JLAYER,JPATCH)
    ENDDO
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='WSNOW_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
    CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
  ! * Snow depth (m)
  !
  DO JLAYER = 1,TSNOW%NLAYER
    !
    ZWORK(:)=0.0
    DO JPATCH=1,NPATCH
      ZWORK(:) = ZWORK(:) + XPATCH(:,JPATCH) * TSNOW%WSNOW(:,JLAYER,JPATCH)/TSNOW%RHO(:,JLAYER,JPATCH)
    ENDDO
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='DSNOW_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (kg/m2)'
    CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
  ! * Snow temperature (k)
  !    
  DO JLAYER = 1,TSNOW%NLAYER
    !
    ZWORK (:) = 0.0
    ZPATCH(:) = 0.0
    DO JPATCH=1,NPATCH
      WHERE(TSNOW%WSNOW(:,JLAYER,JPATCH)>0.)
        ZWORK (:) = ZWORK (:) + XPATCH(:,JPATCH) * TSNOW%TEMP(:,JLAYER,JPATCH) 
        ZPATCH(:) = ZPATCH(:) + XPATCH(:,JPATCH)
      ENDWHERE
    ENDDO
    !
    WHERE(ZPATCH(:)>0.0)
      ZWORK(:) = ZWORK(:) / ZPATCH(:)
    ELSEWHERE
      ZWORK(:) = XUNDEF
    ENDWHERE
    !
    WRITE(YLVL,'(I4)') JLAYER
    YRECFM='TSNOW_'//ADJUSTL(YLVL(:LEN_TRIM(YLVL)))
    YRECFM=YRECFM(:LEN_TRIM(YRECFM))//'_ISBA'
    YCOMMENT='X_Y_'//YRECFM//' (K)'
    CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
    !
  ENDDO
  !
ENDIF
!
! * Leaf Area Index
!
IF(CPHOTO/='NON'.AND.CPHOTO/='AGS'.AND.CPHOTO/='AST')THEN
  !            
  ZWORK(:) = 0.0
  ZPATCH(:) = 0.0
  DO JPATCH=1,NPATCH
    WHERE(XLAI(:,JPATCH)/=XUNDEF)
      ZWORK (:) = ZWORK (:) + XPATCH(:,JPATCH) * XLAI(:,JPATCH)
      ZPATCH(:) = ZPATCH(:) + XPATCH(:,JPATCH)
    ENDWHERE
  ENDDO
  !
  WHERE(ZPATCH(:)>0.0)
    ZWORK(:) = ZWORK(:) / ZPATCH(:)
  ELSEWHERE
    ZWORK(:) = XUNDEF
  ENDWHERE
  !  
  YRECFM='LAI_ISBA'
  YCOMMENT='X_Y_'//YRECFM//' (m2/m2)'
  CALL WRITE_SURF(HPROGRAM,YRECFM,ZWORK(:),IRESP,HCOMMENT=YCOMMENT)
  !
ENDIF  
!
IF (LHOOK) CALL DR_HOOK('WRITE_DIAG_SEB_ISBA_N:PROVAR_TO_DIAG',1,ZHOOK_HANDLE)
!
END SUBROUTINE PROVAR_TO_DIAG
!
END SUBROUTINE WRITE_DIAG_SEB_ISBA_n
